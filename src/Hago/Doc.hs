{-# LANGUAGE LambdaCase #-}

-- | hago doc: a reference of the standard library in Markdown, one file per
-- module and an index. What a module exports, and the type of each name,
-- come from the type checker, so they are exact. The text comes from the
-- comments in the source, which the lexer drops, so they are read from the
-- source text: the block of comment lines right above a declaration (or its
-- signature) is its documentation, the block at the top of a file is the
-- module's, and a comment line that ends in dashes (@-- Building -----@)
-- starts a section.
module Hago.Doc (documentLibrary) where

import Data.Char (isAlphaNum, isSpace)
import Data.List (dropWhileEnd, intercalate, isPrefixOf, nub, sortOn)
import qualified Data.Map as M
import Data.Maybe (fromMaybe)
import Hago.Cache (Iface (..))
import Hago.Core (ClassInfo (..), ConInfo (..), DataInfo (..), Pred (..), Scheme (..))
import Hago.Lexer (Tok (..), Token (..), lexer)
import Hago.Rename (Renamed (..), Table (..), moduleQualify)
import Hago.Syntax
import Hago.TcMonad (InstHead (..), Record (..), pretty, prettyAtom)
import Hago.Typecheck (Checked (..))

-- | A module of the library: its name, file, source, and what compiling it
-- gave.
type Unit = (Name, FilePath, String, Iface)

-- | The files of the reference, by name: the index, README.md, and one per
-- module.
documentLibrary :: [Unit] -> [(FilePath, String)]
documentLibrary units =
  ("README.md", index ordered) : [(n ++ ".md", moduleDoc allChecked origins u) | u@(n, _, _, _) <- ordered]
  where
    allChecked = mconcat [ifChecked i | (_, _, _, i) <- units]
    origins = M.fromList [(k, n) | (n, _, _, i) <- units, k <- M.keys (ckInsts (ifChecked i))]
    ordered = sortOn (\(n, _, _, _) -> (n /= "Prelude", n)) units

-- The index -------------------------------------------------------------------

index :: [Unit] -> String
index units = unlines $
  [ "# The standard library"
  , ""
  , "The Prelude, which every module imports unless it says otherwise, and the modules that come"
  , "with the compiler. Generated by `hago doc` from their sources (`prelude/Prelude.hgo` and"
  , "`lib/`): the names and types are the type checker's, and the text is the comments written"
  , "above each declaration. Do not edit these files; edit the sources and run `hago doc`."
  , ""
  , "| Module | |"
  , "| --- | --- |" ]
    ++ [ "| [" ++ n ++ "](" ++ n ++ ".md) | " ++ escapeCell (firstSentence (header src)) ++ " |"
       | (n, _, src, _) <- units ]
  where
    escapeCell = concatMap (\c -> if c == '|' then "\\|" else [c])

-- | The first sentence of a comment, on one line.
firstSentence :: [String] -> String
firstSentence ls = go (unwords (words (unwords (takeWhile (not . null) ls))))
  where
    go s = case s of
      '.' : rest | null rest || take 1 rest == " " -> "."
      c : rest -> c : go rest
      [] -> []

-- A module ----------------------------------------------------------------------

-- | A module's page, given every module's checked declarations and the
-- module each instance is defined in.
moduleDoc :: Checked -> M.Map (Name, Name) Name -> Unit -> String
moduleDoc allChecked origins (name, path, src, iface) =
  unlines . collapse . concat $
    [ ["# " ++ name, ""]
    , paragraph (header src)
    , ["Its source is [`" ++ path ++ "`](../../" ++ path ++ ")."] ++ [""]
    , body
    , reexports
    , builtinInstances
    ]
  where
    table = M.findWithDefault (Table M.empty M.empty M.empty) name (rnExports (ifRenamed iface))
    own internal surface = moduleQualify name surface == internal
    -- exported names this module defines, by surface name
    ownVals = M.filterWithKey (flip own) (tVals table)
    ownTypes = M.filterWithKey (flip own) (tTypes table)
    -- constructors and methods are documented with their type or class
    isChild i = M.member i (ckCons allChecked) || M.member i methodNames
    methodNames = M.fromList [(m, ()) | ci <- M.elems (ckClasses allChecked), (m, _) <- clsMethods ci]
    exported i = M.lookup (unqual i) (tVals table) == Just i
    pieces = sourcePieces src
    -- every name a declaration of the source documents, where it is first declared
    placed = M.fromListWith (\_ a -> a) [(n, ()) | Decl g <- pieces, n <- gNames g]
    entries = map pieceEntry pieces
    pieceEntry = \case
      Heading t -> Left t
      Decl g -> Right (entriesOf g)
    entriesOf g = case gKind g of
      KType -> [typeEntry g n i | n <- gNames g, Just i <- [M.lookup n ownTypes], not (isClass i)]
      KClass -> [classEntry g n i | n <- gNames g, Just i <- [M.lookup n ownTypes], isClass i]
      KValue -> [valueEntry (gDoc g) n i | n <- gNames g, Just i <- [M.lookup n ownVals], not (isChild i)]
      KOther -> []
    -- names exported but declared where the source scan does not see them
    unplaced =
      [valueEntry [] n i | (n, i) <- M.toList ownVals, not (M.member n placed), not (isChild i)]
    body = render (entries ++ [Left "Other definitions" | not (null unplaced)] ++ [Right unplaced])

    isClass i = M.member i (ckClasses allChecked)

    valueEntry doc n i = Entry True doc (fixity i ++ [operator n ++ " :: " ++ maybe "?" scheme (M.lookup i (ckVars allChecked))]) []

    fixity i = [assoc a ++ " " ++ show p ++ " " ++ unqual i | (n, (a, p)) <- ifFixities iface, n == i]
    assoc = \case
      AssocL -> "infixl"
      AssocR -> "infixr"
      AssocN -> "infix"

    typeEntry g n i = Entry False (gDoc g) code []
      where
        code = case (M.lookup i (ckData allChecked), M.lookup i (ifSynonyms iface)) of
          (_, Just (ps, t)) -> [unwords ("type" : n : ps) ++ " = " ++ stype t]
          (Just d, _) -> declaration d ++ instancesOf i
          _ -> ["data " ++ n]
        declaration d = case diForeign d of
          Just sym -> [unwords (["foreign import go type", show sym, n] ++ diParams d)]
          Nothing ->
            let keyword = if diNewtype d then "newtype" else "data"
                lhs = unwords (keyword : n : diParams d)
                cons = [constructor i k | k <- diCons d, exported k]
             in case cons of
                  [] -> [lhs]
                  _ | length (lhs ++ concat cons) + 3 * length cons <= 90 -> [lhs ++ " = " ++ intercalate " | " cons]
                  c : cs -> lhs : ("  = " ++ c) : map ("  | " ++) cs
    constructor ty k = case M.lookup k (ckCons allChecked) of
      Nothing -> unqual k
      Just ci ->
        let labels = case M.lookup ty (ckRecords allChecked) of
              Just r -> sortOn snd [(l, j) | (l, (_, _, ks)) <- M.toList (recFields r), (k', j) <- ks, k' == k]
              Nothing -> []
            field (lz, t) = (if lz then "~" else "") ++ prettyAtom t
            fields = ciFields ci
         in case () of
              _ | not (null labels), length labels == length fields ->
                    unqual k ++ " { " ++ intercalate ", " [l ++ " :: " ++ (if lz then "~" else "") ++ pretty t | ((l, _), (lz, t)) <- zip labels fields] ++ " }"
                | isOperator (unqual k), [a, b] <- fields -> field a ++ " " ++ unqual k ++ " " ++ field b
                | otherwise -> unwords (operator (unqual k) : map field fields)

    classEntry g n i = Entry False (gDoc g) code after
      where
        ci = ckClasses allChecked M.! i
        supers = [p | p <- clsSupers ci]
        dependency = case clsVars ci of
          vs@(_ : _ : _) | (key, _ : _) <- (vs !! clsKey ci, [v | v <- vs, v /= vs !! clsKey ci]) ->
            " | " ++ key ++ " -> " ++ unwords [v | v <- vs, v /= key]
          _ -> ""
        headLine = "class " ++ context supers ++ unwords (n : clsVars ci) ++ dependency ++ (if null methods then "" else " where")
        methods = [(unqual m, sc) | (m, sc) <- clsMethods ci, exported m]
        code = headLine : concat [map ("  " ++) (map ("-- " ++) (M.findWithDefault [] m (gMethodDocs g)) ++ [operator m ++ " :: " ++ method sc]) | (m, sc) <- methods]

        method (Forall _ ps t) = context (drop 1 ps) ++ pretty t
        defaults = [operator (unqual m) | m <- clsDefaults ci, exported m]
        after = ["Methods with a default definition: " ++ intercalate ", " (map (\m -> "`" ++ m ++ "`") defaults) ++ "." | not (null defaults)]

    -- instances of a type of the library, wherever they are defined
    instancesOf i = case [(key, ih) | (key@(_, k), ih) <- M.toList (ckInsts allChecked), k == i] of
      [] -> []
      ihs -> "" : [instanceLine ih ++ from key | (key, ih) <- ihs]
    from key = case M.lookup key origins of
      Just m | m /= name -> "  -- in " ++ m
      _ -> ""
    builtinInstances = case [ih | ((_, k), ih) <- M.toList (ckInsts (ifChecked iface)), builtinType k, not (bigTuple k)] of
      [] -> []
      ihs ->
        [ "## Instances for the types the language has", "" ]
          ++ ["Also for every tuple up to fifteen elements, as for pairs." | any (\((_, k), _) -> bigTuple k) (M.toList (ckInsts (ifChecked iface)))]
          ++ [""]
          ++ ["```haskell"] ++ map instanceLine ihs ++ ["```", ""]
    builtinType k = not (M.member k (ckData allChecked)) || k `elem` ["[]", "Bool"]
    bigTuple k = maybe False (> 2) (tupleArity k)
    instanceLine ih = "instance " ++ context (ihCtx ih) ++ unqual (classOfInstance ih) ++ " " ++ unwords (map prettyAtom (ihHead ih))
    classOfInstance ih = head' [c | ((c, _), ih') <- M.toList (ckInsts allChecked), ihId ih' == ihId ih]
    head' xs = case xs of
      x : _ -> x
      [] -> "?"

    reexports = case M.toList groupsByModule of
      [] -> []
      gs ->
        ["## Re-exported", ""]
          ++ [ "- From [" ++ m ++ "](" ++ m ++ ".md): " ++ intercalate ", " (map (\x -> "`" ++ operator x ++ "`") (nub xs)) ++ "."
             | (m, xs) <- gs ]
          ++ [""]
    groupsByModule = M.fromListWith (flip (++))
      [ (fromMaybe "Prelude" (fst (splitQual i)), [n])
      | (n, i) <- M.toList (tVals table) ++ M.toList (tTypes table), not (own i n), not (isChild i) ]

-- | Something documented: whether it is a value (whose code can share a
-- block with others), its comment, its code, and text after the code.
data Entry = Entry Bool [String] [String] [String]

-- | Sections and entries in source order. Undocumented entries in a row
-- share one block of code; a documented one gets its own, followed by its
-- comment. A section without entries is left out.
render :: [Either String [Entry]] -> [String]
render items = concat (go Nothing items)
  where
    go _ [] = []
    go _ (Left title : rest) = go (Just title) rest
    go pending (Right [] : rest) = go pending rest
    go pending (Right es : rest) =
      let (run, rest') = spanEntries (Right es : rest)
       in (maybe [] (\t -> ["## " ++ t, ""]) pending ++ blocks run) : go Nothing rest'
    spanEntries = \case
      Right es : rest -> let (more, rest') = spanEntries rest in (es ++ more, rest')
      other -> ([], other)
    blocks es = case es of
      [] -> []
      Entry value doc code after : rest
        | value && null doc ->
            -- undocumented values in a row share a block
            let (plain, rest') = span (\(Entry v d _ _) -> v && null d) es
             in fence (concat [c | Entry _ _ c _ <- plain]) ++ blocks rest'
        | otherwise -> fence code ++ paragraph doc ++ paragraph after ++ blocks rest
    fence code = ["```haskell"] ++ code ++ ["```", ""]

-- | Comment lines as Markdown text, then a blank line.
paragraph :: [String] -> [String]
paragraph ls = case dropWhile null ls of
  [] -> []
  ls' -> map escape (dropWhileEnd null ls') ++ [""]
  where
    -- a line that starts like Markdown's quotes or headings is still text,
    -- and so is something that looks like an HTML tag, as <a> or <n>
    escape l =
      let (sp, rest) = span (== ' ') l
          rest' = case rest of
            c : _ | c `elem` ">#" -> '\\' : rest
            _ -> rest
       in sp ++ tags rest'
    tags s = case s of
      '<' : c : more | isAlphaNum c || c == '/' -> "&lt;" ++ tags (c : more)
      c : more -> c : tags more
      [] -> []

-- | No more than one blank line in a row, none at the end.
collapse :: [String] -> [String]
collapse = dropWhileEnd null . go
  where
    go (a : b : rest) | null a, null b = go (b : rest)
    go (a : rest) = a : go rest
    go [] = []

-- Types ----------------------------------------------------------------------------

scheme :: Scheme -> String
scheme (Forall _ ps t) = context ps ++ pretty t

context :: [Pred] -> String
context ps = case [unqual c ++ " " ++ unwords (map prettyAtom ts) | IsIn c ts <- ps] of
  [] -> ""
  [p] -> p ++ " => "
  ps' -> "(" ++ intercalate ", " ps' ++ ") => "

-- | A type as written, from a synonym's right-hand side.
stype :: SType -> String
stype = go (0 :: Int)
  where
    go p = \case
      STVar v -> v
      STCon "[]" [t] -> "[" ++ go 0 t ++ "]"
      STCon c ts | Just n <- tupleArity c, n == length ts -> "(" ++ intercalate ", " (map (go 0) ts) ++ ")"
      STCon c [] -> unqual c
      STCon c ts -> paren (p > 1) (unwords (unqual c : map (go 2) ts))
      STApp f ts -> paren (p > 1) (unwords (go 2 f : map (go 2) ts))
      STFun a b -> paren (p > 0) (go 1 a ++ " -> " ++ go 0 b)
    paren b s = if b then "(" ++ s ++ ")" else s

isOperator :: Name -> Bool
isOperator n = case n of
  c : _ -> not (isAlphaNum c || c == '_' || c == '(' || c == '[')
  [] -> False

-- | A name as it is written in a signature: (!?) for an operator.
operator :: Name -> Name
operator n = if isOperator n then "(" ++ n ++ ")" else n

-- The source ---------------------------------------------------------------------

data Kind = KValue | KType | KClass | KOther

-- | A top-level declaration: its comment, what it declares, and the
-- comments of the methods in a class.
data Group = Group {gDoc :: [String], gNames :: [Name], gKind :: Kind, gMethodDocs :: M.Map Name [String]}

data Piece = Heading String | Decl Group

-- | The module's comment: the comment lines the file starts with.
header :: String -> [String]
header src = haddock (map commentText (takeWhile (\l -> isComment l && not (isHeading l)) (lines src)))

-- | A comment without Haddock's mark, which some start with: -- | Text.
haddock :: [String] -> [String]
haddock = \case
  ('|' : ' ' : first) : rest -> first : rest
  "|" : rest -> rest
  ls -> ls

-- | Section headings and declarations, in the order of the source.
sourcePieces :: String -> [Piece]
sourcePieces src = case lexer src of
  Left _ -> []
  Right toks -> merge headings (firstOnly [] (map group (starts toks)))
  where
    ls = lines src
    lineAt i = if i >= 1 && i <= length ls then ls !! (i - 1) else ""
    headings = [(i, Heading (headingTitle l)) | (i, l) <- zip [1 ..] ls, isComment l, isHeading l]
    merge hs ds = map snd (sortOn fst (hs ++ ds))
    -- a function's clauses after the first, or its definition after its signature
    firstOnly seen = \case
      [] -> []
      (i, Decl g) : rest ->
        let names = [n | n <- gNames g, n `notElem` seen]
         in (i, Decl g {gNames = names}) : firstOnly (names ++ seen) rest
      p : rest -> p : firstOnly seen rest
    -- the tokens of each top-level declaration: one starts in the first column
    starts = \case
      [] -> []
      t : rest -> let (body, more) = break ((== 1) . tokCol) rest in (t : body) : starts more
    group ts@(t : _) =
      let (kind, names) = declared (map tokVal ts)
       in (tokLine t, Decl (Group (commentAbove (tokLine t) 0) names kind (methodDocs ts)))
    group [] = (0, Decl (Group [] [] KOther M.empty))
    -- the comment lines right above line i, indented as it is
    commentAbove i indent =
      let above = reverse (takeWhile (\l -> isCommentAt indent l && not (isHeading l)) (map lineAt [i - 1, i - 2 .. 1]))
       in haddock (map (commentText . drop indent) above)
    isCommentAt indent l = length (takeWhile (== ' ') l) == indent && isComment (drop indent l)
    -- in a class, the comment above each method's signature
    methodDocs ts = M.fromList
      [ (n, doc)
      | line@(first : _) <- byLine (drop 1 ts)
      , Just names <- [signature (map tokVal line)]
      , let doc = commentAbove (tokLine first) (tokCol first - 1)
      , not (null doc)
      , n <- names ]
    byLine = \case
      [] -> []
      t : rest -> let (same, more) = span ((== tokLine t) . tokLine) rest in (t : same) : byLine more

-- | What a declaration's tokens declare.
declared :: [Tok] -> (Kind, [Name])
declared = \case
  TKey k : rest | k `elem` ["data", "newtype"] -> (KType, take 1 [c | TConId c <- rest])
  TKey "type" : TConId c : _ -> (KType, [c])
  TKey "class" : rest ->
    let h = takeWhile (/= TKey "where") rest
        afterContext = if TKey "=>" `elem` h then drop 1 (dropWhile (/= TKey "=>") h) else h
     in (KClass, take 1 [c | TConId c <- afterContext])
  TKey "foreign" : TKey "import" : TVarId "go" : TKey "type" : TStr _ : TConId c : _ -> (KType, [c])
  TKey "foreign" : TKey "import" : TVarId "go" : TStr _ : rest -> (KValue, fromMaybe [] (signature rest))
  TKey _ : _ -> (KOther, [])
  ts -> (KValue, fromMaybe (binding ts) (signature ts))
  where
    binding = \case
      TSpecial "(" : TVarSym o : TSpecial ")" : _ -> [o]
      TVarId _ : TVarSym o : _ -> [o]
      TVarId _ : TSpecial "`" : TVarId o : TSpecial "`" : _ -> [o]
      TVarId x : _ -> [x]
      _ -> []

-- | The names a signature's tokens declare: @x, (<+>) :: ...@.
signature :: [Tok] -> Maybe [Name]
signature ts = case break (`elem` [TKey "::", TKey "=", TKey "|"]) ts of
  (names, TKey "::" : _) -> binders names
  _ -> Nothing
  where
    binders = \case
      [TVarId x] -> Just [x]
      [TSpecial "(", TVarSym o, TSpecial ")"] -> Just [o]
      TVarId x : TSpecial "," : rest -> (x :) <$> binders rest
      TSpecial "(" : TVarSym o : TSpecial ")" : TSpecial "," : rest -> (o :) <$> binders rest
      _ -> Nothing

-- | A line that is a comment: --, but not an operator that starts with it.
isComment :: String -> Bool
isComment l = case dropWhile isSpace l of
  '-' : '-' : rest -> case dropWhile (== '-') rest of
    c : _ -> c `notElem` "!#$%&*+./<=>?@\\^|~:"
    [] -> True
  _ -> False

-- | A comment line that ends in three dashes or more, after some words.
isHeading :: String -> Bool
isHeading l = "---" `isPrefixOf` reverse (dropWhileEnd isSpace l) && not (null (headingTitle l))

headingTitle :: String -> String
headingTitle l = trim (dropWhileEnd (\c -> c == '-' || isSpace c) (commentText l))

commentText :: String -> String
commentText l = case dropWhile isSpace l of
  '-' : '-' : ' ' : rest -> dropWhileEnd isSpace rest
  '-' : '-' : rest -> dropWhileEnd isSpace (dropWhile (== '-') rest)
  other -> other

trim :: String -> String
trim = dropWhile isSpace . dropWhileEnd isSpace
