-- | What a name refers to, and with how many arguments it is called directly.
data VK
  = VKTop Int [Name] Bool  -- ^ top-level: arity, type parameters, whether it is a shared value
  | VKLocal Int        -- ^ local: arity (0 for plain values)
  | VKForeign Foreign
  | VKPrim Int

data Ctx = Ctx
  { cxVars :: M.Map Name VK
  , cxSelf :: Maybe (Name, Int)   -- ^ function whose self tail calls become a loop
  , cxSelfParams :: [Name]        -- ^ its parameters, assigned before going round again
  , cxTParams :: [Name]
  , cxProg :: Program
  , cxPending :: S.Set Name   -- ^ local variables declared but not assigned yet
  , cxUnboxed :: M.Map Name Repr   -- ^ the data types kept by value (see 'dataReprs')
  , cxRun :: M.Map Name (String, Int)
    -- ^ functions that return an action and have a run form (see 'genRun'):
    -- its Go name and how many arguments it takes
  , cxGroup :: S.Set Name
    -- ^ while generating a run form, the functions a tail call to which goes
    -- through the trampoline: those that may call this one back
  }

data GS = GS {gsNext :: Int, gsLoop :: Bool}

type Gen = State GS

-- | The runtime copied into a program.
data Runtime = Runtime
  { rtCore :: Bool -> String
    -- ^ what every program gets, in two versions: a program that may run on
    -- several goroutines gets the one whose thunks any of them can force
  , rtConcurrentSymbols :: [String]
    -- ^ the functions only the concurrent version has (threads, MVars, channels)
  , rtParts :: [RuntimePart]
  }

-- | A part of the runtime that a program gets only if it calls one of its
-- functions, so that every program does not import net/http or crypto.
data RuntimePart = RuntimePart
  { rpSource :: String
  , rpSymbols :: [String] -- ^ the functions and types it defines
  , rpImports :: [String] -- ^ its import lines, as @rt_http "net/http"@
  }

-- | The Go program.
generate :: Runtime -> Program -> String
generate runtime prog =
  unlines (header ++ [rtCore runtime concurrent] ++ map rpSource parts ++ tupleDecls ++ dataDecls ++ hkDecls ++ foreignUses ++ tops ++ initBlock ++ mainFn)
  where
    usedForeign = S.fromList (concatMap (coreRefs . tbBody) (progBinds prog))
    used = [f | (n, f) <- M.toList (progForeign prog), S.member n usedForeign]
    concurrent = any (\f -> fSymbol f `elem` rtConcurrentSymbols runtime || startsGoroutines f) used
    parts = [p | p <- rtParts runtime, any ((`elem` rpSymbols p) . fSymbol) used]
    coreImports = map (takeWhile (/= ' ')) baseImports
    partImports = nub [i | p <- parts, i <- rpImports p, takeWhile (/= ' ') i `notElem` coreImports]
    foreignPkgs = nub
      [ pkg
      | sym <- map fSymbol (M.elems (progForeign prog)) ++ [s | di <- M.elems (progData prog), Just s <- [diForeign di]]
      , take 1 sym /= "."
      , let (pkg, _) = splitSymbol (dropWhile (== '*') sym), pkg /= "" ]
    header =
      [ "// Code generated by hago. DO NOT EDIT."
      , "package main"
      , "import (" ]
        ++ baseImports
        ++ (if concurrent then ["rt_reflect \"reflect\"", "rt_runtime \"runtime\"", "rt_syscall \"syscall\""] else [])
        ++ partImports
        ++ [show p | p <- foreignPkgs]
        ++ [")"]
    baseImports =
      [ "rt_bufio \"bufio\""
      , "rt_fmt \"fmt\""
      , "rt_os \"os\""
      , "rt_strconv \"strconv\""
      , "rt_strings \"strings\""
      , "rt_sync \"sync\""
      , "rt_big \"math/big\""
      , "rt_filepath \"path/filepath\""
      , "rt_time \"time\""
      , "rt_atomic \"sync/atomic\""
      , "rt_iter \"iter\""
      , "rt_slices \"slices\"" ]
    -- every imported package is used, even by a program that calls none of
    -- its functions; a generic function cannot be named without its types
    foreignUses =
      [ "var _ = " ++ short | f <- M.elems (progForeign prog), fArity f > 0, null (fVars f)
      , take 1 (fSymbol f) /= "."
      , let (pkg, short) = splitSymbol (fSymbol f), pkg /= "" ]
        ++ [ "var _ " ++ goTypeSymbol s ++ (if null (diParams di) then "" else "[" ++ commas (map (const "any") (diParams di)) ++ "]")
           | di <- M.elems (progData prog), Just s <- [diForeign di], '.' `elem` s ]
    ctx0 = Ctx
      { cxVars = M.unions
          [ M.fromList [(tbName b, VKTop (tbArity b) (tbParams b) (tbShared b)) | b <- progBinds prog]
          , M.map VKForeign (progForeign prog)
          , M.fromList [(n, VKPrim (arrows t)) | (n, Forall _ _ t) <- M.toList primSchemes] ]
      , cxSelf = Nothing
      , cxSelfParams = []
      , cxTParams = []
      , cxProg = prog
      , cxPending = S.empty
      , cxUnboxed = unboxed
      , cxRun = M.fromList [(tbName b, (runName (tbName b), tbArity b)) | b <- progBinds prog, hasRunForm prog b]
      , cxGroup = S.empty
      }
    -- a struct for each size of tuple the program uses
    tupleDecls =
      [ "type Tup" ++ show n ++ "[" ++ commas ["T" ++ show i | i <- [1 .. n]] ++ " any] struct{ "
          ++ intercalate "; " ["F" ++ show (i - 1) ++ " T" ++ show i | i <- [1 .. n]] ++ " }"
      | n <- sort (nub (concatMap tupleSizes (typesIn prog {progCons = M.filterWithKey (\k _ -> tupleArity k == Nothing) (progCons prog)}))) ]
    tupleSizes = \case
      TCon c ts -> maybe [] pure (tupleArity c) ++ concatMap tupleSizes ts
      TFun a b -> tupleSizes a ++ tupleSizes b
      TApp f x -> tupleSizes f ++ tupleSizes x
      _ -> []
    unboxed = dataReprs prog
    dataDecls = concatMap (genData prog unboxed)
      [(n, d) | (n, d) <- M.toList (progData prog), n `notElem` ["[]", "Bool"], null (hkPositions prog n), diForeign d == Nothing]
    hkDecls = concatMap (genHkData prog) (hkInstances prog)
    (tops, inits) = flip evalState (GS 0 False) (unzip <$> mapM (\b -> genTop ctx0 {cxGroup = groupOf (tbName b)} (S.member (tbName b) deferred) b) initOrder)
    -- the functions of each one's group of mutually recursive ones, itself among them
    groupOf n = M.findWithDefault (S.singleton n) n groups
    groups = M.fromList [(tbName b, S.fromList (map tbName bs)) | CyclicSCC bs <- sccs, b <- bs]
    initBlock = ["func init() {", "defer rt_failed()"] ++ concat inits ++ ["}"]
    -- values are initialised in order, so each comes after everything its
    -- computation reaches, functions included; copies made by specialisation
    -- would otherwise come after their users
    sccs =
      let names = S.fromList (map tbName (progBinds prog))
       in stronglyConnComp
            [(b, tbName b, filter (`S.member` names) (coreRefs (tbBody b))) | b <- progBinds prog]
    initOrder = flattenSCCs sccs
    -- Values defined in terms of each other (parsers built with combinators)
    -- cannot be computed one after the other in a strict language. Those
    -- that are functions, IO actions among them, start as a function that
    -- computes the value the first time it is called and then calls it, so
    -- every value in the group exists before any is computed.
    deferred = S.fromList
      [ tbName b
      | CyclicSCC bs <- sccs, b <- bs, tbArity b == 0, tbShared b
      , isFunctionType (zonk (progSubst prog) (tbType b)) ]
    isFunctionType = \case
      TFun _ _ -> True
      TCon "IO" [_] -> True
      _ -> False
    -- drop the global reference first, so actions already run can be collected
    mainFn = ["func main() {", "defer rt_failed()", "m := " ++ mangle "main", mangle "main" ++ " = nil", "rt_run(m)", "}"]

-- Names -------------------------------------------------------------------------

goReserved :: [String]
goReserved = words
  "break default func interface select case defer go map struct chan else goto package switch \
  \const fallthrough if range type continue for import return var any bool byte comparable \
  \complex64 complex128 error float32 float64 int int8 int16 int32 int64 rune string uint uint8 \
  \uint16 uint32 uint64 uintptr true false iota nil append cap clear close complex copy delete \
  \imag len make max min new panic print println real recover main init List Nil Cons Tup2 Tup3 IO IOStep"

mangle :: Name -> String
mangle n
  -- a specialised operator keeps the letters of its types: ++__Int
  | isSymbolic n = "op_" ++ concatMap (\c -> if isAlphaNum c || c == '_' then [c] else symWord c) n
  | s `elem` goReserved = s ++ "_"
  | any (`isPrefixOf` s) ["rt_", "hg_"] = "u_" ++ s
  | otherwise = s
  where
    s = concatMap (\c -> if c == '\'' then "_q" else if c == '.' then "_" else if isAlphaNum c || c == '_' then [c] else "_" ++ symWord c) n'
    -- a qualified operator: the module part as a prefix, the operator spelled out
    n' = case splitQual n of
      (Just q, base) | isSymbolic base -> q ++ ".op_" ++ concatMap symWord base
      _ -> n
    -- any other character by its code, so that two names never meet
    symWord c = fromMaybe ("x" ++ show (fromEnum c)) (lookup c symNames)
    symNames =
      [ ('+', "plus"), ('-', "minus"), ('*', "star"), ('/', "slash"), ('.', "dot"), ('<', "lt")
      , ('>', "gt"), ('=', "eq"), ('!', "bang"), ('$', "dollar"), ('&', "amp"), ('|', "bar")
      , (':', "colon"), ('^', "caret"), ('%', "pct"), ('@', "at"), ('#', "hash"), ('?', "qm")
      , ('~', "tilde"), ('\\', "bslash") ]

-- | A constructor's part of its struct name: without its module, operators spelled out.
conSuffix :: Name -> String
conSuffix k = let b = unqual k in if isSymbolic b then mangle b else b

-- | Operators and operator constructors, as opposed to alphanumeric names.
isSymbolic :: Name -> Bool
isSymbolic (c : _) = not (isAlpha c || c == '_')
isSymbolic [] = False

tyVar :: Name -> String
tyVar v = "T_" ++ concatMap (\c -> if c == '\'' then "_q" else [c]) v

typeName :: Name -> String
typeName c = if c' `elem` goReserved then c' ++ "_" else c'
  where c' = map (\x -> if x == '.' then '_' else x) c

conStruct :: Program -> Name -> String
conStruct prog k = case k of
  "[]" -> "Nil"
  ":" -> "Cons"
  _ | Just n <- tupleArity k -> "Tup" ++ show n
  _ -> typeName (ciType (progCons prog M.! k)) ++ "_" ++ conSuffix k

-- | A Go type named in @foreign import go type@, as the generated code writes
-- it: @"*net/http.Request"@ is @*http.Request@, and the runtime's own types
-- (@"*rt_MVar"@) have no package.
goTypeSymbol :: String -> String
goTypeSymbol sym = let (stars, rest) = span (== '*') sym in stars ++ snd (splitSymbol rest)

splitSymbol :: String -> (String, String)
splitSymbol s = case break (== '.') (reverse s) of
  (_, []) -> ("", s)
  (_, _ : revPkg) ->
    let pkgPath = reverse revPkg
        short = reverse (takeWhile (/= '/') revPkg)
     in (pkgPath, short ++ drop (length pkgPath) s)

-- Types ---------------------------------------------------------------------------

goTy :: Ctx -> Type -> String
goTy ctx = render . zonk (progSubst (cxProg ctx))
  where
    render = \case
      TVar v -> tyVar v
      TMeta _ -> "struct{}"
      TCon "Int" [] -> "int"
      TCon "Double" [] -> "float64"
      TCon "Integer" [] -> "*rt_big.Int"
      TCon "Bool" [] -> "bool"
      TCon "Char" [] -> "rune"
      TCon "String" [] -> "string"
      TCon "()" [] -> "struct{}"
      TCon "[]" [t] -> "List[" ++ render t ++ "]"
      TCon "IO" [t] -> "IO[" ++ render t ++ "]"
      TCon "Lazy" [t] -> "*rt_thunk[" ++ render t ++ "]"
      TCon c ts | Just n <- tupleArity c -> "Tup" ++ show n ++ "[" ++ commas (map render ts) ++ "]"
      TCon c ts
        | not (null (hkPositions (cxProg ctx) c)) ->
            let (n, args) = dataInst (cxProg ctx) c ts
             in n ++ (if null args then "" else "[" ++ commas (map render args) ++ "]")
      TCon c [t] | Just "[]" <- M.lookup c (progData (cxProg ctx)) >>= diForeign -> "[]" ++ render t
      TCon c ts | Just sym <- M.lookup c (progData (cxProg ctx)) >>= diForeign ->
        goTypeSymbol sym ++ (if null ts then "" else "[" ++ commas (map render ts) ++ "]")
      TCon c [] -> typeName c
      TCon c ts -> typeName c ++ "[" ++ commas (map render ts) ++ "]"
      TFun a b -> "func(" ++ render a ++ ") " ++ render b
      TApp _ _ -> error "codegen: a type application survived specialisation"

typeArgs :: Ctx -> [Type] -> String
typeArgs _ [] = ""
typeArgs ctx ts = "[" ++ commas (map (goTy ctx) ts) ++ "]"

tparamList :: [Name] -> String
tparamList [] = ""
tparamList vs = "[" ++ commas [tyVar v ++ " any" | v <- vs] ++ "]"

commas :: [String] -> String
commas = intercalate ", "

-- Data types ----------------------------------------------------------------------

-- | Parameters of a data type that take a type constructor (the m of StateT s m a).
hkPositions :: Program -> Name -> [Int]
hkPositions prog c = maybe [] (\di -> [i | (i, k) <- zip [0 ..] (diKinds di), k > 0]) (M.lookup c (progData prog))

-- | Go has no type parameters of a higher kind, so a data type applied to a
-- type constructor gets one Go type per constructor: StateT s IO a becomes
-- StateT__IO[S, A]. Variables inside the constructor become extra type
-- parameters. Returns the Go name and its type arguments.
dataInst :: Program -> Name -> [Type] -> (String, [Type])
dataInst prog c ts =
  let pos = hkPositions prog c
      hk = [t | (i, t) <- zip [0 :: Int ..] ts, i `elem` pos]
      rest = [t | (i, t) <- zip [0 :: Int ..] ts, i `notElem` pos]
      (canon, extras) = canonVars hk
   in (instName c canon, rest ++ map TVar extras)

canonVars :: [Type] -> ([Type], [Name])
canonVars hk =
  let vs = nub (concatMap tyVarsOf hk)
      s = M.fromList [(v, TVar ("_hk" ++ show i)) | (i, v) <- zip [0 :: Int ..] vs]
   in (map (substTV s) hk, vs)

instName :: Name -> [Type] -> String
instName c canon = typeName c ++ "__" ++ intercalate "_" (map typeTag canon)

-- | A constructor as a Go struct, with its type arguments.
conRef :: Ctx -> Name -> [Type] -> String
conRef ctx k targs = case M.lookup k (progCons prog) of
  Just ci | not (null (hkPositions prog (ciType ci))) ->
    let (n, args) = dataInst prog (ciType ci) (map (zonk (progSubst prog)) targs)
     in n ++ "_" ++ conSuffix k ++ typeArgs ctx args
  _ -> conStruct prog k ++ typeArgs ctx targs
  where prog = cxProg ctx

-- | Every instantiation of a data type over type constructors that the
-- program uses, including those that only appear inside other ones' fields.
hkInstances :: Program -> [(Name, [Type])]
hkInstances prog = go [] (concatMap found allTypes)
  where
    sub = progSubst prog
    allTypes = concat [tbType b : exprTypes (tbBody b) | b <- progBinds prog]
    found t = case zonk sub t of
      TCon c ts
        | not (null (hkPositions prog c)), Just di <- M.lookup c (progData prog), length ts == length (diParams di) ->
            (c, fst (canonVars [x | (i, x) <- zip [0 :: Int ..] ts, i `elem` hkPositions prog c])) : concatMap found ts
        | otherwise -> concatMap found ts
      TFun a b -> found a ++ found b
      TApp f x -> found f ++ found x
      _ -> []
    go _ [] = []
    go seen (x : xs)
      | x `elem` seen = go seen xs
      | otherwise = x : go (x : seen) (xs ++ concatMap found (fieldTypes x))
    fieldTypes (c, canon) =
      let di = progData prog M.! c
          s = M.fromList (zip [p | (p, k) <- zip (diParams di) (diKinds di), k > 0] canon)
       in [substTV s t | k <- diCons di, (_, t) <- ciFields (progCons prog M.! k)]

genHkData :: Program -> (Name, [Type]) -> [String]
genHkData prog (c, canon) =
  ["type " ++ name ++ tparamList params ++ " interface{ " ++ marker ++ "() }"] ++ concatMap con (diCons di)
  where
    di = progData prog M.! c
    hkParams = [p | (p, k) <- zip (diParams di) (diKinds di), k > 0]
    params = [p | (p, k) <- zip (diParams di) (diKinds di), k == 0] ++ nub (concatMap tyVarsOf canon)
    s = M.fromList (zip hkParams canon)
    name = instName c canon
    marker = "is" ++ name
    ctx = Ctx M.empty Nothing [] params prog S.empty M.empty M.empty S.empty
    recv k = name ++ "_" ++ suffix k ++ (if null params then "" else "[" ++ commas (map tyVar params) ++ "]")
    suffix = conSuffix
    con k =
      let ci = progCons prog M.! k
          fields = ["F" ++ show i ++ " " ++ goTy ctx (substTV s (if lz then tLazy t else t)) | (i, (lz, t)) <- zip [0 :: Int ..] (ciFields ci)]
       in [ "type " ++ name ++ "_" ++ suffix k ++ tparamList params ++ " struct{ " ++ intercalate "; " fields ++ " }"
          , "func (" ++ recv k ++ ") " ++ marker ++ "() {}" ]

-- | How a data type is kept in Go, when it is not an interface with a
-- struct per constructor (which costs an allocation to build and a type
-- test to match).
data Repr
  = Plain    -- ^ its one constructor's struct, passed by value
  | Tagged   -- ^ one struct, passed by value, with a tag saying which constructor and the fields of all of them
  | Pointer  -- ^ a pointer to the struct of the constructor with fields; nil is the one without, as [] and Tip

-- | The data types kept by value. Not one that contains itself by value
-- (through its fields, tuples, or other such types), which would have no
-- size, nor one over type constructors, nor one bigger than eight words,
-- which would be slow to copy.
--
-- A type with two constructors, one with no fields, as a list or a tree, is
-- a pointer, which is half the size of an interface and is matched by
-- comparing it with nil.
dataReprs :: Program -> M.Map Name Repr
dataReprs prog = M.union byValueReprs pointers
  where
    byValueReprs = M.fromList [(n, repr n) | AcyclicSCC n <- stronglyConnComp [(n, n, byValue n) | n <- S.toList candidates]]
    pointers = M.fromList
      [ (n, Pointer) | (n, DataInfo _ _ [a, b] nt _) <- M.toList (progData prog), not nt, n `notElem` ["Bool"]
      , null (hkPositions prog n), tupleArity n == Nothing
      , length (filter null [ciFields (progCons prog M.! a), ciFields (progCons prog M.! b)]) == 1 ]
    candidates = S.fromList
      [ n | (n, DataInfo _ _ ks nt _) <- M.toList (progData prog), not nt, not (null ks), n `notElem` ["[]", "Bool", "()"]
      , tupleArity n == Nothing, null (hkPositions prog n), sizeOf [] n <= (8 :: Int) ]
    -- the sums small enough to be kept by value if they do not contain themselves
    smallSums = S.fromList [n | (n, di) <- M.toList (progData prog), length (diCons di) <= 3]
    repr n = case diCons (progData prog M.! n) of
      [_] -> Plain
      _ -> Tagged
    fieldsOf n = [(lz, t) | k <- diCons (progData prog M.! n), (lz, t) <- ciFields (progCons prog M.! k)]
    byValue n = [c | (lz, t) <- fieldsOf n, not lz, c <- inside t]
    inside = \case
      TCon c ts
        | S.member c candidates -> c : concatMap inside ts
        | tupleArity c /= Nothing -> concatMap inside ts
      _ -> []
    -- the types that contain themselves, through strict fields and the
    -- types inside them: never kept by value, so a field of one is a pointer
    -- or an interface
    selfContaining = S.fromList [n | CyclicSCC ns <- stronglyConnComp [(n, n, refs n) | n <- M.keys (progData prog)], n <- ns]
    refs n = nub [c | (lz, t) <- fieldsOf n, not lz, c <- conNamesIn t]
    conNamesIn = \case
      TCon c ts | c /= "[]", M.member c (progData prog) || tupleArity c /= Nothing -> c : concatMap conNamesIn ts
      TCon _ ts -> concatMap conNamesIn ts
      _ -> []
    -- in words, guessing two for a type variable; a type that contains
    -- itself is too big
    sizeOf seen n
      | n `elem` seen = 100
      | otherwise =
          let ks = diCons (progData prog M.! n)
           in (if length ks > 1 then 1 else 0) + sum [if lz then 1 else wordsOf (n : seen) t | (lz, t) <- fieldsOf n]
    wordsOf seen = \case
      TCon c ts
        | c `elem` ["Int", "Double", "Char", "Bool", "Integer", "()", "Lazy", "IO"] -> 1
        | tupleArity c /= Nothing -> sum (map (wordsOf seen) ts)
        | M.member c pointers, not (S.member c smallSums) -> 1
        | S.member c selfContaining -> if M.member c pointers then 1 else 2
        | Just di <- M.lookup c (progData prog), length (diCons di) <= 3, not (diNewtype di), null (hkPositions prog c), c `notElem` ["[]"] ->
            min 100 (sizeOf seen c)
        | otherwise -> 2
      TFun _ _ -> 1
      _ -> 2

genData :: Program -> M.Map Name Repr -> (Name, DataInfo) -> [String]
genData prog unboxed (n, DataInfo ps _ ks _ _)
  | n == "()" || tupleArity n /= Nothing = []
  | Just Pointer <- M.lookup n unboxed, [k] <- [k | k <- ks, not (null (ciFields (progCons prog M.! k)))] =
      let ci = progCons prog M.! k
          fields = [ "F" ++ show i ++ " " ++ goTy ctx (if lz then tLazy t else t) | (i, (lz, t)) <- zip [0 :: Int ..] (ciFields ci)]
       in [ "type " ++ conStruct prog k ++ tparamList ps ++ " struct{ " ++ intercalate "; " fields ++ " }"
          , "type " ++ typeName n ++ tparamList ps ++ " = *" ++ conStruct prog k ++ (if null ps then "" else "[" ++ commas (map tyVar ps) ++ "]") ]
  | Just Tagged <- M.lookup n unboxed =
      let fields =
            "tag uint8"
              : [ taggedField (progCons prog M.! k) i ++ " " ++ goTy ctx (if lz then tLazy t else t)
                | k <- ks, (i, (lz, t)) <- zip [0 :: Int ..] (ciFields (progCons prog M.! k)) ]
       in ["type " ++ typeName n ++ tparamList ps ++ " struct{ " ++ intercalate "; " fields ++ " }"]
  | Just Plain <- M.lookup n unboxed, [k] <- ks =
      let ci = progCons prog M.! k
          fields = [ "F" ++ show i ++ " " ++ goTy ctx (if lz then tLazy t else t) | (i, (lz, t)) <- zip [0 :: Int ..] (ciFields ci)]
       -- the struct is the type itself and the constructor's name an alias
       -- of it: a struct that refers to itself through an alias (a list of
       -- itself) makes Go 1.27 fail with "incomplete alias" (go.dev/issue/78296)
       in [ "type " ++ typeName n ++ tparamList ps ++ " struct{ " ++ intercalate "; " fields ++ " }"
          , "type " ++ conStruct prog k ++ tparamList ps ++ " = " ++ typeName n ++ (if null ps then "" else "[" ++ commas (map tyVar ps) ++ "]") ]
  | otherwise =
      ["type " ++ typeName n ++ tparamList ps ++ " interface{ " ++ marker ++ "() }"]
        ++ concatMap con ks
  where
    marker = "is" ++ typeName n
    recv k = conStruct prog k ++ (if null ps then "" else "[" ++ commas (map tyVar ps) ++ "]")
    ctx = Ctx M.empty Nothing [] ps prog S.empty M.empty M.empty S.empty
    con k =
      let ci = progCons prog M.! k
          fields = [ "F" ++ show i ++ " " ++ goTy ctx (if lz then tLazy t else t) | (i, (lz, t)) <- zip [0 :: Int ..] (ciFields ci)]
       in [ "type " ++ conStruct prog k ++ tparamList ps ++ " struct{ " ++ intercalate "; " fields ++ " }"
          , "func (" ++ recv k ++ ") " ++ marker ++ "() {}" ]

-- Top-level bindings ----------------------------------------------------------------

-- | A top-level binding: its declaration, and its initialisation if it is a CAF.
genTop :: Ctx -> Bool -> TopBind -> Gen (String, [String])
genTop ctx0 deferred (TopBind n tps dicts t ar body shared) = do
  -- specialisation leaves no dictionary
  unless (null dicts) (error ("codegen: dictionaries left in " ++ n))
  let ctx = ctx0 {cxTParams = tps}
  case (ar, body) of
    (0, _) | shared, deferred -> do
      e <- genExpr ctx body
      let ty = goTy ctx t
          cell = mangle n ++ "__cell"
          wrapper = case zonk (progSubst (cxProg ctx)) t of
            TFun a r -> "func(hg_arg " ++ goTy ctx a ++ ") " ++ goTy ctx r ++ " { return " ++ cell ++ ".force()(hg_arg) }"
            TCon "IO" [r] -> "func() IOStep[" ++ goTy ctx r ++ "] { return " ++ cell ++ ".force()() }"
            _ -> error ("genTop: deferred value of type " ++ ty)
      pure
        ( "var " ++ mangle n ++ " " ++ ty ++ "\nvar " ++ cell ++ " *rt_thunk[" ++ ty ++ "]"
        , [cell ++ " = rt_lazy(func() " ++ ty ++ " { return " ++ e ++ " })", mangle n ++ " = " ++ wrapper] )
    (0, _) | shared -> do
      e <- genExpr ctx body
      pure ("var " ++ mangle n ++ " " ++ goTy ctx t, [mangle n ++ " = " ++ e])
    (0, _) -> do
      ls <- genStmts ctx body
      pure (unlines (["func " ++ mangle n ++ tparamList tps ++ "() " ++ goTy ctx t ++ " {"] ++ ls ++ ["}"]), [])
    (_, CLam ps r inner) -> do
      fn <- genFunction ctx (Just (n, ar)) [] ps r inner
      runFn <- case (M.lookup n (cxRun ctx), ioResult ctx r) of
        (Just (rn, _), Just x) -> (\f -> "\nfunc " ++ rn ++ tparamList tps ++ f) <$> genRunFunction ctx (Just (n, ar)) ps x inner
        _ -> pure ""
      pure ("func " ++ mangle n ++ tparamList tps ++ fn ++ runFn, [])
    _ -> error ("genTop: " ++ n)

-- | Parameters, result type and body of a function, with self tail calls
-- turned into a loop.
genFunction :: Ctx -> Maybe (Name, Int) -> [(String, String)] -> [(Name, Type)] -> Type -> CExpr -> Gen String
genFunction ctx self extra ps r inner = do
  saved <- gets gsLoop
  modify (\s -> s {gsLoop = False})
  let ctx' = (bindLocals ctx [(p, 0) | (p, _) <- ps]) {cxSelf = self, cxSelfParams = map fst ps}
  ls <- genStmts ctx' inner
  looped <- gets gsLoop
  modify (\s -> s {gsLoop = saved})
  let params = commas ([d ++ " " ++ ty | (d, ty) <- extra] ++ [mangle p ++ " " ++ goTy ctx pt | (p, pt) <- ps])
      body = if looped then ["for {"] ++ ls ++ ["}"] else ls
  pure (unlines (["(" ++ params ++ ") " ++ goTy ctx r ++ " {"] ++ body ++ ["}"]))

bindLocals :: Ctx -> [(Name, Int)] -> Ctx
bindLocals ctx bs =
  ctx { cxVars = foldr (\(n, a) -> M.insert n (VKLocal a)) (cxVars ctx) bs
      , cxPending = foldr (S.delete . fst) (cxPending ctx) bs
      , cxRun = foldr (M.delete . fst) (cxRun ctx) bs
      , cxSelf = case cxSelf ctx of
          Just (n, _) | n `elem` map fst bs -> Nothing
          self -> self }

noSelf :: Ctx -> Ctx
noSelf ctx = ctx {cxSelf = Nothing}

freshName :: String -> Gen String
freshName base = do
  n <- gets gsNext
  modify (\s -> s {gsNext = n + 1})
  pure ("hg_" ++ base ++ show n)

-- Statements (a body that returns) --------------------------------------------------

genStmts :: Ctx -> CExpr -> Gen [String]
genStmts ctx e = case e of
  CMatch scruts rows _ -> genMatch genStmts ctx scruts rows
  CLet bs body _ -> do
    (ctx', ls) <- genBinds ctx bs
    (ls ++) <$> genStmts ctx' body
  CIf c a b _ -> do
    c' <- genExpr ctx c
    as <- genStmts ctx a
    bs <- genStmts ctx b
    pure (["if " ++ c' ++ " {"] ++ as ++ ["}"] ++ bs)
  CApp (CVar x _ _) args
    | Just (self, n) <- cxSelf ctx, x == self, length args == n, isSelf (M.lookup x (cxVars ctx)) n -> do
        as <- mapM (genExpr ctx) args
        modify (\s -> s {gsLoop = True})
        pure [commas (map mangle (cxSelfParams ctx)) ++ " = " ++ commas as, "continue"]
  _ -> do
    e' <- genExpr ctx e
    pure ["return " ++ e']
  where
    isSelf (Just (VKTop a _ _)) n = a == n
    isSelf (Just (VKLocal a)) n = a == n
    isSelf _ _ = False

-- | A @case@ as statements; tl makes those of each body.
genMatch :: (Ctx -> CExpr -> Gen [String]) -> Ctx -> [CExpr] -> [CRow] -> Gen [String]
genMatch tl ctx scruts rows = do
  prepared <- forM scruts $ \case
    CVar x _ _ | Just (VKLocal 0) <- M.lookup x (cxVars ctx) -> pure ([], mangle x)
    s -> do
      n <- freshName "s"
      s' <- genExpr ctx s
      -- a constructor's Go value has its struct type; matching needs the
      -- interface of its data type
      let decl = case conHead s of
            Just (k, targs) | tupleArity k == Nothing, k `notElem` ["()", "True", "False"] ->
              "var " ++ n ++ " " ++ goTy ctx (TCon (ciType (progCons (cxProg ctx) M.! k)) targs) ++ " = " ++ s'
            _ -> n ++ " := " ++ s'
      pure ([decl, "_ = " ++ n], n)
  rowLines <- forM rows $ \(CRow pats binds guards) -> do
    ls <- genPats ctx (zip (map snd prepared) pats) (\ctx' -> genRow tl ctx' binds guards)
    pure (["{"] ++ ls ++ ["}"])
  pure (concatMap fst prepared ++ concat rowLines ++ ["panic(\"pattern match failure\")"])

conHead :: CExpr -> Maybe (Name, [Type])
conHead = \case
  CCon k targs _ -> Just (k, targs)
  CApp f _ -> conHead f
  _ -> Nothing

genRow :: (Ctx -> CExpr -> Gen [String]) -> Ctx -> [CBind] -> [(Maybe CExpr, CExpr)] -> Gen [String]
genRow tl ctx binds guards = do
  (ctx', ls) <- genBinds ctx binds
  (ls ++) <$> go ctx' guards
  where
    go _ [] = pure []
    go c ((g, e) : rest) = case g of
      Nothing -> tl c e
      Just (CVar "otherwise" _ _) | isTopOtherwise c -> tl c e
      Just (CCon "True" _ _) -> tl c e
      Just cond -> do
        cond' <- genExpr c cond
        body <- tl c e
        rest' <- go c rest
        pure (["if " ++ cond' ++ " {"] ++ body ++ ["}"] ++ rest')
    isTopOtherwise c = case M.lookup "otherwise" (cxVars c) of
      Just (VKTop 0 _ _) -> True
      _ -> False

-- | Nested tests and bindings for a row of patterns; the continuation
-- produces the code that runs when everything matches.
genPats :: Ctx -> [(String, CPat)] -> (Ctx -> Gen [String]) -> Gen [String]
genPats ctx [] k = k ctx
genPats ctx ((s, p) : rest) k = case p of
  CPWild -> genPats ctx rest k
  CPVar x _ -> do
    body <- genPats (bindLocals ctx [(x, 0)]) rest k
    pure ([mangle x ++ " := " ++ s, "_ = " ++ mangle x] ++ body)
  CPAs x _ q -> do
    body <- genPats (bindLocals ctx [(x, 0)]) ((s, q) : rest) k
    pure ([mangle x ++ " := " ++ s, "_ = " ++ mangle x] ++ body)
  CPLit l -> do
    body <- genPats ctx rest k
    pure (["if " ++ s ++ " == " ++ genLit l ++ " {"] ++ body ++ ["}"])
  CPNum n t _ _ -> do
    let test = s ++ " == " ++ numLit ctx n t
    body <- genPats ctx rest k
    pure (["if " ++ test ++ " {"] ++ body ++ ["}"])
  CPEq f v -> do
    f' <- genExpr ctx f
    v' <- genExpr ctx v
    body <- genPats ctx rest k
    pure (["if (" ++ f' ++ ")(" ++ s ++ ")(" ++ v' ++ ") {"] ++ body ++ ["}"])
  CPForce q -> do
    n <- freshName "f"
    body <- genPats ctx ((n, q) : rest) k
    pure ([n ++ " := " ++ s ++ ".force()", "_ = " ++ n] ++ body)
  CPCon "True" _ _ -> cond s
  CPCon "False" _ _ -> cond ("!" ++ s)
  CPCon "()" _ _ -> genPats ctx rest k
  CPCon k' _ subs | Just _ <- tupleArity k' ->
    genPats ctx ([(s ++ ".F" ++ show i, q) | (i, q) <- zip [0 :: Int ..] subs] ++ rest) k
  -- the only constructor of a type kept as a struct always matches, and
  -- one of a tagged struct is told by its tag
  CPCon k' _ subs | Just ci <- M.lookup k' (progCons (cxProg ctx)), Just r <- M.lookup (ciType ci) (cxUnboxed ctx) -> case r of
    Plain -> genPats ctx ([(s ++ ".F" ++ show i, q) | (i, q) <- zip [0 :: Int ..] subs] ++ rest) k
    Tagged -> do
      body <- genPats ctx ([(s ++ "." ++ taggedField ci i, q) | (i, q) <- zip [0 :: Int ..] subs] ++ rest) k
      pure (["if " ++ s ++ ".tag == " ++ show (ciTag ci) ++ " {"] ++ body ++ ["}"])
    Pointer
      | null (ciFields ci) -> do
          body <- genPats ctx rest k
          pure (["if " ++ s ++ " == nil {"] ++ body ++ ["}"])
      | otherwise -> do
          body <- genPats ctx ([(s ++ ".F" ++ show i, q) | (i, q) <- zip [0 :: Int ..] subs] ++ rest) k
          pure (["if " ++ s ++ " != nil {"] ++ body ++ ["}"])
  CPCon k' targs subs -> do
    let struct = conRef ctx k' targs
    if all isWild subs
      then do
        body <- genPats ctx rest k
        pure (["if _, hg_ok := " ++ s ++ ".(" ++ struct ++ "); hg_ok {"] ++ body ++ ["}"])
      else do
        v <- freshName "v"
        body <- genPats ctx ([(v ++ ".F" ++ show i, q) | (i, q) <- zip [0 :: Int ..] subs] ++ rest) k
        -- a field matched by a pattern that looks at nothing, as (), leaves v unused
        pure (["if " ++ v ++ ", hg_ok := " ++ s ++ ".(" ++ struct ++ "); hg_ok {", "_ = " ++ v] ++ body ++ ["}"])
  where
    cond c = do
      body <- genPats ctx rest k
      pure (["if " ++ c ++ " {"] ++ body ++ ["}"])
    isWild CPWild = True
    isWild (CPCon "()" _ _) = True
    isWild _ = False

-- | Local bindings, declared first so they can refer to each other, then
-- assigned in dependency order. A function that returns an action gets its
-- run form too (see 'genRun').
genBinds :: Ctx -> [CBind] -> Gen (Ctx, [String])
genBinds ctx binds = do
  let ctx1 = bindLocals ctx [(n, ar) | CBind n _ ar _ <- binds]
      runs = [(n, ps, x) | CBind n _ ar (CLam ps r _) <- binds, ar > 0, length ps == ar, Just x <- [ioResult ctx r]]
      ctx' = ctx1 {cxRun = M.union (M.fromList [(n, (runName n, length ps)) | (n, ps, _) <- runs]) (cxRun ctx1)}
      names = [n | CBind n _ _ _ <- binds]
      sccs = stronglyConnComp
        [(b, n, filter (`elem` names) (coreRefs body)) | b@(CBind n _ _ body) <- binds]
      ordered = flattenSCCs sccs
      -- a function's group: those of its own binding group that may call it
      -- back, and the functions around, which may too
      groupOf n = S.union (cxGroup ctx) (S.fromList (n : concat [ms | CyclicSCC bs <- sccs, let ms = [m | CBind m _ _ _ <- bs], n `elem` ms]))
      decl (CBind n t ar _) =
        let (ps, r) = splitFun ar (zonk (progSubst (cxProg ctx)) t)
            ty = if ar == 0 then goTy ctx t else "func(" ++ commas (map (goTy ctx) ps) ++ ") " ++ goTy ctx r
         in "var " ++ mangle n ++ " " ++ ty
      runDecl (n, ps, x) = "var " ++ runName n ++ " func(" ++ commas (map (goTy ctx . snd) ps) ++ ") " ++ goTy ctx x
  assigns <- forM (zip ordered (tails' (map (\(CBind n _ _ _) -> n) ordered))) $ \(CBind n _ ar body, pending) ->
    let c = (noSelf ctx') {cxPending = S.union (S.fromList pending) (cxPending ctx')}
     in case body of
          CLam ps r inner | ar > 0 -> do
            let c' = c {cxGroup = groupOf n}
            fn <- genFunction c' (Just (n, ar)) [] ps r inner
            runFn <- case (M.lookup n (cxRun ctx'), ioResult ctx r) of
              (Just (rn, _), Just x) -> (\f -> [rn ++ " = func" ++ f]) <$> genRunFunction c' (Just (n, ar)) ps x inner
              _ -> pure []
            pure ((mangle n ++ " = func" ++ fn) : runFn)
          _ -> do
            e <- genExpr c body
            pure [mangle n ++ " = " ++ e]
  pure (ctx', map decl binds ++ map runDecl runs ++ concat assigns ++ ["_ = " ++ mangle n | n <- names] ++ ["_ = " ++ runName n | (n, _, _) <- runs])
  where
    -- each binding, with itself and the ones after it, which are not assigned yet
    tails' xs = [drop i xs | i <- [0 .. length xs - 1]]

-- Expressions -------------------------------------------------------------------------

genExpr :: Ctx -> CExpr -> Gen String
genExpr ctx e = case e of
  CLit l -> pure (genLit l)
  CNum n t _ -> pure (numLit ctx n t)
  CVar x ref t -> genVar ctx x ref t
  CCon k targs t -> genApp ctx e [] (Just (conArity k)) (\args -> pure (conValue ctx k targs args)) t
  CApp f args -> case f of
    -- s ++ t on strings, with t suspended, needs no suspension: Go's + is
    -- strict, and t is generated once (generating the suspension too would
    -- make a chain of ++ exponential)
    CVar "primAppend" (Inst [targ] _) _
      | [a, CDelay _ inner] <- args
      , TCon "String" [] <- zonk (progSubst (cxProg ctx)) targ -> do
          a' <- genExpr ctx a
          b' <- genExpr ctx inner
          pure ("(" ++ a' ++ " + " ++ b' ++ ")")
    -- the Prelude's && and ||, whose second argument is suspended, are Go's,
    -- which only computes it when it is needed
    CVar op _ _
      | op `elem` ["&&", "||"], Just (VKTop 2 _ _) <- M.lookup op (cxVars ctx), [a, CDelay _ inner] <- args -> do
          a' <- genExpr ctx a
          b' <- genExpr ctx inner
          pure ("(" ++ a' ++ " " ++ op ++ " " ++ b' ++ ")")
    -- a call to Go: functions given to it are generated as Go functions of
    -- all their arguments at once (see 'foreignArg')
    -- a bind or a *> of IO is a do block of two statements, whose first is
    -- run on the spot and whose second goes back to the trampoline
    CVar "primBindIO" (Inst [a, b] _) _ | isPrim ctx "primBindIO", [m, k] <- args -> case k of
      CLam [(x, t)] _ body -> genDo ctx b [CSBind x t m, CSExpr b body]
      _ -> do
        v <- freshName "b"
        genDo ctx b [CSBind v a m, CSExpr b (CApp k [CVar v (Inst [] []) a])]
    CVar "primThenIO" (Inst [_, b] _) _ | isPrim ctx "primThenIO", [m, n] <- args ->
      genDo ctx b [CSExpr tUnit m, CSExpr b (case n of CDelay _ x -> x; _ -> CForce n)]
    -- an action run where it is made, as runST makes one
    CVar "primRunIO" (Inst [a] _) _ | isPrim ctx "primRunIO", [m] <- args -> do
      ls <- genRun (noSelf ctx) (RReturn False) m
      pure $ case ls of
        [l] | Just v <- stripReturn l -> v
        _ -> "func() " ++ goTy ctx a ++ " {\n" ++ unlines ls ++ "}()"
    CVar x ref _
      | Just (VKForeign fo) <- M.lookup x (cxVars ctx), fArity fo > 0, length args >= fArity fo -> do
          let (now, later) = splitAt (fArity fo) args
              targs = refTypes ctx ref
              (params, _) = splitFun (fArity fo) (foreignInst fo targs)
          as <- zipWith3M (foreignArg ctx (isRuntimeSymbol fo)) (fst (splitFun (fArity fo) (fType fo))) params now
          foldM (\acc a -> (\a' -> acc ++ "(" ++ a' ++ ")") <$> genExpr ctx a) (foreignCall ctx fo targs True as) later
    CVar x ref t | Just ar <- knownArity x, ar > 0 ->
      genApp ctx f args (Just ar) (\as -> call ctx x ref t as) t
    -- a cell kept behind a pointer, given suspensions for its lazy fields
    -- (a list's cell and its tail), is one allocation with its thunks
    -- instead of one each
    CCon k targs t
      | length args == conArity k, any isDelay args
      , Just ci <- M.lookup k (progCons (cxProg ctx)), Just Pointer <- M.lookup (ciType ci) (cxUnboxed ctx) -> do
          parts <- forM (zip [0 :: Int ..] args) $ \case
            (i, CDelay ty inner) -> do
              th <- thunkValue ty inner
              pure (Right (i, ty, th))
            (i, a) -> Left . (,) i <$> genExpr ctx a
          let st = conRef ctx k targs
              (_, r) = splitFun (length args) (zonk (progSubst (cxProg ctx)) t)
              thunks = [(i, ty, th) | Right (i, ty, th) <- parts]
          pure $ "func() " ++ goTy ctx r ++ " {\n"
            ++ "hg_c := &struct{ c " ++ st ++ concat ["; t" ++ show i ++ " rt_thunk[" ++ goTy ctx ty ++ "]" | (i, ty, _) <- thunks] ++ " }{"
            ++ commas (("c: " ++ st ++ "{" ++ commas ["F" ++ show i ++ ": " ++ v | Left (i, v) <- parts] ++ "}") : ["t" ++ show i ++ ": " ++ th | (i, _, th) <- thunks])
            ++ "}\n"
            ++ concat ["hg_c.c.F" ++ show i ++ " = &hg_c.t" ++ show i ++ "\n" | (i, _, _) <- thunks]
            ++ "return &hg_c.c\n}()"
    CCon k targs t -> genApp ctx f args (Just (conArity k)) (\as -> pure (conValue ctx k targs as)) t
    _ -> do
      h <- genExpr ctx f
      applyAll h args
  CLam ps r body -> genLam ctx ps r body
  -- A value that is cheap to compute and cannot fail, such as a variable
  -- already computed or a constructor applied to such values, is computed
  -- now: a suspension that is already done is one allocation, and one that
  -- is not is two (the thunk and the closure).
  CDelay t inner -> case inner of
    _ | isValue inner -> do
          v <- genExpr ctx inner
          pure ("rt_ready[" ++ goTy ctx t ++ "](" ++ v ++ ")")
    CVar {} -> do
      v <- genExpr ctx inner
      pure ("rt_lazy(func() " ++ goTy ctx t ++ " { return " ++ v ++ " })")
    _ -> do
      ls <- genStmts (noSelf ctx) inner
      pure ("rt_lazy(func() " ++ goTy ctx t ++ " {\n" ++ unlines ls ++ "})")
  CForce inner -> (++ ".force()") <$> genExpr ctx inner
  CDo _ _ r stmts -> genDo ctx r stmts
  CFrac x t _ -> pure $ case zonk (progSubst (cxProg ctx)) t of
    TCon "Double" [] -> show x
    _ -> error "codegen: a decimal literal at a type other than Double"
  CMatch _ _ t -> iife t
  CLet _ _ t -> iife t
  CIf _ _ _ t -> iife t
  where
    knownArity x = case M.lookup x (cxVars ctx) of
      Just (VKTop a _ _) -> Just a
      Just (VKLocal a) -> Just a
      Just (VKForeign f) -> Just (fArity f)
      Just (VKPrim a) -> Just a
      Nothing -> Nothing
    conArity k = length (ciFields (progCons (cxProg ctx) M.! k))
    isDelay = \case
      CDelay {} -> True
      _ -> False
    -- a suspension as a thunk's value, to be kept inside another struct,
    -- computed now when that does the same (see CDelay)
    thunkValue ty inner
      | isValue inner = (\v -> "rt_thunk[" ++ goTy ctx ty ++ "]{v: " ++ v ++ ", state: 2}") <$> genExpr ctx inner
      | otherwise = do
          ls <- genStmts (noSelf ctx) inner
          pure ("rt_thunk[" ++ goTy ctx ty ++ "]{f: func() " ++ goTy ctx ty ++ " {\n" ++ unlines ls ++ "}}")
    -- computing it now does the same as later: it is total, cheap, and does
    -- not read a variable that is still being defined
    isValue = \case
      CLit _ -> True
      CNum {} -> True
      CFrac {} -> True
      CCon {} -> True
      CLam {} -> True
      CDelay {} -> True
      CVar x _ _
        | S.member x (cxPending ctx) -> False
        | otherwise -> case M.lookup x (cxVars ctx) of
            Just (VKLocal _) -> True
            Just (VKTop a _ _) -> a > 0
            Just (VKForeign f) -> fArity f > 0
            Just (VKPrim a) -> a > 0
            Nothing -> False
      CApp (CCon _ _ _) as -> all isValue as
      _ -> False
    iife t = do
      ls <- genStmts (noSelf ctx) e
      pure ("func() " ++ goTy ctx t ++ " {\n" ++ unlines ls ++ "}()")
    applyAll h [] = pure h
    applyAll h (a : as) = do
      a' <- genExpr ctx a
      applyAll (h ++ "(" ++ a' ++ ")") as

-- | A head that takes n arguments directly: saturated calls go straight to
-- it, partial ones go through a curried wrapper, extra arguments are applied
-- one by one to the result.
genApp :: Ctx -> CExpr -> [CExpr] -> Maybe Int -> ([String] -> Gen String) -> Type -> Gen String
genApp ctx _ args (Just n) mk t
  | length args >= n = do
      let (now, later) = splitAt n args
      as <- mapM (genExpr ctx) now
      h <- mk as
      foldM (\acc a -> (\a' -> acc ++ "(" ++ a' ++ ")") <$> genExpr ctx a) h later
  | otherwise = do
      names <- replicateM n (freshName "x")
      let (ps, r) = splitFun n (zonk (progSubst (cxProg ctx)) t)
      body <- mk names
      let lam = curried ctx (zip names ps) r body
      foldM (\acc a -> (\a' -> "(" ++ acc ++ ")(" ++ a' ++ ")") <$> genExpr ctx a) lam args
genApp ctx _ args Nothing mk _ = do
  h <- mk []
  foldM (\acc a -> (\a' -> acc ++ "(" ++ a' ++ ")") <$> genExpr ctx a) h args

curried :: Ctx -> [(String, Type)] -> Type -> String -> String
curried _ [] _ body = body
curried ctx ((n, p) : rest) r body =
  "func(" ++ n ++ " " ++ goTy ctx p ++ ") " ++ goTy ctx (foldr (TFun . snd) r rest)
    ++ " { return " ++ curried ctx rest r body ++ " }"

genVar :: Ctx -> Name -> VRef -> Type -> Gen String
genVar ctx x ref t = case M.lookup x (cxVars ctx) of
  Just (VKTop 0 _ True) -> pure (mangle x)
  Just (VKTop 0 _ False) -> pure (mangle x ++ insts ++ "(" ++ commas (dictArgs ctx ref) ++ ")")
  Just (VKLocal 0) -> pure (mangle x)
  Just (VKForeign f) | fArity f == 0 -> pure (foreignCall ctx f (refTypes ctx ref) True [])
  Just (VKPrim 0) -> call ctx x ref t []
  Just _ -> genExpr ctx (CApp (CVar x ref t) [])
  Nothing -> error ("codegen: unknown variable " ++ x)
  where
    insts = case ref of
      Inst ts _ -> typeArgs ctx ts
      SelfGroup -> if null (cxTParams ctx) then "" else "[" ++ commas (map tyVar (cxTParams ctx)) ++ "]"

-- | A saturated call to a known function.
call :: Ctx -> Name -> VRef -> Type -> [String] -> Gen String
call ctx x ref _ as = case M.lookup x (cxVars ctx) of
  Just (VKTop _ tps _) -> pure (mangle x ++ insts tps ++ "(" ++ commas (dictArgs ctx ref ++ as) ++ ")")
  Just (VKLocal _) -> pure (mangle x ++ "(" ++ commas as ++ ")")
  Just (VKForeign f) -> pure (foreignCall ctx f (refTypes ctx ref) False as)
  Just (VKPrim _) -> genPrim ctx x targs as
  Nothing -> error ("codegen: unknown function " ++ x)
  where
    targs = case ref of
      Inst ts _ -> map (zonk (progSubst (cxProg ctx))) ts
      SelfGroup -> []
    insts tps = case ref of
      Inst ts _ -> typeArgs ctx ts
      SelfGroup -> if null tps then "" else "[" ++ commas (map tyVar (cxTParams ctx)) ++ "]"

genPrim :: Ctx -> Name -> [Type] -> [String] -> Gen String
genPrim ctx x targs as = case (x, as) of
  (op, [a, b]) | Just o <- lookup op binops -> pure ("(" ++ a ++ " " ++ o ++ " " ++ b ++ ")")
  ("primNeg", [a]) -> pure ("(-" ++ a ++ ")")
  ("primDiv", [a, b]) -> pure ("rt_div(" ++ a ++ ", " ++ b ++ ")")
  ("primMod", [a, b]) -> pure ("rt_mod(" ++ a ++ ", " ++ b ++ ")")
  ("primShow", [a]) -> pure $ case targs of
    [TCon "Int" []] -> "rt_strconv.Itoa(" ++ a ++ ")"
    [TCon "Double" []] -> "rt_showDouble(" ++ a ++ ")"
    [TCon "Char" []] -> "rt_strconv.QuoteRune(" ++ a ++ ")"
    [TCon "String" []] -> "rt_strconv.Quote(" ++ a ++ ")"
    _ -> "rt_fmt.Sprint(" ++ a ++ ")"
  ("primIntToDouble", [a]) -> pure ("float64(" ++ a ++ ")")
  ("primTruncate", [a]) -> pure ("int(" ++ a ++ ")")
  ("putStrLn", [a]) -> pure (action ("rt_fmt.Println(" ++ a ++ ")"))
  ("putStr", [a]) -> pure (action ("rt_fmt.Print(" ++ a ++ ")"))
  ("getLine", []) -> pure "rt_getLine"
  ("primReturnIO", [a]) -> pure ("rt_pure" ++ typeArgs ctx targs ++ "(" ++ a ++ ")")
  ("primBindIO", [a, b]) -> pure ("rt_bind" ++ typeArgs ctx targs ++ "(" ++ a ++ ", " ++ b ++ ")")
  ("primThenIO", [a, b]) -> pure ("rt_then" ++ typeArgs ctx targs ++ "(" ++ a ++ ", " ++ b ++ ")")
  ("primRunIO", [a]) -> pure ("rt_run" ++ typeArgs ctx targs ++ "(" ++ a ++ ")")
  ("error", [a]) -> pure ("rt_error" ++ typeArgs ctx targs ++ "(" ++ a ++ ")")
  ("primAppend", [a, b]) -> case targs of
    [TCon "String" []] -> pure ("(" ++ a ++ " + " ++ b ++ ".force())")
    [TCon "[]" [el]] -> pure (mangle "append" ++ typeArgs ctx [el] ++ "(" ++ a ++ ", " ++ b ++ ")")
    _ -> pure ("rt_error[" ++ goTy ctx (case targs of (t : _) -> t; [] -> tUnit) ++ "](\"primAppend needs a String or a list\")")
  ("pack", [a]) -> pure ("rt_pack(" ++ a ++ ")")
  ("unpack", [a]) -> pure ("rt_unpack(" ++ a ++ ")")
  ("ord", [a]) -> pure ("int(" ++ a ++ ")")
  ("chr", [a]) -> pure ("rune(" ++ a ++ ")")
  _ -> error ("codegen: bad primitive call " ++ x)
  where
    binops =
      [ ("primEq", "=="), ("primNeq", "!="), ("primLt", "<"), ("primLe", "<="), ("primGt", ">")
      , ("primGe", ">="), ("primAdd", "+"), ("primSub", "-"), ("primMul", "*"), ("primFDiv", "/")
      , ("primQuot", "/"), ("primRem", "%") ]
    action e = "func() IOStep[struct{}] { " ++ e ++ "; return rt_done(struct{}{}) }"

-- Dictionaries -------------------------------------------------------------------------

resolveDict :: Ctx -> Dict -> Dict
resolveDict ctx = \case
  DHole h -> case IM.lookup h (progSolved (cxProg ctx)) of
    Just d -> resolveDict ctx d
    Nothing -> error ("codegen: unsolved constraint " ++ show h)
  d -> d

-- | Specialisation resolves every dictionary at compile time.
dictArgs :: Ctx -> VRef -> [String]
dictArgs ctx = \case
  Inst _ ds -> map (genDict ctx) ds
  SelfGroup -> []

genDict :: Ctx -> Dict -> String
genDict ctx d = error ("codegen: a dictionary at run time: " ++ show (resolveDict ctx d))

numLit :: Ctx -> Integer -> Type -> String
numLit ctx n t = case zonk (progSubst (cxProg ctx)) t of
  TCon "Int" [] -> show n
  TCon "Double" [] -> show n ++ ".0"
  _ -> error "codegen: a number literal at a type other than Int or Double"

-- | Whether a Go function from outside the runtime may make the program run
-- on several goroutines: any that is given a Hago function or action, which
-- Go code could call from another goroutine (net/http calls a handler on
-- one per request).
startsGoroutines :: Foreign -> Bool
startsGoroutines f = not (isRuntimeSymbol f) && any callable (fst (splitFun (fArity f) (fType f)))
  where
    callable = \case
      TFun _ _ -> True
      TCon "IO" _ -> True
      TCon _ ts -> any callable ts
      _ -> False

-- | The types a use of a polymorphic name instantiates its variables with.
refTypes :: Ctx -> VRef -> [Type]
refTypes ctx = \case
  Inst ts _ -> map (zonk (progSubst (cxProg ctx))) ts
  SelfGroup -> []

-- | A call to a Go function. A polymorphic one is a generic Go function whose
-- type parameters are the Hago type variables in the order they first appear
-- in its signature, and it is given them explicitly: Go cannot infer a type
-- parameter that only the result has (newEmptyMVar :: IO (MVar a)).
foreignCall :: Ctx -> Foreign -> [Type] -> Bool -> [String] -> String
foreignCall ctx f targs adapted as0 = case declared of
  -- the conventions (IO (), Either for an error) follow the declared type:
  -- takeMVar :: MVar a -> IO a stays a plain call at a = Either e b
  TCon "IO" [TCon "()" []] -> "func() IOStep[struct{}] { " ++ goCall ++ "; return rt_done(struct{}{}) }"
  TCon "IO" [TCon "Either" [_, _]] ->
    "func() IOStep[" ++ goTy ctx t ++ "] { return rt_done(func() " ++ goTy ctx t ++ " {\n" ++ eitherBody t ++ "}()) }"
  TCon "IO" [_] -> "func() IOStep[" ++ goTy ctx t ++ "] { return rt_done[" ++ goTy ctx t ++ "](" ++ goCall ++ ") }"
  TCon "Either" [_, _] -> "func() " ++ goTy ctx t ++ " {\n" ++ eitherBody t ++ "}()"
  _ -> goCall
  where
    (declared, t, goCall, eitherBody) = foreignParts ctx f targs adapted as0

-- | A call to Go that makes an action, run at once (see 'genRun'): what to
-- do, and then the value of its result.
foreignRun :: Ctx -> Foreign -> [Type] -> [String] -> ([String], String)
foreignRun ctx f targs as = case declared of
  TCon "IO" [TCon "()" []] -> ([goCall], "struct{}{}")
  TCon "IO" [TCon "Either" [_, _]] -> ([], "func() " ++ goTy ctx t ++ " {\n" ++ eitherBody t ++ "}()")
  _ -> ([], goCall)
  where
    (declared, t, goCall, eitherBody) = foreignParts ctx f targs True as

-- | Whether a function from Go makes an action.
foreignIO :: Foreign -> Bool
foreignIO f = case snd (splitFun (fArity f) (fType f)) of
  TCon "IO" _ -> True
  _ -> False

-- | The type a call to Go was declared with, the type of what it gives (in
-- an action or not), the call, and the body of a Go function that makes an
-- Either from a Go function that returns an error.
foreignParts :: Ctx -> Foreign -> [Type] -> Bool -> [String] -> (Type, Type, String, Type -> String)
foreignParts ctx f targs adapted as0 = (declared, t, goCall, eitherBody)
  where
    (_, declared) = splitFun (fArity f) (fType f)
    t = case r of TCon "IO" [x] -> x; x -> x
    (params, r) = splitFun (fArity f) (foreignInst f targs)
    isIO = case r of TCon "IO" _ -> True; _ -> False
    -- arguments already made into what Go expects, or values to adapt
    as = if adapted then as0 else zipWith3 (callback ctx (isRuntimeSymbol f)) (fst (splitFun (fArity f) (fType f))) params as0
    sym = snd (splitSymbol (fSymbol f)) ++ (if length targs == length (fVars f) then typeArgs ctx targs else "")
    goCall = case (fSymbol f, as) of
      -- ".Body.Close()": a selector on the first argument, a field or a method
      ('.' : _, recv : rest) -> "(" ++ recv ++ ")" ++ fSymbol f ++ (if null rest then "" else "(" ++ commas rest ++ ")")
      ('.' : _, []) -> error ("codegen: the selector " ++ fSymbol f ++ " needs a value to select from")
      _ | fArity f == 0 && not isIO -> sym
      _ -> sym ++ "(" ++ commas as ++ ")"
    -- a Go function that returns (T, error) is an Either String T; one that
    -- returns only an error is an Either String ()
    eitherBody e =
      let targsOf = case e of TCon _ ts -> ts; _ -> []
          unitRight = case declared of
            TCon "IO" [TCon "Either" [_, TCon "()" []]] -> True
            TCon "Either" [_, TCon "()" []] -> True
            _ -> False
       in unlines
            [ (if unitRight then "hg_err := " else "hg_v, hg_err := ") ++ goCall
            , "if hg_err != nil { return " ++ conValue ctx "Left" targsOf ["hg_err.Error()"] ++ " }"
            , "return " ++ conValue ctx "Right" targsOf [if unitRight then "struct{}{}" else "hg_v"] ]

-- | A Hago function or action already computed, given to a Go function: see
-- 'foreignArg', which makes better code when it sees the function's source.
--
-- The shape of what Go gets is the declared type's (decl), with the types of
-- this call (ty): a parameter declared a -> b takes a function of one
-- argument even where b is a function, and one declared a takes any value
-- as it is.
callback :: Ctx -> Bool -> Type -> Type -> String -> String
callback ctx runtime decl ty a = case decl of
  TFun _ _ | runtime, [_] <- args -> a
  TFun _ _ -> goFunc ctx runtime args res (\ps -> "(" ++ a ++ ")" ++ concat ["(" ++ p ++ ")" | p <- ps])
  TCon "IO" [_] | not runtime -> goFunc ctx runtime [] ty (const a)
  _ -> a
  where
    (args, res) = splitFun (arrows decl) ty

zipWith3M :: Applicative m => (a -> b -> c -> m d) -> [a] -> [b] -> [c] -> m [d]
zipWith3M f as bs cs = sequenceA (zipWith3 f as bs cs)

-- | A Go function of all the arguments at once, whose body applies the Hago
-- function (given the parameter names). For a Go function from outside the
-- runtime, an action it makes is run and its result returned (nothing for
-- ()), and a failure in it ends the program, as in any thread: Go may call
-- it from any goroutine (net/http calls a handler on one per request). The
-- runtime's functions get the action itself.
goFunc :: Ctx -> Bool -> [Type] -> Type -> ([String] -> String) -> String
goFunc ctx runtime args res apply =
  "func(" ++ commas [p ++ " " ++ goTy ctx x | (p, x) <- zip ps args] ++ ")" ++ resTy
    ++ " {\n" ++ (if runtime then "" else "defer rt_failed()\n") ++ body ++ "\n}"
  where
    ps = ["hg_p" ++ show i | i <- [0 .. length args - 1]]
    applied = apply ps
    (resTy, body) = case res of
      TCon "IO" [TCon "()" []] | not runtime -> ("", "rt_run(" ++ applied ++ ")")
      TCon "IO" [x] | not runtime -> (" " ++ goTy ctx x, "return rt_run(" ++ applied ++ ")")
      x -> (" " ++ goTy ctx x, "return " ++ applied)

-- | The Go type of what 'goFunc' makes.
goFuncType :: Ctx -> Bool -> [Type] -> Type -> String
goFuncType ctx runtime args res = "func(" ++ commas (map (goTy ctx) args) ++ ")" ++ case res of
  TCon "IO" [TCon "()" []] | not runtime -> ""
  TCon "IO" [x] | not runtime -> " " ++ goTy ctx x
  x -> " " ++ goTy ctx x

-- | A Go function's type, with its type variables given.
foreignInst :: Foreign -> [Type] -> Type
foreignInst f targs = substTV (M.fromList (zip (fVars f) targs)) (fType f)

-- | The runtime's own functions take Hago's actions as they are; any other Go
-- function gets them made into Go functions that run them.
isRuntimeSymbol :: Foreign -> Bool
isRuntimeSymbol f = "rt_" `isPrefixOf` fSymbol f

-- | An argument of a call to Go. A function is given as a Go function of all
-- its arguments at once; when its source is a lambda or a known function,
-- that function is generated directly, without the curried closures a
-- function value has, which would allocate one per argument on each call.
foreignArg :: Ctx -> Bool -> Type -> Type -> CExpr -> Gen String
foreignArg ctx runtime decl ty e = case decl of
  TFun _ _
    | [_] <- args, runtime -> genExpr ctx e
    | otherwise -> case e of
        CLam ps _ body | length ps == n -> do
          let ctx' = noSelf (bindLocals ctx [(p, 0) | (p, _) <- ps])
          ls <- genStmts ctx' body
          let direct = "func(" ++ commas [mangle p ++ " " ++ goTy ctx t | (p, t) <- ps] ++ ") " ++ goTy ctx res ++ " {\n" ++ unlines ls ++ "}"
          pure (if runtime then direct else goFunc ctx runtime args res (\qs -> direct ++ "(" ++ commas qs ++ ")"))
        CVar x ref t | Just k <- arityOf x, k == n -> do
          let names = ["hg_p" ++ show i | i <- [0 .. n - 1]]
          body <- call ctx x ref t names
          pure (goFunc ctx runtime args res (const body))
        -- a known function given some of its arguments: those are computed
        -- once, before the Go function is made
        CApp (CVar x ref t) given | Just k <- arityOf x, k == length given + n -> do
          vals <- mapM (genExpr ctx) given
          vars <- mapM (const (freshName "a")) given
          let names = ["hg_p" ++ show i | i <- [0 .. n - 1]]
          body <- call ctx x ref t (vars ++ names)
          pure ("func() " ++ goFuncType ctx runtime args res ++ " {\n" ++ unlines [v ++ " := " ++ a | (v, a) <- zip vars vals]
                  ++ "return " ++ goFunc ctx runtime args res (const body) ++ "\n}()")
        _ -> callback ctx runtime decl ty <$> genExpr ctx e
  TCon "IO" [_] | not runtime -> callback ctx runtime decl ty <$> genExpr ctx e
  _ -> genExpr ctx e
  where
    (args, res) = splitFun (arrows decl) ty
    n = length args
    arityOf x = case M.lookup x (cxVars ctx) of
      Just (VKTop a _ _) -> Just a
      Just (VKLocal a) -> Just a
      Just (VKPrim a) -> Just a
      _ -> Nothing

conValue :: Ctx -> Name -> [Type] -> [String] -> String
conValue ctx k targs as = case k of
  "True" -> "true"
  "False" -> "false"
  "()" -> "struct{}{}"
  _ | Just ci <- M.lookup k (progCons (cxProg ctx)), Just Pointer <- M.lookup (ciType ci) (cxUnboxed ctx) ->
        if null (ciFields ci)
          then goTy ctx (TCon (ciType ci) targs) ++ "(nil)"
          else "&" ++ conRef ctx k targs ++ "{" ++ commas as ++ "}"
  _ | Just ci <- M.lookup k (progCons (cxProg ctx)), Just Tagged <- M.lookup (ciType ci) (cxUnboxed ctx) ->
        typeName (ciType ci) ++ typeArgs ctx targs ++ "{" ++ commas (("tag: " ++ show (ciTag ci)) : [taggedField ci i ++ ": " ++ a | (i, a) <- zip [0 :: Int ..] as]) ++ "}"
  _ -> conRef ctx k targs ++ "{" ++ commas as ++ "}"

-- | The field of a tagged struct that holds a constructor's i-th field.
taggedField :: ConInfo -> Int -> String
taggedField ci i = "K" ++ show (ciTag ci) ++ "_" ++ show i

genLam :: Ctx -> [(Name, Type)] -> Type -> CExpr -> Gen String
genLam ctx ps r body = go ps
  where
    ctx' = noSelf (bindLocals ctx [(p, 0) | (p, _) <- ps])
    go [] = error "genLam: no parameters"
    go [(p, t)] = do
      ls <- genStmts ctx' body
      pure ("func(" ++ mangle p ++ " " ++ goTy ctx t ++ ") " ++ goTy ctx r ++ " {\n" ++ unlines ls ++ "}")
    go ((p, t) : rest) = do
      inner <- go rest
      let restTy = foldr (TFun . snd) r rest
      pure ("func(" ++ mangle p ++ " " ++ goTy ctx t ++ ") " ++ goTy ctx restTy ++ " { return " ++ inner ++ " }")

genDo :: Ctx -> Type -> [CStmt] -> Gen String
genDo ctx0 r stmts = do
  ls <- go (noSelf ctx0) stmts
  pure ("func() IOStep[" ++ rt ++ "] {\n" ++ unlines ls ++ "}")
  where
    rt = goTy ctx0 r
    -- the last action is returned to rt_run instead of called: a tail call
    go _ [] = pure []
    go ctx [CSExpr _ e] = case e of
      CApp (CVar n _ _) [x] | n `elem` ["primReturnIO", instMethodName "inst_Applicative_IO" "pure"] ->
        (\x' -> ["return rt_done[" ++ rt ++ "](" ++ x' ++ ")"]) <$> genExpr ctx x
      _ -> (\e' -> ["return rt_next[" ++ rt ++ "](" ++ e' ++ ")"]) <$> genExpr ctx e
    -- the others are run on the spot (see 'genRun')
    go ctx (s : rest) = case s of
      CSExpr _ e -> (++) <$> genRun ctx RDiscard e <*> go ctx rest
      CSBind "_" _ e -> (++) <$> genRun ctx RDiscard e <*> go ctx rest
      CSBind x t e -> (++) <$> genRun ctx (RBind x t) e <*> go (bindLocals ctx [(x, 0)]) rest
      CSLet bs -> do
        (ctx', ls) <- genBinds ctx bs
        (ls ++) <$> go ctx' rest

-- Running actions directly ------------------------------------------------------

-- An action is a closure that the trampoline (rt_run) calls, and a function
-- that returns one returns a closure made on every call. Where an action is
-- run as soon as it is made (a statement in a do block, the action a
-- function returns when that function's own action is run), it does not
-- need to exist: 'genRun' makes the statements that run it. A function
-- that returns an action also gets a run form, hgrun_f, which runs what f
-- would return and returns its result; a call to f that is run at once
-- calls hgrun_f instead.
--
-- The trampoline is there so that loops written as recursion, and
-- functions that end calling each other, run in constant stack. In a run
-- form, a tail call to itself becomes a loop, as in a pure function; one to
-- a function that cannot call it back (a later one in dependency order) is
-- a direct call, so a chain of them is as long as the program has
-- functions. A tail call to one that may call it back goes through the
-- trampoline, and so does every action whose source is not known (a
-- parameter, a suspension). Once on the trampoline, a loop stays on it.

-- | What becomes of an action's result: returned (True: from a run form,
-- where tail calls loop; False: from a Go function called on the spot),
-- dropped, or bound to a variable of a type.
data RunK = RReturn Bool | RDiscard | RBind Name Type

runName :: Name -> String
runName n = "hgrun_" ++ mangle n

-- | What an action of this type gives, if it is one.
ioResult :: Ctx -> Type -> Maybe Type
ioResult ctx t = case zonk (progSubst (cxProg ctx)) t of
  TCon "IO" [x] -> Just x
  _ -> Nothing

-- | A top-level function that returns an action has a run form.
hasRunForm :: Program -> TopBind -> Bool
hasRunForm prog b = case tbBody b of
  CLam ps r _ -> tbArity b > 0 && not (tbShared b) && length ps == tbArity b && case zonk (progSubst prog) r of
    TCon "IO" [_] -> True
    _ -> False
  _ -> False

isPrim :: Ctx -> Name -> Bool
isPrim ctx n = case M.lookup n (cxVars ctx) of
  Just (VKPrim _) -> True
  _ -> False

stripReturn :: String -> Maybe String
stripReturn l = if "return " `isPrefixOf` l then Just (drop 7 l) else Nothing

-- | The parameters, result type and body of a run form.
genRunFunction :: Ctx -> Maybe (Name, Int) -> [(Name, Type)] -> Type -> CExpr -> Gen String
genRunFunction ctx self ps x inner = do
  saved <- gets gsLoop
  modify (\s -> s {gsLoop = False})
  let ctx' = (bindLocals ctx [(p, 0) | (p, _) <- ps]) {cxSelf = self, cxSelfParams = map fst ps}
  ls <- genRun ctx' (RReturn True) inner
  looped <- gets gsLoop
  modify (\s -> s {gsLoop = saved})
  let params = commas [mangle p ++ " " ++ goTy ctx pt | (p, pt) <- ps]
      body = if looped then ["for {"] ++ ls ++ ["}"] else ls
  pure (unlines (["(" ++ params ++ ") " ++ goTy ctx x ++ " {"] ++ body ++ ["}"]))

-- | Statements that run the action and do with its result what k says.
genRun :: Ctx -> RunK -> CExpr -> Gen [String]
genRun ctx k e = case e of
  CDo m _ _ stmts | Just _ <- ioResult ctx (tApp m tUnit) -> sequenced stmts
  CApp (CVar "primReturnIO" _ _) [x] | isPrim ctx "primReturnIO" -> finish <$> genExpr ctx x
  CApp (CVar "primBindIO" _ _) [m, CLam [(x, t)] _ body] | isPrim ctx "primBindIO" ->
    sequenced [CSBind x t m, CSExpr t body]
  CApp (CVar "primBindIO" (Inst [a, _] _) _) [m, f] | isPrim ctx "primBindIO" -> do
    v <- freshName "b"
    sequenced [CSBind v a m, CSExpr a (CApp f [CVar v (Inst [] []) a])]
  CApp (CVar "primThenIO" _ _) [a, b] | isPrim ctx "primThenIO" ->
    sequenced [CSExpr tUnit a, CSExpr tUnit (case b of CDelay _ x -> x; _ -> CForce b)]
  CIf c a b _ -> case k of
    RBind x t -> onTheSpot x t
    RDiscard -> do
      c' <- genExpr ctx c
      as <- genRun ctx k a
      bs <- genRun ctx k b
      pure (["if " ++ c' ++ " {"] ++ as ++ ["} else {"] ++ bs ++ ["}"])
    RReturn _ -> do
      c' <- genExpr ctx c
      as <- genRun ctx k a
      bs <- genRun ctx k b
      pure (["if " ++ c' ++ " {"] ++ as ++ ["}"] ++ bs)
  CMatch ss rows t -> case k of
    RBind x xt -> onTheSpot x xt
    RDiscard -> do
      ls <- genMatch (\c -> genRun c (RReturn False)) (noSelf ctx) ss rows
      pure (["func() " ++ goTy ctx (fromMaybe tUnit (ioResult ctx t)) ++ " {"] ++ ls ++ ["}()"])
    RReturn _ -> genMatch (\c -> genRun c k) ctx ss rows
  CLet bs body _ -> case k of
    RBind x t -> onTheSpot x t
    RDiscard -> do
      (ctx', ls) <- genBinds ctx bs
      b <- genRun ctx' k body
      pure (["{"] ++ ls ++ b ++ ["}"])
    RReturn _ -> do
      (ctx', ls) <- genBinds ctx bs
      (ls ++) <$> genRun ctx' k body
  CForce x -> (\x' -> finish ("rt_run(" ++ x' ++ ".force())")) <$> genExpr ctx x
  CApp (CVar f ref _) args
    -- a tail call to itself: round the loop again
    | RReturn True <- k, Just (self, n) <- cxSelf ctx, f == self, length args == n, M.member f (cxRun ctx) -> do
        as <- mapM (genExpr ctx) args
        modify (\s -> s {gsLoop = True})
        pure [commas (map mangle (cxSelfParams ctx)) ++ " = " ++ commas as, "continue"]
    | Just (rn, n) <- M.lookup f (cxRun ctx), length args == n -> case k of
        RReturn True | S.member f (cxGroup ctx) -> trampolined
        _ -> do
          as <- mapM (genExpr ctx) args
          pure (finish (runCall ctx rn f ref as))
    | Just (VKForeign fo) <- M.lookup f (cxVars ctx), fArity fo == length args, fArity fo > 0, foreignIO fo -> do
        let targs = refTypes ctx ref
            (params, _) = splitFun (fArity fo) (foreignInst fo targs)
        as <- zipWith3M (foreignArg ctx (isRuntimeSymbol fo)) (fst (splitFun (fArity fo) (fType fo))) params args
        let (ls, v) = foreignRun ctx fo targs as
        pure (ls ++ finishValue v)
    | f `elem` ["putStrLn", "putStr"], isPrim ctx f, [a] <- args -> do
        a' <- genExpr ctx a
        pure (("rt_fmt." ++ (if f == "putStrLn" then "Println(" else "Print(") ++ a' ++ ")") : finishValue "struct{}{}")
  CVar f ref _
    | Just (VKForeign fo) <- M.lookup f (cxVars ctx), fArity fo == 0, foreignIO fo -> do
        let (ls, v) = foreignRun ctx fo (refTypes ctx ref) []
        pure (ls ++ finishValue v)
  _ -> trampolined
  where
    trampolined = (\e' -> finish ("rt_run(" ++ e' ++ ")")) <$> genExpr ctx e
    finish v = case k of
      RReturn _ -> ["return " ++ v]
      RDiscard -> ["_ = " ++ v]
      RBind x _ -> [mangle x ++ " := " ++ v, "_ = " ++ mangle x]
    finishValue v = case k of
      RDiscard | v == "struct{}{}" -> []
      _ -> finish v
    -- statements run one after the other: in a block of their own, since
    -- they bind names, or in a Go function called on the spot when the
    -- result is bound to a name outside it
    sequenced stmts = case k of
      RBind x t -> onTheSpot x t
      _ -> (\ls -> ["{"] ++ ls ++ ["}"]) <$> runStmts ctx k stmts
    onTheSpot x t
      -- nothing to bind: () is ()
      | TCon "()" [] <- zonk (progSubst (cxProg ctx)) t = do
          ls <- genRun ctx RDiscard e
          pure (ls ++ [mangle x ++ " := struct{}{}", "_ = " ++ mangle x])
      | otherwise = do
          ls <- genRun (noSelf ctx) (RReturn False) e
          pure ([mangle x ++ " := func() " ++ goTy ctx t ++ " {"] ++ ls ++ ["}()", "_ = " ++ mangle x])

-- | The statements of a do block, run in order; the last one's result is
-- the block's.
runStmts :: Ctx -> RunK -> [CStmt] -> Gen [String]
runStmts ctx k = \case
  [] -> pure []
  [CSExpr _ e] -> genRun ctx k e
  CSExpr _ e : rest -> (++) <$> genRun ctx RDiscard e <*> runStmts ctx k rest
  CSBind "_" _ e : rest -> (++) <$> genRun ctx RDiscard e <*> runStmts ctx k rest
  CSBind x t e : rest -> (++) <$> genRun ctx (RBind x t) e <*> runStmts (bindLocals ctx [(x, 0)]) k rest
  CSLet bs : rest -> do
    (ctx', ls) <- genBinds ctx bs
    (ls ++) <$> runStmts ctx' k rest

-- | A call to a run form.
runCall :: Ctx -> String -> Name -> VRef -> [String] -> String
runCall ctx rn x ref as = case M.lookup x (cxVars ctx) of
  Just (VKTop _ tps _) -> rn ++ insts tps ++ "(" ++ commas (dictArgs ctx ref ++ as) ++ ")"
  _ -> rn ++ "(" ++ commas as ++ ")"
  where
    insts tps = case ref of
      Inst ts _ -> typeArgs ctx ts
      SelfGroup -> if null tps then "" else "[" ++ commas (map tyVar (cxTParams ctx)) ++ "]"

-- Literals ---------------------------------------------------------------------------

genLit :: Lit -> String
genLit = \case
  LInt n -> show n
  LDouble d -> show d
  LChar c
    | c == '\'' -> "'\\''"
    | c == '\\' -> "'\\\\'"
    | c >= ' ' && c <= '~' -> ['\'', c, '\'']
    | otherwise -> "rune(" ++ show (ord c) ++ ")"
  LStr s -> "\"" ++ concatMap esc s ++ "\""
  where
    esc '"' = "\\\""
    esc '\\' = "\\\\"
    esc '\n' = "\\n"
    esc '\t' = "\\t"
    esc c
      | c >= ' ' && c <= '~' = [c]
      | ord c < 0x10000 = "\\u" ++ pad 4 (showHex (ord c) "")
      | otherwise = "\\U" ++ pad 8 (showHex (ord c) "")
    pad n s = replicate (n - length s) '0' ++ s

-- | Every outermost type inside a value.
typesIn :: forall a. Data a => a -> [Type]
typesIn = go
  where
    go :: forall b. Data b => b -> [Type]
    go x = case eqT @b @Type of
      Just Refl -> [x]
      Nothing -> concat (gmapQ go x)
