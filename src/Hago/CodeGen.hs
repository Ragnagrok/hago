-- | What a name refers to, and with how many arguments it is called directly.
data VK
  = VKTop Int [Name] Bool  -- ^ top-level: arity, type parameters, whether it is a shared value
  | VKLocal Int        -- ^ local: arity (0 for plain values)
  | VKForeign Foreign
  | VKPrim Int

data Ctx = Ctx
  { cxVars :: M.Map Name VK
  , cxSelf :: Maybe (Name, Int)   -- ^ function whose self tail calls become a loop
  , cxSelfParams :: [Name]        -- ^ its parameters, assigned before going round again
  , cxTParams :: [Name]
  , cxProg :: Program
  , cxPending :: S.Set Name   -- ^ local variables declared but not assigned yet
  , cxUnboxed :: M.Map Name Repr   -- ^ the data types kept by value (see 'dataReprs')
  , cxRun :: M.Map Name (String, Int)
    -- ^ functions that return an action and have a run form (see 'genRun'):
    -- its Go name and how many arguments it takes
  , cxGroup :: S.Set Name
    -- ^ while generating a run form, the functions a tail call to which goes
    -- through the trampoline: those that may call this one back
  , cxConfined :: M.Map Name [Bool]
    -- ^ for each top-level function, which of its parameters, mutable
    -- structures, it keeps in the thread that calls it (see 'unshare')
  , cxLoop :: (Int, M.Map Name (Int, [String]))
    -- ^ while generating a run form inside a loop over several (see
    -- 'genRunLoop'): which one this is, and for each, which it is and the
    -- variables its arguments are given in for the next round
  }

-- | gsLoop: a self tail call went round the loop; gsJumped: the tail calls
-- from one function of the loop to another, by their place in it (see
-- 'genRunLoop').
data GS = GS {gsNext :: Int, gsLoop :: Bool, gsJumped :: [(Int, Int)]}

type Gen = State GS

-- | The runtime copied into a program.
data Runtime = Runtime
  { rtCore :: Bool -> String
    -- ^ what every program gets, in two versions: a program that may run on
    -- several goroutines gets the one whose thunks any of them can force
  , rtConcurrentSymbols :: [String]
    -- ^ the functions only the concurrent version has (threads, MVars, channels)
  , rtParts :: [RuntimePart]
  }

-- | A part of the runtime that a program gets only if it calls one of its
-- functions, so that every program does not import net/http or crypto.
data RuntimePart = RuntimePart
  { rpSource :: String
  , rpSymbols :: [String] -- ^ the functions and types it defines
  , rpImports :: [String] -- ^ its import lines, as @rt_http "net/http"@
  }

-- | The Go program.
generate :: Runtime -> Program -> String
generate runtime prog =
  unlines (header ++ [rtCore runtime concurrent] ++ map rpSource parts ++ tupleDecls ++ dataDecls ++ hkDecls ++ foreignUses ++ tops ++ loopFns ++ initBlock ++ mainFn)
  where
    usedForeign = S.fromList (concatMap (coreRefs . tbBody) (progBinds prog))
    used = [f | (n, f) <- M.toList (progForeign prog), S.member n usedForeign]
    concurrent = any (\f -> fSymbol f `elem` rtConcurrentSymbols runtime || startsGoroutines f) used
    parts = [p | p <- rtParts runtime, any ((`elem` rpSymbols p) . fSymbol) used]
    coreImports = map (takeWhile (/= ' ')) baseImports
    partImports = nub [i | p <- parts, i <- rpImports p, takeWhile (/= ' ') i `notElem` coreImports]
    foreignPkgs = nub
      [ pkg
      | sym <- map fSymbol (M.elems (progForeign prog)) ++ [s | di <- M.elems (progData prog), Just s <- [diForeign di]]
      , take 1 sym /= "."
      , let (pkg, _) = splitSymbol (dropWhile (== '*') sym), pkg /= "" ]
    header =
      [ "// Code generated by hago. DO NOT EDIT."
      , "package main"
      , "import (" ]
        ++ baseImports
        ++ (if concurrent then ["rt_reflect \"reflect\"", "rt_syscall \"syscall\""] else [])
        ++ partImports
        ++ [show p | p <- foreignPkgs]
        ++ [")"]
    baseImports =
      [ "rt_bufio \"bufio\""
      , "rt_fmt \"fmt\""
      , "rt_os \"os\""
      , "rt_debug \"runtime/debug\""
      , "rt_runtime \"runtime\""
      , "rt_metrics \"runtime/metrics\""
      , "rt_strconv \"strconv\""
      , "rt_strings \"strings\""
      , "rt_sync \"sync\""
      , "rt_big \"math/big\""
      , "rt_filepath \"path/filepath\""
      , "rt_time \"time\""
      , "rt_atomic \"sync/atomic\""
      , "rt_iter \"iter\""
      , "rt_slices \"slices\""
      , "rt_unsafe \"unsafe\"" ]
    -- every imported package is used, even by a program that calls none of
    -- its functions; a generic function cannot be named without its types
    foreignUses =
      [ "var _ = " ++ short | f <- M.elems (progForeign prog), fArity f > 0, null (fVars f)
      , take 1 (fSymbol f) /= "."
      , let (pkg, short) = splitSymbol (fSymbol f), pkg /= "" ]
        ++ [ "var _ " ++ goTypeSymbol s ++ (if null (diParams di) then "" else "[" ++ commas (map (const "any") (diParams di)) ++ "]")
           | di <- M.elems (progData prog), Just s <- [diForeign di], '.' `elem` s ]
    ctx0 = Ctx
      { cxVars = M.unions
          [ M.fromList [(tbName b, VKTop (tbArity b) (tbParams b) (tbShared b)) | b <- progBinds prog]
          , M.map VKForeign (progForeign prog)
          , M.fromList [(n, VKPrim (arrows t)) | (n, Forall _ _ t) <- M.toList primSchemes] ]
      , cxSelf = Nothing
      , cxSelfParams = []
      , cxTParams = []
      , cxProg = prog
      , cxPending = S.empty
      , cxUnboxed = unboxed
      , cxRun = M.fromList [(tbName b, (runName (tbName b), tbArity b)) | b <- progBinds prog, hasRunForm prog b]
      , cxGroup = S.empty
      , cxConfined = confinedParams ctx0 {cxConfined = M.empty} prog
      , cxLoop = (0, M.empty)
      }
    -- a struct for each size of tuple the program uses
    tupleDecls =
      [ "type Tup" ++ show n ++ "[" ++ commas ["T" ++ show i | i <- [1 .. n]] ++ " any] struct{ "
          ++ intercalate "; " ["F" ++ show (i - 1) ++ " T" ++ show i | i <- [1 .. n]] ++ " }"
      | n <- sort (nub (concatMap tupleSizes (typesIn prog {progCons = M.filterWithKey (\k _ -> tupleArity k == Nothing) (progCons prog)}))) ]
    tupleSizes = \case
      TCon c ts -> maybe [] pure (tupleArity c) ++ concatMap tupleSizes ts
      TFun a b -> tupleSizes a ++ tupleSizes b
      TApp f x -> tupleSizes f ++ tupleSizes x
      _ -> []
    unboxed = dataReprs prog
    dataDecls = concatMap (genData prog unboxed)
      [(n, d) | (n, d) <- M.toList (progData prog), n `notElem` ["[]", "Bool"], null (hkPositions prog n), diForeign d == Nothing]
    hkDecls = concatMap (genHkData prog) (hkInstances prog)
    (loopFns, tops, inits, mainRun) = flip evalState (GS 0 False []) $ do
      loops <- forM topLoops $ \bs -> case bs of
        [] -> pure Nothing
        b0 : _ -> do
          let name = "hgloop_" ++ mangle (tbName b0)
              ctx = ctx0 {cxGroup = groupOf (tbName b0), cxTParams = tbParams b0}
          r <- genRunLoop False ctx name [(tbName b, ps, inner) | b <- bs, CLam ps _ inner <- [tbBody b]] (runResult b0)
          pure (fmap (\(fn, entries) -> ("func " ++ name ++ tparamList (tbParams b0) ++ fn, entries)) r)
      ploops <- forM pureLoops $ \bs -> case bs of
        [] -> pure Nothing
        b0 : _ -> do
          let name = "hgloop_" ++ mangle (tbName b0)
              ctx = ctx0 {cxGroup = groupOf (tbName b0), cxTParams = tbParams b0}
          r <- genRunLoop True ctx name [(tbName b, ps, inner) | b <- bs, CLam ps _ inner <- [tbBody b]] (pureResult b0)
          pure (fmap (\(fn, es) -> ("func " ++ name ++ tparamList (tbParams b0) ++ fn, es)) r)
      let entries = M.fromList (concat [es | Just (_, es) <- loops])
          pentries = M.fromList (concat [es | Just (_, es) <- ploops])
      (ts, is) <- unzip <$> mapM (\b -> genTop ctx0 {cxGroup = groupOf (tbName b)} (S.member (tbName b) deferred) (M.lookup (tbName b) pentries) (M.lookup (tbName b) entries) b) (filter (not . isMainRun) initOrder)
      ms <- case mainBind of
        Just b | isMainRun b -> Just <$> genRun ctx0 {cxGroup = groupOf "main"} RDiscard (tbBody b)
        _ -> pure Nothing
      pure ([fn | Just (fn, _) <- loops ++ ploops], ts, is, ms)
    -- main, when nothing refers to it, is not an action made and then run:
    -- its body is run (see 'genRun'), so that a loop it calls is its run form
    mainBind = find ((== "main") . tbName) (progBinds prog)
    isMainRun b = tbName b == "main" && tbArity b == 0 && not (any (elem "main" . coreRefs . tbBody) (progBinds prog))
    -- the run forms of functions that end calling each other, as loops
    topLoops = concat [runLoops [(b, (tbParams b, runResult b)) | b <- bs, hasRunForm prog b] | CyclicSCC bs <- sccs]
    -- and the functions that end calling each other and are not actions,
    -- by the type they give; a loop that builds a map in place stays its own
    pureLoops = concat [runLoops [(b, (tbParams b, pureResult b)) | b <- bs, pureLoopable b] | CyclicSCC bs <- sccs]
    pureLoopable b = case tbBody b of
      CLam ps r inner -> tbArity b > 0 && not (tbShared b) && length ps == tbArity b && not (hasRunForm prog b)
        && isNothing (ioResult ctx0 r) && isNothing (ownedLoop ctx0 (tbName b) (tbArity b) ps inner)
      _ -> False
    pureResult b = case tbBody b of
      CLam _ r _ -> zonk (progSubst prog) r
      _ -> error ("pureResult: " ++ tbName b)
    runResult b = case tbBody b of
      CLam _ r _ | Just x <- ioResult ctx0 r -> x
      _ -> error ("runResult: " ++ tbName b)
    -- the functions of each one's group of mutually recursive ones, itself among them
    groupOf n = M.findWithDefault (S.singleton n) n groups
    groups = M.fromList [(tbName b, S.fromList (map tbName bs)) | CyclicSCC bs <- sccs, b <- bs]
    initBlock = ["func init() {", "defer rt_failed()"] ++ concat inits ++ ["}"]
    -- values are initialised in order, so each comes after everything its
    -- computation reaches, functions included; copies made by specialisation
    -- would otherwise come after their users
    sccs =
      let names = S.fromList (map tbName (progBinds prog))
       in stronglyConnComp
            [(b, tbName b, filter (`S.member` names) (coreRefs (tbBody b))) | b <- progBinds prog]
    initOrder = flattenSCCs sccs
    -- Values defined in terms of each other (parsers built with combinators)
    -- cannot be computed one after the other in a strict language. Those
    -- that are functions, IO actions among them, start as a function that
    -- computes the value the first time it is called and then calls it, so
    -- every value in the group exists before any is computed.
    deferred = S.fromList
      [ tbName b
      | CyclicSCC bs <- sccs, b <- bs, tbArity b == 0, tbShared b
      , isFunctionType (zonk (progSubst prog) (tbType b)) ]
    isFunctionType = \case
      TFun _ _ -> True
      TCon "IO" [_] -> True
      _ -> False
    -- drop the global reference first, so actions already run can be collected
    -- The garbage collector's settings (see rt_startGC).
    mainFn =
      [ "func main() {", "defer rt_failed()", "rt_startGC()"
      ] ++ fromMaybe ["m := " ++ mangle "main", mangle "main" ++ " = nil", "rt_run(m)"] mainRun ++ ["}"]

-- Names -------------------------------------------------------------------------

goReserved :: [String]
goReserved = words
  "break default func interface select case defer go map struct chan else goto package switch \
  \const fallthrough if range type continue for import return var any bool byte comparable \
  \complex64 complex128 error float32 float64 int int8 int16 int32 int64 rune string uint uint8 \
  \uint16 uint32 uint64 uintptr true false iota nil append cap clear close complex copy delete \
  \imag len make max min new panic print println real recover main init List Nil Cons Tup2 Tup3 IO IOStep"

mangle :: Name -> String
mangle n
  -- a specialised operator keeps the letters of its types: ++__Int
  | isSymbolic n = "op_" ++ concatMap (\c -> if isAlphaNum c || c == '_' then [c] else symWord c) n
  | s `elem` goReserved = s ++ "_"
  | any (`isPrefixOf` s) ["rt_", "hg_"] = "u_" ++ s
  | otherwise = s
  where
    s = concatMap (\c -> if c == '\'' then "_q" else if c == '.' then "_" else if isAlphaNum c || c == '_' then [c] else "_" ++ symWord c) n'
    -- a qualified operator: the module part as a prefix, the operator spelled out
    n' = case splitQual n of
      (Just q, base) | isSymbolic base -> q ++ ".op_" ++ concatMap symWord base
      _ -> n
    -- any other character by its code, so that two names never meet
    symWord c = fromMaybe ("x" ++ show (fromEnum c)) (lookup c symNames)
    symNames =
      [ ('+', "plus"), ('-', "minus"), ('*', "star"), ('/', "slash"), ('.', "dot"), ('<', "lt")
      , ('>', "gt"), ('=', "eq"), ('!', "bang"), ('$', "dollar"), ('&', "amp"), ('|', "bar")
      , (':', "colon"), ('^', "caret"), ('%', "pct"), ('@', "at"), ('#', "hash"), ('?', "qm")
      , ('~', "tilde"), ('\\', "bslash") ]

-- | A constructor's part of its struct name: without its module, operators spelled out.
conSuffix :: Name -> String
conSuffix k = let b = unqual k in if isSymbolic b then mangle b else b

-- | Operators and operator constructors, as opposed to alphanumeric names.
isSymbolic :: Name -> Bool
isSymbolic (c : _) = not (isAlpha c || c == '_')
isSymbolic [] = False

tyVar :: Name -> String
tyVar v = "T_" ++ concatMap (\c -> if c == '\'' then "_q" else [c]) v

typeName :: Name -> String
typeName c = if c' `elem` goReserved then c' ++ "_" else c'
  where c' = map (\x -> if x == '.' then '_' else x) c

conStruct :: Program -> Name -> String
conStruct prog k = case k of
  "[]" -> "Nil"
  ":" -> "Cons"
  _ | Just n <- tupleArity k -> "Tup" ++ show n
  _ -> typeName (ciType (progCons prog M.! k)) ++ "_" ++ conSuffix k

-- | A Go type named in @foreign import go type@, as the generated code writes
-- it: @"*net/http.Request"@ is @*http.Request@, and the runtime's own types
-- (@"*rt_MVar"@) have no package.
goTypeSymbol :: String -> String
goTypeSymbol sym = let (stars, rest) = span (== '*') sym in stars ++ snd (splitSymbol rest)

splitSymbol :: String -> (String, String)
splitSymbol s = case break (== '.') (reverse s) of
  (_, []) -> ("", s)
  (_, _ : revPkg) ->
    let pkgPath = reverse revPkg
        short = reverse (takeWhile (/= '/') revPkg)
     in (pkgPath, short ++ drop (length pkgPath) s)

-- Types ---------------------------------------------------------------------------

goTy :: Ctx -> Type -> String
goTy ctx = render . zonk (progSubst (cxProg ctx))
  where
    render = \case
      TVar v -> tyVar v
      TMeta _ -> "struct{}"
      TCon "Int" [] -> "int"
      TCon "Double" [] -> "float64"
      TCon "Integer" [] -> "*rt_big.Int"
      TCon "Bool" [] -> "bool"
      TCon "Char" [] -> "rune"
      TCon "String" [] -> "string"
      TCon "()" [] -> "struct{}"
      TCon "[]" [t] -> "List[" ++ render t ++ "]"
      TCon "IO" [t] -> "IO[" ++ render t ++ "]"
      TCon "Lazy" [t] -> "*rt_thunk[" ++ render t ++ "]"
      TCon c ts | Just n <- tupleArity c -> "Tup" ++ show n ++ "[" ++ commas (map render ts) ++ "]"
      TCon c ts
        | not (null (hkPositions (cxProg ctx) c)) ->
            let (n, args) = dataInst (cxProg ctx) c ts
             in n ++ (if null args then "" else "[" ++ commas (map render args) ++ "]")
      TCon c [t] | Just "[]" <- M.lookup c (progData (cxProg ctx)) >>= diForeign -> "[]" ++ render t
      TCon c ts | Just sym <- M.lookup c (progData (cxProg ctx)) >>= diForeign ->
        goTypeSymbol sym ++ (if null ts then "" else "[" ++ commas (map render ts) ++ "]")
      TCon c [] -> typeName c
      TCon c ts -> typeName c ++ "[" ++ commas (map render ts) ++ "]"
      TFun a b -> "func(" ++ render a ++ ") " ++ render b
      TApp _ _ -> error "codegen: a type application survived specialisation"

typeArgs :: Ctx -> [Type] -> String
typeArgs _ [] = ""
typeArgs ctx ts = "[" ++ commas (map (goTy ctx) ts) ++ "]"

tparamList :: [Name] -> String
tparamList [] = ""
tparamList vs = "[" ++ commas [tyVar v ++ " any" | v <- vs] ++ "]"

commas :: [String] -> String
commas = intercalate ", "

-- Data types ----------------------------------------------------------------------

-- | Parameters of a data type that take a type constructor (the m of StateT s m a).
hkPositions :: Program -> Name -> [Int]
hkPositions prog c = maybe [] (\di -> [i | (i, k) <- zip [0 ..] (diKinds di), k > 0]) (M.lookup c (progData prog))

-- | Go has no type parameters of a higher kind, so a data type applied to a
-- type constructor gets one Go type per constructor: StateT s IO a becomes
-- StateT__IO[S, A]. Variables inside the constructor become extra type
-- parameters. Returns the Go name and its type arguments.
dataInst :: Program -> Name -> [Type] -> (String, [Type])
dataInst prog c ts =
  let pos = hkPositions prog c
      hk = [t | (i, t) <- zip [0 :: Int ..] ts, i `elem` pos]
      rest = [t | (i, t) <- zip [0 :: Int ..] ts, i `notElem` pos]
      (canon, extras) = canonVars hk
   in (instName c canon, rest ++ map TVar extras)

canonVars :: [Type] -> ([Type], [Name])
canonVars hk =
  let vs = nub (concatMap tyVarsOf hk)
      s = M.fromList [(v, TVar ("_hk" ++ show i)) | (i, v) <- zip [0 :: Int ..] vs]
   in (map (substTV s) hk, vs)

instName :: Name -> [Type] -> String
instName c canon = typeName c ++ "__" ++ intercalate "_" (map typeTag canon)

-- | A constructor as a Go struct, with its type arguments.
conRef :: Ctx -> Name -> [Type] -> String
conRef ctx k targs = case M.lookup k (progCons prog) of
  Just ci | not (null (hkPositions prog (ciType ci))) ->
    let (n, args) = dataInst prog (ciType ci) (map (zonk (progSubst prog)) targs)
     in n ++ "_" ++ conSuffix k ++ typeArgs ctx args
  _ -> conStruct prog k ++ typeArgs ctx targs
  where prog = cxProg ctx

-- | Every instantiation of a data type over type constructors that the
-- program uses, including those that only appear inside other ones' fields.
hkInstances :: Program -> [(Name, [Type])]
hkInstances prog = go [] (concatMap found allTypes)
  where
    sub = progSubst prog
    allTypes = concat [tbType b : exprTypes (tbBody b) | b <- progBinds prog]
    found t = case zonk sub t of
      TCon c ts
        | not (null (hkPositions prog c)), Just di <- M.lookup c (progData prog), length ts == length (diParams di) ->
            (c, fst (canonVars [x | (i, x) <- zip [0 :: Int ..] ts, i `elem` hkPositions prog c])) : concatMap found ts
        | otherwise -> concatMap found ts
      TFun a b -> found a ++ found b
      TApp f x -> found f ++ found x
      _ -> []
    go _ [] = []
    go seen (x : xs)
      | x `elem` seen = go seen xs
      | otherwise = x : go (x : seen) (xs ++ concatMap found (fieldTypes x))
    fieldTypes (c, canon) =
      let di = progData prog M.! c
          s = M.fromList (zip [p | (p, k) <- zip (diParams di) (diKinds di), k > 0] canon)
       in [substTV s t | k <- diCons di, (_, t) <- ciFields (progCons prog M.! k)]

genHkData :: Program -> (Name, [Type]) -> [String]
genHkData prog (c, canon) =
  ["type " ++ name ++ tparamList params ++ " interface{ " ++ marker ++ "() }"] ++ concatMap con (diCons di)
  where
    di = progData prog M.! c
    hkParams = [p | (p, k) <- zip (diParams di) (diKinds di), k > 0]
    params = [p | (p, k) <- zip (diParams di) (diKinds di), k == 0] ++ nub (concatMap tyVarsOf canon)
    s = M.fromList (zip hkParams canon)
    name = instName c canon
    marker = "is" ++ name
    ctx = Ctx M.empty Nothing [] params prog S.empty M.empty M.empty S.empty M.empty (0, M.empty)
    recv k = name ++ "_" ++ suffix k ++ (if null params then "" else "[" ++ commas (map tyVar params) ++ "]")
    suffix = conSuffix
    con k =
      let ci = progCons prog M.! k
          fields = ["F" ++ show i ++ " " ++ goTy ctx (substTV s (if lz then tLazy t else t)) | (i, (lz, t)) <- zip [0 :: Int ..] (ciFields ci)]
       in [ "type " ++ name ++ "_" ++ suffix k ++ tparamList params ++ " struct{ " ++ intercalate "; " fields ++ " }"
          , "func (" ++ recv k ++ ") " ++ marker ++ "() {}" ]

-- | How a data type is kept in Go, when it is not an interface with a
-- struct per constructor (which costs an allocation to build and a type
-- test to match).
data Repr
  = Plain    -- ^ its one constructor's struct, passed by value
  | Tagged   -- ^ one struct, passed by value, with a tag saying which constructor and the fields of all of them
  | Pointer  -- ^ a pointer to the struct of the constructor with fields; nil is the one without, as [] and Tip

-- | The data types kept by value. Not one that contains itself by value
-- (through its fields, tuples, or other such types), which would have no
-- size, nor one over type constructors, nor one bigger than eight words,
-- which would be slow to copy.
--
-- A type with two constructors, one with no fields, as a list or a tree, is
-- a pointer, which is half the size of an interface and is matched by
-- comparing it with nil. So is a type of one constructor that is not kept
-- by value (a record of many fields, one that contains itself): a field is
-- read through the pointer, where an interface would be asserted to its
-- struct and the struct copied out.
dataReprs :: Program -> M.Map Name Repr
dataReprs prog = M.unions [byValueReprs, pointers, onePointers]
  where
    byValueReprs = M.fromList [(n, repr n) | AcyclicSCC n <- stronglyConnComp [(n, n, byValue n) | n <- S.toList candidates]]
    pointers = M.fromList
      [ (n, Pointer) | (n, DataInfo _ _ [a, b] nt _) <- M.toList (progData prog), not nt, n `notElem` ["Bool"]
      , null (hkPositions prog n), tupleArity n == Nothing
      , length (filter null [ciFields (progCons prog M.! a), ciFields (progCons prog M.! b)]) == 1 ]
    onePointers = M.fromList
      [ (n, Pointer) | (n, DataInfo _ _ [k] nt _) <- M.toList (progData prog), not nt, n `notElem` ["()"]
      , null (hkPositions prog n), tupleArity n == Nothing, not (null (ciFields (progCons prog M.! k))) ]
    candidates = S.fromList
      [ n | (n, DataInfo _ _ ks nt _) <- M.toList (progData prog), not nt, not (null ks), n `notElem` ["[]", "Bool", "()"]
      , tupleArity n == Nothing, null (hkPositions prog n), sizeOf [] n <= (8 :: Int) ]
    -- the sums small enough to be kept by value if they do not contain themselves
    smallSums = S.fromList [n | (n, di) <- M.toList (progData prog), length (diCons di) <= 3]
    repr n = case diCons (progData prog M.! n) of
      [_] -> Plain
      _ -> Tagged
    fieldsOf n = [(lz, t) | k <- diCons (progData prog M.! n), (lz, t) <- ciFields (progCons prog M.! k)]
    byValue n = [c | (lz, t) <- fieldsOf n, not lz, c <- inside t]
    inside = \case
      TCon c ts
        | S.member c candidates -> c : concatMap inside ts
        | tupleArity c /= Nothing -> concatMap inside ts
      _ -> []
    -- the types that contain themselves, through strict fields and the
    -- types inside them: never kept by value, so a field of one is a pointer
    -- or an interface
    selfContaining = S.fromList [n | CyclicSCC ns <- stronglyConnComp [(n, n, refs n) | n <- M.keys (progData prog)], n <- ns]
    refs n = nub [c | (lz, t) <- fieldsOf n, not lz, c <- conNamesIn t]
    conNamesIn = \case
      TCon c ts | c /= "[]", M.member c (progData prog) || tupleArity c /= Nothing -> c : concatMap conNamesIn ts
      TCon _ ts -> concatMap conNamesIn ts
      _ -> []
    -- in words, guessing two for a type variable; a type that contains
    -- itself is too big
    sizeOf seen n
      | n `elem` seen = 100
      | otherwise =
          let ks = diCons (progData prog M.! n)
           in (if length ks > 1 then 1 else 0) + sum [if lz then 1 else wordsOf (n : seen) t | (lz, t) <- fieldsOf n]
    wordsOf seen = \case
      TCon c ts
        | c `elem` ["Int", "Double", "Char", "Bool", "Integer", "()", "Lazy", "IO"] -> 1
        | tupleArity c /= Nothing -> sum (map (wordsOf seen) ts)
        | M.member c pointers, not (S.member c smallSums) -> 1
        | S.member c selfContaining -> if M.member c pointers then 1 else 2
        | Just di <- M.lookup c (progData prog), length (diCons di) <= 3, not (diNewtype di), null (hkPositions prog c), c `notElem` ["[]"] ->
            min 100 (sizeOf seen c)
        | otherwise -> 2
      TFun _ _ -> 1
      _ -> 2

genData :: Program -> M.Map Name Repr -> (Name, DataInfo) -> [String]
genData prog unboxed (n, DataInfo ps _ ks _ _)
  | n == "()" || tupleArity n /= Nothing = []
  | Just Pointer <- M.lookup n unboxed, [k] <- [k | k <- ks, not (null (ciFields (progCons prog M.! k)))] =
      let ci = progCons prog M.! k
          fields = [ "F" ++ show i ++ " " ++ goTy ctx (if lz then tLazy t else t) | (i, (lz, t)) <- zip [0 :: Int ..] (ciFields ci)]
       in [ "type " ++ conStruct prog k ++ tparamList ps ++ " struct{ " ++ intercalate "; " fields ++ " }"
          , "type " ++ typeName n ++ tparamList ps ++ " = *" ++ conStruct prog k ++ (if null ps then "" else "[" ++ commas (map tyVar ps) ++ "]") ]
  | Just Tagged <- M.lookup n unboxed =
      let fields =
            "tag uint8"
              : [ taggedField (progCons prog M.! k) i ++ " " ++ goTy ctx (if lz then tLazy t else t)
                | k <- ks, (i, (lz, t)) <- zip [0 :: Int ..] (ciFields (progCons prog M.! k)) ]
       in ["type " ++ typeName n ++ tparamList ps ++ " struct{ " ++ intercalate "; " fields ++ " }"]
  | Just Plain <- M.lookup n unboxed, [k] <- ks =
      let ci = progCons prog M.! k
          fields = [ "F" ++ show i ++ " " ++ goTy ctx (if lz then tLazy t else t) | (i, (lz, t)) <- zip [0 :: Int ..] (ciFields ci)]
       -- the struct is the type itself and the constructor's name an alias
       -- of it: a struct that refers to itself through an alias (a list of
       -- itself) makes Go 1.27 fail with "incomplete alias" (go.dev/issue/78296)
       in [ "type " ++ typeName n ++ tparamList ps ++ " struct{ " ++ intercalate "; " fields ++ " }"
          , "type " ++ conStruct prog k ++ tparamList ps ++ " = " ++ typeName n ++ (if null ps then "" else "[" ++ commas (map tyVar ps) ++ "]") ]
  | otherwise =
      ["type " ++ typeName n ++ tparamList ps ++ " interface{ " ++ marker ++ "() }"]
        ++ concatMap con ks
  where
    marker = "is" ++ typeName n
    recv k = conStruct prog k ++ (if null ps then "" else "[" ++ commas (map tyVar ps) ++ "]")
    ctx = Ctx M.empty Nothing [] ps prog S.empty M.empty M.empty S.empty M.empty (0, M.empty)
    con k =
      let ci = progCons prog M.! k
          fields = [ "F" ++ show i ++ " " ++ goTy ctx (if lz then tLazy t else t) | (i, (lz, t)) <- zip [0 :: Int ..] (ciFields ci)]
       in [ "type " ++ conStruct prog k ++ tparamList ps ++ " struct{ " ++ intercalate "; " fields ++ " }"
          , "func (" ++ recv k ++ ") " ++ marker ++ "() {}" ]

-- Top-level bindings ----------------------------------------------------------------

-- | A top-level binding: its declaration, and its initialisation if it is a
-- CAF. Its run form may be given, as the entry to a loop (see 'genRunLoop').
genTop :: Ctx -> Bool -> Maybe String -> Maybe String -> TopBind -> Gen (String, [String])
genTop ctx0 deferred pentry entry (TopBind n tps dicts t ar body shared) = do
  -- specialisation leaves no dictionary
  unless (null dicts) (error ("codegen: dictionaries left in " ++ n))
  let ctx = ctx0 {cxTParams = tps}
  case (ar, body) of
    (0, _) | shared, deferred -> do
      e <- genExpr ctx body
      let ty = goTy ctx t
          cell = mangle n ++ "__cell"
          wrapper = case zonk (progSubst (cxProg ctx)) t of
            TFun a r -> "func(hg_arg " ++ goTy ctx a ++ ") " ++ goTy ctx r ++ " { return " ++ cell ++ ".force()(hg_arg) }"
            TCon "IO" [r] -> "func() IOStep[" ++ goTy ctx r ++ "] { return " ++ cell ++ ".force()() }"
            _ -> error ("genTop: deferred value of type " ++ ty)
      pure
        ( "var " ++ mangle n ++ " " ++ ty ++ "\nvar " ++ cell ++ " *rt_thunk[" ++ ty ++ "]"
        , [cell ++ " = rt_lazy(func() " ++ ty ++ " { return " ++ e ++ " })", mangle n ++ " = " ++ wrapper] )
    (0, _) | shared -> do
      e <- genExpr ctx body
      pure ("var " ++ mangle n ++ " " ++ goTy ctx t, [mangle n ++ " = " ++ e])
    (0, _) -> do
      ls <- genStmts ctx body
      pure (unlines (["func " ++ mangle n ++ tparamList tps ++ "() " ++ goTy ctx t ++ " {"] ++ ls ++ ["}"]), [])
    (_, CLam ps r inner) -> do
      fn <- maybe (genFunction ctx (Just (n, ar)) [] ps r inner) pure pentry
      runFn <- case (M.lookup n (cxRun ctx), ioResult ctx r, entry) of
        (Just (rn, _), Just _, Just f) -> pure ("\nfunc " ++ rn ++ tparamList tps ++ f)
        (Just (rn, _), Just x, Nothing) -> (\f -> "\nfunc " ++ rn ++ tparamList tps ++ f) <$> genRunFunction ctx (Just (n, ar)) ps x inner
        _ -> pure ""
      pure ("func " ++ mangle n ++ tparamList tps ++ fn ++ runFn, [])
    _ -> error ("genTop: " ++ n)

-- | Parameters, result type and body of a function, with self tail calls
-- turned into a loop.
genFunction :: Ctx -> Maybe (Name, Int) -> [(String, String)] -> [(Name, Type)] -> Type -> CExpr -> Gen String
genFunction ctx self extra ps r inner0 = do
  saved <- gets gsLoop
  modify (\s -> s {gsLoop = False})
  -- a loop that builds a map in a parameter builds it in place (see 'ownedLoop')
  o <- freshName "o"
  let owned = case self of
        Just (n, ar) -> ownedLoop ctx n ar ps inner0
        Nothing -> Nothing
      inner = maybe inner0 (\f -> f o) owned
      ctx' = (bindLocals ctx ([(p, 0) | (p, _) <- ps] ++ [(o, 0)])) {cxSelf = self, cxSelfParams = map fst ps}
  ls <- genStmts ctx' inner
  looped <- gets gsLoop
  modify (\s -> s {gsLoop = saved})
  let params = commas ([d ++ " " ++ ty | (d, ty) <- extra] ++ [(if looped then nextName p else mangle p) ++ " " ++ goTy ctx pt | (p, pt) <- ps])
      start = case owned of
        Just _ -> [mangle o ++ " := rt_newOwner()", "defer rt_endOwner(" ++ mangle o ++ ")"]
        Nothing -> []
      body = start ++ if looped then ["for {"] ++ roundStart (map fst ps) ++ ls ++ ["}"] else ls
  pure (unlines (["(" ++ params ++ ") " ++ goTy ctx r ++ " {"] ++ body ++ ["}"]))

-- | A function that calls itself at the end, a loop, with a parameter that
-- is a map it builds: go (Map.insert k v m) rest. The map can be built in
-- place, with an owner of the call's own (see Data.Map), if on every path
-- that goes round again the map is only read before (given, at once, to a
-- function whose result has no map in it, as Map.lookup) and then given to
-- the call again through operations that take an owner, appearing in none
-- of the call's other arguments. Paths that leave the loop may do anything
-- with it: once the call returns, its owner is no longer active. The result
-- is the body with the owner (a variable) given to those operations.
ownedLoop :: Ctx -> Name -> Int -> [(Name, Type)] -> CExpr -> Maybe (Name -> CExpr)
ownedLoop ctx self ar ps body = case [i | (i, (_, t)) <- zip [0 ..] ps, Just c <- [mapCon t], ok i c] of
  i : _ -> Just (\o -> give i o body)
  [] -> Nothing
  where
    mapCon t = case zonk (progSubst (cxProg ctx)) t of
      TCon c _ | c == "Data.Map.Map" -> Just c
      _ -> Nothing
    -- the names the parameter goes by: itself, and what patterns call it
    aliases i = grow (S.singleton (fst (ps !! i)))
    grow as =
      let more = S.fromList [x | CMatch ss rows _ <- everything body, (CVar a _ _, j) <- zip ss [0 :: Int ..], S.member a as
                             , CRow pats _ _ <- rows, Just (CPVar x _) <- [nth j pats]]
       in if more `S.isSubsetOf` as then as else grow (S.union as more)
    nth j xs = if j < length xs then Just (xs !! j) else Nothing
    ok i c = let as = aliases i in path i c as body && worth i body
    selfCall = \case
      CApp (CVar f _ _) args | f == self, length args == ar -> Just args
      _ -> Nothing
    mentions as e = any (`S.member` as) (coreRefs e)
    path i c as e = case e of
      _ | Just args <- selfCall e ->
          and [if j == i then chain as a else not (mentions as a) | (j, a) <- zip [0 ..] args]
      CMatch ss rows _ -> all (\sc -> isAlias as sc || readOnly c as sc) ss && all (row i c as) rows
      CIf cond a b _ -> readOnly c as cond && path i c as a && path i c as b
      CLet bs b _ -> all (\(CBind _ _ _ x) -> readOnly c as x) bs && path i c as b
      -- leaves the loop: anything goes
      _ -> True
    row i c as (CRow _ bs gs) =
      all (\(CBind _ _ _ x) -> readOnly c as x) bs && all (\(g, b) -> maybe True (readOnly c as) g && path i c as b) gs
    isAlias as = \case
      CVar a _ _ -> S.member a as
      _ -> False
    -- the map given to the next round: itself, or changed by an operation
    -- that takes an owner, or by a fold that builds it in place
    chain as = \case
      CVar a _ _ -> S.member a as
      CApp (CVar f _ _) (CVar o _ _ : rest)
        | isTop ctx f, Just "rt_noOwner" <- foreignSym ctx o, not (null rest) ->
            chain as (last rest) && not (any (mentions as) (init rest))
      CApp (CVar "listFoldl" _ _) [g, z, xs] | isTop ctx "listFoldl" ->
        chain as z && ownedStep ctx g && not (mentions as g) && not (mentions as xs)
      _ -> False
    -- the map read, at once, by functions whose results hold no map
    readOnly c as e = case e of
      CVar a _ _ -> not (S.member a as)
      CApp (CVar f _ t) args ->
        let res = snd (splitFun (length args) (zonk (progSubst (cxProg ctx)) t))
         in (f /= self) && all (\a -> if isAlias as a then c `notElem` tyCons res else readOnly c as a) args
      CApp f args -> readOnly c as f && all (readOnly c as) args
      CIf a b d _ -> all (readOnly c as) [a, b, d]
      CLet bs b _ -> all (\(CBind _ _ _ x) -> readOnly c as x) bs && readOnly c as b
      CMatch ss rows _ -> all (readOnly c as) ss && and [all (\(CBind _ _ _ x) -> readOnly c as x) bs && all (\(g, b) -> maybe True (readOnly c as) g && readOnly c as b) gs | CRow _ bs gs <- rows]
      _ -> not (mentions as e)
    tyCons = \case
      TCon c ts -> c : concatMap tyCons ts
      TFun a b -> tyCons a ++ tyCons b
      TApp a b -> tyCons a ++ tyCons b
      _ -> []
    -- worth it only if some round changes the map
    worth i e = or [any changes (take 1 (drop i args)) | x <- everything e, Just args <- [selfCall x]]
      where
        changes = \case
          CApp (CVar _ _ _) (CVar o _ _ : _) | Just "rt_noOwner" <- foreignSym ctx o -> True
          CApp (CVar "listFoldl" _ _) [_, z, _] -> changes z
          _ -> False
    -- the owner given to the operations of every chain
    give i o = \case
      e | Just args <- selfCall e, CApp f _ <- e -> CApp f [if j == i then giveChain o a else a | (j, a) <- zip [0 ..] args]
      CMatch ss rows t -> CMatch ss [CRow pats bs [(g, give i o b) | (g, b) <- gs] | CRow pats bs gs <- rows] t
      CIf c a b t -> CIf c (give i o a) (give i o b) t
      CLet bs b t -> CLet bs (give i o b) t
      e -> e
    giveChain o = \case
      CApp f@(CVar _ _ _) (CVar n ref t : rest) | Just "rt_noOwner" <- foreignSym ctx n ->
        CApp f (CVar o ref t : init rest ++ [giveChain o (last rest)])
      -- a fold in the chain builds in place with the loop's owner too
      CApp f@(CVar "listFoldl" _ _) [g, z, xs] -> CApp f [giveOwner ctx o g, giveChain o z, xs]
      e -> e

-- A function whose calls to itself at the end are a loop takes its
-- arguments in variables of their own (nextName), which each call assigns
-- before going round again; each round starts by copying them into new
-- variables of the parameters' names. A closure or a suspension made in a
-- round keeps that round's values, as it would in the recursion: were the
-- parameters themselves assigned, it would see the next round's.
nextName :: Name -> String
nextName p = "hg_next_" ++ mangle p

roundStart :: [Name] -> [String]
roundStart ps = concat [[mangle p ++ " := " ++ nextName p, "_ = " ++ mangle p] | p <- ps]

bindLocals :: Ctx -> [(Name, Int)] -> Ctx
bindLocals ctx bs =
  ctx { cxVars = foldr (\(n, a) -> M.insert n (VKLocal a)) (cxVars ctx) bs
      , cxPending = foldr (S.delete . fst) (cxPending ctx) bs
      , cxRun = foldr (M.delete . fst) (cxRun ctx) bs
      , cxLoop = fmap (\m -> foldr (M.delete . fst) m bs) (cxLoop ctx)
      , cxSelf = case cxSelf ctx of
          Just (n, _) | n `elem` map fst bs -> Nothing
          self -> self }

noSelf :: Ctx -> Ctx
noSelf ctx = ctx {cxSelf = Nothing, cxLoop = (0, M.empty)}

freshName :: String -> Gen String
freshName base = do
  n <- gets gsNext
  modify (\s -> s {gsNext = n + 1})
  pure ("hg_" ++ base ++ show n)

-- Statements (a body that returns) --------------------------------------------------

genStmts :: Ctx -> CExpr -> Gen [String]
genStmts ctx e = case e of
  CMatch scruts rows _ -> genMatch genStmts ctx scruts rows
  CLet bs body _ -> do
    (ctx', ls) <- genBinds ctx bs
    (ls ++) <$> genStmts ctx' body
  CIf c a b _ -> do
    c' <- genExpr ctx c
    as <- genStmts ctx a
    bs <- genStmts ctx b
    pure (["if " ++ c' ++ " {"] ++ as ++ ["}"] ++ bs)
  -- a tail call to one of the loop's functions (see 'genRunLoop')
  CApp (CVar x ref _) args
    | (from, loop) <- cxLoop ctx, Just (j, ns) <- M.lookup x loop, length args == length ns
    , M.notMember x (cxRun ctx), sameLoopInstance ctx ref -> do
        as <- mapM (genExpr ctx) args
        when (j /= from) (modify (\s -> s {gsJumped = (from, j) : gsJumped s}))
        pure [commas ns ++ " = " ++ commas as, "hg_which = " ++ show j, "continue"]
  CApp (CVar x _ _) args
    | Just (self, n) <- cxSelf ctx, x == self, length args == n, isSelf (M.lookup x (cxVars ctx)) n -> do
        as <- mapM (genExpr ctx) args
        modify (\s -> s {gsLoop = True})
        pure [commas (map nextName (cxSelfParams ctx)) ++ " = " ++ commas as, "continue"]
  _ -> do
    e' <- genExpr ctx e
    pure ["return " ++ e']
  where
    isSelf (Just (VKTop a _ _)) n = a == n
    isSelf (Just (VKLocal a)) n = a == n
    isSelf _ _ = False

-- | A @case@ as statements; tl makes those of each body.
genMatch :: (Ctx -> CExpr -> Gen [String]) -> Ctx -> [CExpr] -> [CRow] -> Gen [String]
genMatch tl ctx scruts rows = do
  prepared <- forM scruts $ \case
    CVar x _ _ | Just (VKLocal 0) <- M.lookup x (cxVars ctx) -> pure ([], mangle x)
    s -> do
      n <- freshName "s"
      s' <- genExpr ctx s
      -- a constructor's Go value has its struct type; matching needs the
      -- interface of its data type
      -- (only for a constructor given all its fields: one given fewer is a
      -- function)
      let decl = case conHead s of
            Just (k, targs) | tupleArity k == Nothing, k `notElem` ["()", "True", "False"]
                            , Just ci <- M.lookup k (progCons (cxProg ctx)), conArgs s == length (ciFields ci) ->
              "var " ++ n ++ " " ++ goTy ctx (TCon (ciType (progCons (cxProg ctx) M.! k)) targs) ++ " = " ++ s'
            _ -> n ++ " := " ++ s'
      pure ([decl, "_ = " ++ n], n)
  rowLines <- forM rows $ \(CRow pats binds guards) -> do
    ls <- genPats ctx (zip (map snd prepared) pats) (\ctx' -> genRow tl ctx' binds guards)
    pure (["{"] ++ ls ++ ["}"])
  pure (concatMap fst prepared ++ concat rowLines ++ ["panic(\"pattern match failure\")"])

-- | How many arguments a constructor application gives.
conArgs :: CExpr -> Int
conArgs = \case
  CApp f as -> conArgs f + length as
  _ -> 0

conHead :: CExpr -> Maybe (Name, [Type])
conHead = \case
  CCon k targs _ -> Just (k, targs)
  CApp f _ -> conHead f
  _ -> Nothing

genRow :: (Ctx -> CExpr -> Gen [String]) -> Ctx -> [CBind] -> [(Maybe CExpr, CExpr)] -> Gen [String]
genRow tl ctx binds guards = do
  (ctx', ls) <- genBinds ctx binds
  (ls ++) <$> go ctx' guards
  where
    go _ [] = pure []
    go c ((g, e) : rest) = case g of
      Nothing -> tl c e
      Just (CVar "otherwise" _ _) | isTopOtherwise c -> tl c e
      Just (CCon "True" _ _) -> tl c e
      Just cond -> do
        cond' <- genExpr c cond
        body <- tl c e
        rest' <- go c rest
        pure (["if " ++ cond' ++ " {"] ++ body ++ ["}"] ++ rest')
    isTopOtherwise c = case M.lookup "otherwise" (cxVars c) of
      Just (VKTop 0 _ _) -> True
      _ -> False

-- | Nested tests and bindings for a row of patterns; the continuation
-- produces the code that runs when everything matches.
genPats :: Ctx -> [(String, CPat)] -> (Ctx -> Gen [String]) -> Gen [String]
genPats ctx [] k = k ctx
genPats ctx ((s, p) : rest) k = case p of
  CPWild -> genPats ctx rest k
  CPVar x _ -> do
    body <- genPats (bindLocals ctx [(x, 0)]) rest k
    pure ([mangle x ++ " := " ++ s, "_ = " ++ mangle x] ++ body)
  CPAs x _ q -> do
    body <- genPats (bindLocals ctx [(x, 0)]) ((s, q) : rest) k
    pure ([mangle x ++ " := " ++ s, "_ = " ++ mangle x] ++ body)
  CPLit l -> do
    body <- genPats ctx rest k
    pure (["if " ++ s ++ " == " ++ genLit l ++ " {"] ++ body ++ ["}"])
  CPNum n t _ _ -> do
    let test = s ++ " == " ++ numLit ctx n t
    body <- genPats ctx rest k
    pure (["if " ++ test ++ " {"] ++ body ++ ["}"])
  CPEq f v -> do
    f' <- genExpr ctx f
    v' <- genExpr ctx v
    body <- genPats ctx rest k
    pure (["if (" ++ f' ++ ")(" ++ s ++ ")(" ++ v' ++ ") {"] ++ body ++ ["}"])
  CPForce q -> do
    n <- freshName "f"
    body <- genPats ctx ((n, q) : rest) k
    pure ([n ++ " := " ++ s ++ ".force()", "_ = " ++ n] ++ body)
  CPCon "True" _ _ -> cond s
  CPCon "False" _ _ -> cond ("!" ++ s)
  CPCon "()" _ _ -> genPats ctx rest k
  CPCon k' _ subs | Just _ <- tupleArity k' ->
    genPats ctx ([(s ++ ".F" ++ show i, q) | (i, q) <- zip [0 :: Int ..] subs] ++ rest) k
  -- the only constructor of a type kept as a struct always matches, and
  -- one of a tagged struct is told by its tag
  CPCon k' _ subs | Just ci <- M.lookup k' (progCons (cxProg ctx)), Just r <- M.lookup (ciType ci) (cxUnboxed ctx) -> case r of
    Plain -> genPats ctx ([(s ++ ".F" ++ show i, q) | (i, q) <- zip [0 :: Int ..] subs] ++ rest) k
    Tagged -> do
      body <- genPats ctx ([(s ++ "." ++ taggedField ci i, q) | (i, q) <- zip [0 :: Int ..] subs] ++ rest) k
      pure (["if " ++ s ++ ".tag == " ++ show (ciTag ci) ++ " {"] ++ body ++ ["}"])
    Pointer
      | null (ciFields ci) -> do
          body <- genPats ctx rest k
          pure (["if " ++ s ++ " == nil {"] ++ body ++ ["}"])
      | otherwise -> do
          body <- genPats ctx ([(s ++ ".F" ++ show i, q) | (i, q) <- zip [0 :: Int ..] subs] ++ rest) k
          pure (["if " ++ s ++ " != nil {"] ++ body ++ ["}"])
  CPCon k' targs subs -> do
    let struct = conRef ctx k' targs
    if all isWild subs
      then do
        body <- genPats ctx rest k
        pure (["if _, hg_ok := " ++ s ++ ".(" ++ struct ++ "); hg_ok {"] ++ body ++ ["}"])
      else do
        v <- freshName "v"
        body <- genPats ctx ([(v ++ ".F" ++ show i, q) | (i, q) <- zip [0 :: Int ..] subs] ++ rest) k
        -- a field matched by a pattern that looks at nothing, as (), leaves v unused
        pure (["if " ++ v ++ ", hg_ok := " ++ s ++ ".(" ++ struct ++ "); hg_ok {", "_ = " ++ v] ++ body ++ ["}"])
  where
    cond c = do
      body <- genPats ctx rest k
      pure (["if " ++ c ++ " {"] ++ body ++ ["}"])
    isWild CPWild = True
    isWild (CPCon "()" _ _) = True
    isWild _ = False

-- | Local bindings, declared first so they can refer to each other, then
-- assigned in dependency order. A function that returns an action gets its
-- run form too (see 'genRun').
genBinds :: Ctx -> [CBind] -> Gen (Ctx, [String])
genBinds ctx binds = do
  let ctx1 = bindLocals ctx [(n, ar) | CBind n _ ar _ <- binds]
      runs = [(n, ps, x) | CBind n _ ar (CLam ps r _) <- binds, ar > 0, length ps == ar, Just x <- [ioResult ctx r]]
      ctx' = ctx1 {cxRun = M.union (M.fromList [(n, (runName n, length ps)) | (n, ps, _) <- runs]) (cxRun ctx1)}
      names = [n | CBind n _ _ _ <- binds]
      sccs = stronglyConnComp
        [(b, n, filter (`elem` names) (coreRefs body)) | b@(CBind n _ _ body) <- binds]
      ordered = flattenSCCs sccs
      -- a function's group: those of its own binding group that may call it
      -- back, and the functions around, which may too
      groupOf n = S.union (cxGroup ctx) (S.fromList (n : concat [ms | CyclicSCC bs <- sccs, let ms = [m | CBind m _ _ _ <- bs], n `elem` ms]))
      decl (CBind n t ar _) =
        let (ps, r) = splitFun ar (zonk (progSubst (cxProg ctx)) t)
            ty = if ar == 0 then goTy ctx t else "func(" ++ commas (map (goTy ctx) ps) ++ ") " ++ goTy ctx r
         in "var " ++ mangle n ++ " " ++ ty
      runDecl (n, ps, x) = "var " ++ runName n ++ " func(" ++ commas (map (goTy ctx . snd) ps) ++ ") " ++ goTy ctx x
      orderedNames = [n | CBind n _ _ _ <- ordered]
      pendingFrom n = S.union (S.fromList (dropWhile (/= n) orderedNames)) (cxPending ctx')
      -- the run forms of functions that end calling each other, as loops
      localLoops = concat
        [ runLoops [((n, ps, inner, x), x) | CBind n _ _ (CLam ps _ inner) <- bs, (m, _, x) <- runs, m == n]
        | CyclicSCC bs <- sccs ]
      pureLocalLoops = concat
        [ runLoops [ ((n, ps, inner, r'), r') | CBind n _ ar (CLam ps r inner) <- bs, ar > 0, length ps == ar
                   , isNothing (ioResult ctx r), isNothing (ownedLoop ctx n ar ps inner)
                   , let r' = zonk (progSubst (cxProg ctx)) r ]
        | CyclicSCC bs <- sccs ]
  loops <- forM localLoops $ \ms -> case ms of
    [] -> pure Nothing
    (n0, _, _, x) : _ -> do
      let name = "hgloop_" ++ mangle n0
          c = (noSelf ctx') {cxPending = pendingFrom n0, cxGroup = groupOf n0}
          ty = "func(" ++ commas ("int" : [goTy ctx pt | (_, ps, _, _) <- ms, (_, pt) <- ps]) ++ ") " ++ goTy ctx x
      r <- genRunLoop False c name [(n, ps, inner) | (n, ps, inner, _) <- ms] x
      pure (fmap (\(fn, es) -> (["var " ++ name ++ " " ++ ty, name ++ " = func" ++ fn], es)) r)
  -- and the functions that end calling each other and are not actions
  ploops <- forM pureLocalLoops $ \ms -> case ms of
    [] -> pure Nothing
    (n0, _, _, x) : _ -> do
      let name = "hgloop_" ++ mangle n0
          c = (noSelf ctx') {cxPending = pendingFrom n0, cxGroup = groupOf n0}
          ty = "func(" ++ commas ("int" : [goTy ctx pt | (_, ps, _, _) <- ms, (_, pt) <- ps]) ++ ") " ++ goTy ctx x
      r <- genRunLoop True c name [(n, ps, inner) | (n, ps, inner, _) <- ms] x
      pure (fmap (\(fn, es) -> (["var " ++ name ++ " " ++ ty, name ++ " = func" ++ fn], es)) r)
  let entries = M.fromList (concat [es | Just (_, es) <- loops])
      pentries = M.fromList (concat [es | Just (_, es) <- ploops])
  assigns <- forM (zip ordered (tails' orderedNames)) $ \(CBind n _ ar body, pending) ->
    let c = (noSelf ctx') {cxPending = S.union (S.fromList pending) (cxPending ctx')}
     in case body of
          CLam ps r inner | ar > 0 -> do
            let c' = c {cxGroup = groupOf n}
            fn <- maybe (genFunction c' (Just (n, ar)) [] ps r inner) pure (M.lookup n pentries)
            runFn <- case (M.lookup n (cxRun ctx'), ioResult ctx r, M.lookup n entries) of
              (Just (rn, _), Just _, Just f) -> pure [rn ++ " = func" ++ f]
              (Just (rn, _), Just x, Nothing) -> (\f -> [rn ++ " = func" ++ f]) <$> genRunFunction c' (Just (n, ar)) ps x inner
              _ -> pure []
            pure ((mangle n ++ " = func" ++ fn) : runFn)
          _ -> do
            e <- genExpr c body
            pure [mangle n ++ " = " ++ e]
  pure (ctx', map decl binds ++ map runDecl runs ++ concat [ls | Just (ls, _) <- loops ++ ploops] ++ concat assigns ++ ["_ = " ++ mangle n | n <- names] ++ ["_ = " ++ runName n | (n, _, _) <- runs])
  where
    -- each binding, with itself and the ones after it, which are not assigned yet
    tails' xs = [drop i xs | i <- [0 .. length xs - 1]]

-- Expressions -------------------------------------------------------------------------

genExpr :: Ctx -> CExpr -> Gen String
genExpr ctx e = case e of
  CLit l -> pure (genLit l)
  CNum n t _ -> pure (numLit ctx n t)
  CVar x ref t -> genVar ctx x ref t
  CCon k targs t -> genApp ctx e [] (Just (conArity k)) (\args -> pure (conValue ctx k targs args)) t
  CApp f args -> case f of
    -- s ++ t on strings, with t suspended, needs no suspension: Go's + is
    -- strict, and t is generated once (generating the suspension too would
    -- make a chain of ++ exponential)
    CVar "primAppend" (Inst [targ] _) _
      | [a, CDelay _ inner] <- args
      , TCon "String" [] <- zonk (progSubst (cxProg ctx)) targ -> do
          a' <- genExpr ctx a
          b' <- genExpr ctx inner
          pure ("(" ++ a' ++ " + " ++ b' ++ ")")
    -- the Prelude's && and ||, whose second argument is suspended, are Go's,
    -- which only computes it when it is needed
    CVar op _ _
      | op `elem` ["&&", "||"], Just (VKTop 2 _ _) <- M.lookup op (cxVars ctx), [a, CDelay _ inner] <- args -> do
          a' <- genExpr ctx a
          b' <- genExpr ctx inner
          pure ("(" ++ a' ++ " " ++ op ++ " " ++ b' ++ ")")
    -- a call to Go: functions given to it are generated as Go functions of
    -- all their arguments at once (see 'foreignArg')
    -- a fold: a loop (see 'Prod'), over the list where it is made, or
    -- over its cells, without the curried closure listFoldl calls
    CVar "listFoldl" _ t
      | isTop ctx "listFoldl", [g, z, xs] <- args
      , fusable (prodOf ctx xs) ->
          fuseFoldl ctx t g z xs
    CVar "listFoldr" _ t
      | isTop ctx "listFoldr", [k, z, xs] <- args, fusable (prodOf ctx xs)
      , Just b <- ioResult ctx (snd (splitFun 3 t)), Just _ <- ioStepsOf ctx k -> do
          ls <- fuseFoldrIO ctx k xs
          end <- case z of
            CApp (CVar "primReturnIO" _ _) [x] | isPrim ctx "primReturnIO" -> (\x' -> "return rt_done[" ++ goTy ctx b ++ "](" ++ x' ++ ")") <$> genExpr ctx x
            _ -> (\z' -> "return rt_next[" ++ goTy ctx b ++ "](" ++ z' ++ ")") <$> genExpr ctx z
          pure ("func() IOStep[" ++ goTy ctx b ++ "] {\n" ++ unlines ls ++ end ++ "\n}")
      | isTop ctx "listFoldr", [k, z, xs] <- args, fusable (prodOf ctx xs), Just _ <- exitsOf ctx k ->
          fuseFoldr ctx t k z xs
      | isTop ctx "listFoldr", [k, z, xs] <- args, fusable (prodOf ctx xs), Just _ <- strictStepOf ctx k ->
          fuseFoldrBack ctx t k z xs
      | isTop ctx "listFoldr", [k, z, xs] <- args, Just (_, r, body) <- lam2 k, Just st <- stepOf ctx r body, producer st ->
          fuseFoldrLazy ctx t k z xs
    -- Iter.find (any, all, elem, head) of an Iter made right there
    CVar fn _ t | Just "rt_iterFind" <- foreignSym ctx fn, [q0, xs0] <- args
                , let p = iterProdOf ctx xs0, iterKnown p, fusable p -> do
      (q, xs) <- renamed2 q0 xs0
      let c0 = noSelf ctx
          r = snd (splitFun 2 (zonk (progSubst (cxProg ctx)) t))
          targs = case r of TCon _ ts -> ts; _ -> []
      loop <- genLoop c0 (iterProdOf c0 xs) $ \c x -> do
        (ls, _, y) <- applyNew c q [x]
        pure (ls ++ ["if " ++ mangle y ++ " {", "return " ++ conValue ctx "Right" targs [mangle x], "}"])
      pure ("func() " ++ goTy ctx r ++ " {\n" ++ unlines loop ++ "return " ++ conValue ctx "Left" targs ["\"not found\""] ++ "\n}()")
    -- a node changed in place (Data.Map's nodeT): its fields assigned, which
    -- Go does with a store each, instead of copying a whole node made for it
    CVar fn _ t | Just "rt_overwrite" <- foreignSym ctx fn, [dst, CApp (CCon k _ _) fs] <- args
                , Just ci <- M.lookup k (progCons (cxProg ctx)), Just Pointer <- M.lookup (ciType ci) (cxUnboxed ctx)
                , length fs == length (ciFields ci), not (null fs) -> do
      d <- genExpr ctx dst
      vs <- mapM (genExpr ctx) fs
      let ty = goTy ctx (snd (splitFun 2 (zonk (progSubst (cxProg ctx)) t)))
      pure ("func() " ++ ty ++ " {\nhg_d := " ++ d ++ "\n"
              ++ commas ["hg_d.F" ++ show i | i <- [0 .. length fs - 1]] ++ " = " ++ commas vs
              ++ "\nreturn hg_d\n}()")
    -- Iter.foldl (length, sum, maximum) of an Iter made right there: a loop
    CVar fn _ t | Just "rt_iterFoldl" <- foreignSym ctx fn, [g, z, xs] <- args
               , let p = iterProdOf ctx xs, iterKnown p, fusable p ->
      fuseFoldlWith iterProdOf ctx t g z xs
    -- an Iter made by a do: one Go function with the loops, which gives
    -- each value to yield
    CVar fn _ t | Just sym <- foreignSym ctx fn, "rt_iter" `isPrefixOf` sym
               , let p = iterProdOf ctx e, iterWorthIt p, fusable p
               , Just el <- iterElem (snd (splitFun (length args) (zonk (progSubst (cxProg ctx)) t))) -> do
      e' <- renamed e
      let ctx' = noSelf ctx
          elTy = goTy ctx el
      loop <- genLoop ctx' (iterProdOf ctx' e') $ \_ x -> pure ["if !hg_yield(" ++ mangle x ++ ") {", "return", "}"]
      pure ("rt_iter.Seq[" ++ elTy ++ "](func(hg_yield func(" ++ elTy ++ ") bool) {\n" ++ unlines loop ++ "})")
    -- a bind or a *> of IO is a do block of two statements, whose first is
    -- run on the spot and whose second goes back to the trampoline
    CVar "primBindIO" (Inst [a, b] _) _ | isPrim ctx "primBindIO", [m, k] <- args -> case k of
      CLam [(x, t)] _ body -> genDo ctx b [CSBind x t m, CSExpr b body]
      _ -> do
        v <- freshName "b"
        genDo ctx b [CSBind v a m, CSExpr b (CApp k [CVar v (Inst [] []) a])]
    CVar "primThenIO" (Inst [_, b] _) _ | isPrim ctx "primThenIO", [m, n] <- args ->
      genDo ctx b [CSExpr tUnit m, CSExpr b (case n of CDelay _ x -> x; _ -> CForce n)]
    -- an action run where it is made, as runST makes one
    CVar "primRunIO" (Inst [a] _) _ | isPrim ctx "primRunIO", [m] <- args -> do
      ls <- genRun (noSelf ctx) (RReturn False) m
      pure $ case ls of
        [l] | Just v <- stripReturn l -> v
        _ -> "func() " ++ goTy ctx a ++ " {\n" ++ unlines ls ++ "}()"
    CVar x ref _
      | Just (VKForeign fo) <- M.lookup x (cxVars ctx), fArity fo > 0, length args >= fArity fo -> do
          let (now, later) = splitAt (fArity fo) args
              targs = refTypes ctx ref
              (params, _) = splitFun (fArity fo) (foreignInst fo targs)
          as <- zipWith3M (foreignArg ctx (isRuntimeSymbol fo)) (fst (splitFun (fArity fo) (fType fo))) params now
          foldM (\acc a -> (\a' -> acc ++ "(" ++ a' ++ ")") <$> genExpr ctx a) (foreignCall ctx fo targs True as) later
    CVar x ref t | Just ar <- knownArity x, ar > 0 ->
      genApp ctx f args (Just ar) (\as -> call ctx x ref t as) t
    -- a cell kept behind a pointer, given suspensions for its lazy fields
    -- (a list's cell and its tail), is one allocation with its thunks
    -- instead of one each
    CCon k targs t
      | length args == conArity k, any isDelay args
      , Just ci <- M.lookup k (progCons (cxProg ctx)), Just Pointer <- M.lookup (ciType ci) (cxUnboxed ctx) -> do
          parts <- forM (zip [0 :: Int ..] args) $ \case
            (i, CDelay ty inner) | Just v <- nilTail ty inner -> pure (Left (i, v))
            (i, CDelay ty inner) -> do
              th <- thunkValue ty inner
              pure (Right (i, ty, th))
            (i, a) -> Left . (,) i <$> genExpr ctx a
          let st = conRef ctx k targs
              (_, r) = splitFun (length args) (zonk (progSubst (cxProg ctx)) t)
              thunks = [(i, ty, th) | Right (i, ty, th) <- parts]
          if null thunks then pure (conValue ctx k targs [v | Left (_, v) <- parts]) else pure $ "func() " ++ goTy ctx r ++ " {\n"
            ++ "hg_c := &struct{ c " ++ st ++ concat ["; t" ++ show i ++ " rt_thunk[" ++ goTy ctx ty ++ "]" | (i, ty, _) <- thunks] ++ " }{"
            ++ commas (("c: " ++ st ++ "{" ++ commas ["F" ++ show i ++ ": " ++ v | Left (i, v) <- parts] ++ "}") : ["t" ++ show i ++ ": " ++ th | (i, _, th) <- thunks])
            ++ "}\n"
            ++ concat ["hg_c.c.F" ++ show i ++ " = &hg_c.t" ++ show i ++ "\n" | (i, _, _) <- thunks]
            ++ "return &hg_c.c\n}()"
    CCon k targs t -> genApp ctx f args (Just (conArity k)) (\as -> pure (conValue ctx k targs as)) t
    _ -> do
      h <- genExpr ctx f
      applyAll h args
  CLam ps r body -> genLam ctx ps r body
  -- A value that is cheap to compute and cannot fail, such as a variable
  -- already computed or a constructor applied to such values, is computed
  -- now: a suspension that is already done is one allocation, and one that
  -- is not is two (the thunk and the closure).
  CDelay t inner -> case inner of
    _ | Just v <- nilTail t inner -> pure v
    _ | isValue inner -> do
          v <- genExpr ctx inner
          pure ("rt_ready[" ++ goTy ctx t ++ "](" ++ v ++ ")")
    CVar {} -> do
      v <- genExpr ctx inner
      pure ("rt_lazy(func() " ++ goTy ctx t ++ " { return " ++ v ++ " })")
    _ -> do
      ls <- genStmts (noSelf ctx) inner
      pure ("rt_lazy(func() " ++ goTy ctx t ++ " {\n" ++ unlines ls ++ "})")
  CForce inner -> (++ ".force()") <$> genExpr ctx inner
  CDo _ _ r stmts -> genDo ctx r stmts
  CFrac x t _ -> pure $ case zonk (progSubst (cxProg ctx)) t of
    TCon "Double" [] -> show x
    _ -> error "codegen: a decimal literal at a type other than Double"
  CMatch _ _ t -> iife t
  CLet _ _ t -> iife t
  CIf _ _ _ t -> iife t
  where
    knownArity x = case M.lookup x (cxVars ctx) of
      Just (VKTop a _ _) -> Just a
      Just (VKLocal a) -> Just a
      Just (VKForeign f) -> Just (fArity f)
      Just (VKPrim a) -> Just a
      Nothing -> Nothing
    conArity k = length (ciFields (progCons (cxProg ctx) M.! k))
    isDelay = \case
      CDelay {} -> True
      _ -> False
    -- [] suspended, computed already: the one thunk every list shares
    nilTail ty inner = case (zonk (progSubst (cxProg ctx)) ty, inner) of
      (TCon "[]" [el], CCon "[]" _ _) -> Just ("rt_nilTail[" ++ goTy ctx el ++ "]()")
      _ -> Nothing
    -- a suspension as a thunk's value, to be kept inside another struct,
    -- computed now when that does the same (see CDelay)
    thunkValue ty inner
      | isValue inner = (\v -> "rt_thunk[" ++ goTy ctx ty ++ "]{v: " ++ v ++ ", state: 2}") <$> genExpr ctx inner
      | otherwise = do
          ls <- genStmts (noSelf ctx) inner
          pure ("rt_thunk[" ++ goTy ctx ty ++ "]{f: func() " ++ goTy ctx ty ++ " {\n" ++ unlines ls ++ "}}")
    -- computing it now does the same as later: it is total, cheap, and does
    -- not read a variable that is still being defined
    isValue = \case
      CLit _ -> True
      CNum {} -> True
      CFrac {} -> True
      CCon {} -> True
      CLam {} -> True
      CDelay {} -> True
      CVar x _ _
        | S.member x (cxPending ctx) -> False
        | otherwise -> case M.lookup x (cxVars ctx) of
            Just (VKLocal _) -> True
            Just (VKTop a _ _) -> a > 0
            Just (VKForeign f) -> fArity f > 0
            Just (VKPrim a) -> a > 0
            Nothing -> False
      CApp (CCon _ _ _) as -> all isValue as
      _ -> False
    iife t = do
      ls <- genStmts (noSelf ctx) e
      pure ("func() " ++ goTy ctx t ++ " {\n" ++ unlines ls ++ "}()")
    applyAll h [] = pure h
    applyAll h (a : as) = do
      a' <- genExpr ctx a
      applyAll (h ++ "(" ++ a' ++ ")") as

-- | A head that takes n arguments directly: saturated calls go straight to
-- it, partial ones go through a curried wrapper, extra arguments are applied
-- one by one to the result.
genApp :: Ctx -> CExpr -> [CExpr] -> Maybe Int -> ([String] -> Gen String) -> Type -> Gen String
genApp ctx _ args (Just n) mk t
  | length args >= n = do
      let (now, later) = splitAt n args
      as <- mapM (genExpr ctx) now
      h <- mk as
      foldM (\acc a -> (\a' -> acc ++ "(" ++ a' ++ ")") <$> genExpr ctx a) h later
  | otherwise = do
      names <- replicateM n (freshName "x")
      let (ps, r) = splitFun n (zonk (progSubst (cxProg ctx)) t)
      body <- mk names
      let lam = curried ctx (zip names ps) r body
      foldM (\acc a -> (\a' -> "(" ++ acc ++ ")(" ++ a' ++ ")") <$> genExpr ctx a) lam args
genApp ctx _ args Nothing mk _ = do
  h <- mk []
  foldM (\acc a -> (\a' -> acc ++ "(" ++ a' ++ ")") <$> genExpr ctx a) h args

curried :: Ctx -> [(String, Type)] -> Type -> String -> String
curried _ [] _ body = body
curried ctx ((n, p) : rest) r body =
  "func(" ++ n ++ " " ++ goTy ctx p ++ ") " ++ goTy ctx (foldr (TFun . snd) r rest)
    ++ " { return " ++ curried ctx rest r body ++ " }"

genVar :: Ctx -> Name -> VRef -> Type -> Gen String
genVar ctx x ref t = case M.lookup x (cxVars ctx) of
  Just (VKTop 0 _ True) -> pure (mangle x)
  Just (VKTop 0 _ False) -> pure (mangle x ++ insts ++ "(" ++ commas (dictArgs ctx ref) ++ ")")
  Just (VKLocal 0) -> pure (mangle x)
  Just (VKForeign f) | fArity f == 0 -> pure (foreignCall ctx f (refTypes ctx ref) True [])
  Just (VKPrim 0) -> call ctx x ref t []
  Just _ -> genExpr ctx (CApp (CVar x ref t) [])
  Nothing -> error ("codegen: unknown variable " ++ x)
  where
    insts = case ref of
      Inst ts _ -> typeArgs ctx ts
      SelfGroup -> if null (cxTParams ctx) then "" else "[" ++ commas (map tyVar (cxTParams ctx)) ++ "]"

-- | A saturated call to a known function.
call :: Ctx -> Name -> VRef -> Type -> [String] -> Gen String
call ctx x ref _ as = case M.lookup x (cxVars ctx) of
  Just (VKTop _ tps _) -> pure (mangle x ++ insts tps ++ "(" ++ commas (dictArgs ctx ref ++ as) ++ ")")
  Just (VKLocal _) -> pure (mangle x ++ "(" ++ commas as ++ ")")
  Just (VKForeign f) -> pure (foreignCall ctx f (refTypes ctx ref) False as)
  Just (VKPrim _) -> genPrim ctx x targs as
  Nothing -> error ("codegen: unknown function " ++ x)
  where
    targs = case ref of
      Inst ts _ -> map (zonk (progSubst (cxProg ctx))) ts
      SelfGroup -> []
    insts tps = case ref of
      Inst ts _ -> typeArgs ctx ts
      SelfGroup -> if null tps then "" else "[" ++ commas (map tyVar (cxTParams ctx)) ++ "]"

genPrim :: Ctx -> Name -> [Type] -> [String] -> Gen String
genPrim ctx x targs as = case (x, as) of
  (op, [a, b]) | Just o <- lookup op binops -> pure ("(" ++ a ++ " " ++ o ++ " " ++ b ++ ")")
  ("primNeg", [a]) -> pure ("(-" ++ a ++ ")")
  ("primDiv", [a, b]) -> pure ("rt_div(" ++ a ++ ", " ++ b ++ ")")
  ("primMod", [a, b]) -> pure ("rt_mod(" ++ a ++ ", " ++ b ++ ")")
  ("primShow", [a]) -> pure $ case targs of
    [TCon "Int" []] -> "rt_strconv.Itoa(" ++ a ++ ")"
    [TCon "Double" []] -> "rt_showDouble(" ++ a ++ ")"
    [TCon "Char" []] -> "rt_strconv.QuoteRune(" ++ a ++ ")"
    [TCon "String" []] -> "rt_strconv.Quote(" ++ a ++ ")"
    _ -> "rt_fmt.Sprint(" ++ a ++ ")"
  ("primIntToDouble", [a]) -> pure ("float64(" ++ a ++ ")")
  ("primTruncate", [a]) -> pure ("int(" ++ a ++ ")")
  ("putStrLn", [a]) -> pure (action ("rt_fmt.Println(" ++ a ++ ")"))
  ("putStr", [a]) -> pure (action ("rt_fmt.Print(" ++ a ++ ")"))
  ("getLine", []) -> pure "rt_getLine"
  ("primReturnIO", [a]) -> pure ("rt_pure" ++ typeArgs ctx targs ++ "(" ++ a ++ ")")
  ("primBindIO", [a, b]) -> pure ("rt_bind" ++ typeArgs ctx targs ++ "(" ++ a ++ ", " ++ b ++ ")")
  ("primThenIO", [a, b]) -> pure ("rt_then" ++ typeArgs ctx targs ++ "(" ++ a ++ ", " ++ b ++ ")")
  ("primRunIO", [a]) -> pure ("rt_run" ++ typeArgs ctx targs ++ "(" ++ a ++ ")")
  ("error", [a]) -> pure ("rt_error" ++ typeArgs ctx targs ++ "(" ++ a ++ ")")
  ("primAppend", [a, b]) -> case targs of
    [TCon "String" []] -> pure ("(" ++ a ++ " + " ++ b ++ ".force())")
    [TCon "[]" [el]] -> pure (mangle "append" ++ typeArgs ctx [el] ++ "(" ++ a ++ ", " ++ b ++ ")")
    _ -> pure ("rt_error[" ++ goTy ctx (case targs of (t : _) -> t; [] -> tUnit) ++ "](\"primAppend needs a String or a list\")")
  ("primNilNow", [a]) -> pure ("rt_nilNow(" ++ a ++ ")")
  ("pack", [a]) -> pure ("rt_pack(" ++ a ++ ")")
  ("unpack", [a]) -> pure ("rt_unpack(" ++ a ++ ")")
  ("ord", [a]) -> pure ("int(" ++ a ++ ")")
  ("chr", [a]) -> pure ("rune(" ++ a ++ ")")
  _ -> error ("codegen: bad primitive call " ++ x)
  where
    binops =
      [ ("primEq", "=="), ("primNeq", "!="), ("primLt", "<"), ("primLe", "<="), ("primGt", ">")
      , ("primGe", ">="), ("primAdd", "+"), ("primSub", "-"), ("primMul", "*"), ("primFDiv", "/")
      , ("primQuot", "/"), ("primRem", "%") ]
    action e = "func() IOStep[struct{}] { " ++ e ++ "; return rt_done(struct{}{}) }"

-- Dictionaries -------------------------------------------------------------------------

resolveDict :: Ctx -> Dict -> Dict
resolveDict ctx = \case
  DHole h -> case IM.lookup h (progSolved (cxProg ctx)) of
    Just d -> resolveDict ctx d
    Nothing -> error ("codegen: unsolved constraint " ++ show h)
  d -> d

-- | Specialisation resolves every dictionary at compile time.
dictArgs :: Ctx -> VRef -> [String]
dictArgs ctx = \case
  Inst _ ds -> map (genDict ctx) ds
  SelfGroup -> []

genDict :: Ctx -> Dict -> String
genDict ctx d = error ("codegen: a dictionary at run time: " ++ show (resolveDict ctx d))

numLit :: Ctx -> Integer -> Type -> String
numLit ctx n t = case zonk (progSubst (cxProg ctx)) t of
  TCon "Int" [] -> show n
  TCon "Double" [] -> show n ++ ".0"
  _ -> error "codegen: a number literal at a type other than Int or Double"

-- | Whether a Go function from outside the runtime may make the program run
-- on several goroutines: any that is given a Hago function or action, which
-- Go code could call from another goroutine (net/http calls a handler on
-- one per request).
startsGoroutines :: Foreign -> Bool
startsGoroutines f = not (isRuntimeSymbol f) && any callable (fst (splitFun (fArity f) (fType f)))
  where
    callable = \case
      TFun _ _ -> True
      TCon "IO" _ -> True
      TCon _ ts -> any callable ts
      _ -> False

-- | The types a use of a polymorphic name instantiates its variables with.
refTypes :: Ctx -> VRef -> [Type]
refTypes ctx = \case
  Inst ts _ -> map (zonk (progSubst (cxProg ctx))) ts
  SelfGroup -> []

-- | A call to a Go function. A polymorphic one is a generic Go function whose
-- type parameters are the Hago type variables in the order they first appear
-- in its signature, and it is given them explicitly: Go cannot infer a type
-- parameter that only the result has (newEmptyMVar :: IO (MVar a)).
foreignCall :: Ctx -> Foreign -> [Type] -> Bool -> [String] -> String
foreignCall ctx f targs adapted as0 = case declared of
  -- the conventions (IO (), Either for an error) follow the declared type:
  -- takeMVar :: MVar a -> IO a stays a plain call at a = Either e b
  TCon "IO" [TCon "()" []] -> "func() IOStep[struct{}] { " ++ goCall ++ "; return rt_done(struct{}{}) }"
  TCon "IO" [TCon "Either" [_, _]] ->
    "func() IOStep[" ++ goTy ctx t ++ "] { return rt_done(func() " ++ goTy ctx t ++ " {\n" ++ eitherBody t ++ "}()) }"
  TCon "IO" [_] -> "func() IOStep[" ++ goTy ctx t ++ "] { return rt_done[" ++ goTy ctx t ++ "](" ++ goCall ++ ") }"
  TCon "Either" [_, _] -> "func() " ++ goTy ctx t ++ " {\n" ++ eitherBody t ++ "}()"
  _ -> goCall
  where
    (declared, t, goCall, eitherBody) = foreignParts ctx f targs adapted as0

-- | A call to Go that makes an action, run at once (see 'genRun'): what to
-- do, and then the value of its result.
foreignRun :: Ctx -> Foreign -> [Type] -> [String] -> ([String], String)
foreignRun ctx f targs as = case declared of
  TCon "IO" [TCon "()" []] -> ([goCall], "struct{}{}")
  TCon "IO" [TCon "Either" [_, _]] -> ([], "func() " ++ goTy ctx t ++ " {\n" ++ eitherBody t ++ "}()")
  _ -> ([], goCall)
  where
    (declared, t, goCall, eitherBody) = foreignParts ctx f targs True as

-- | A read or a write of a mutable vector, run at once: written out where
-- it is, for the case without a lock and with the index in range (uint(i)
-- < len is both tests, and Go then checks nothing more), since Go does not
-- inline the runtime's generic functions here; the rest, the lock and the
-- error, is the runtime's.
vectorAccess :: Ctx -> Foreign -> [Type] -> [String] -> Gen (Maybe ([String], String))
vectorAccess ctx fo targs as = case (fSymbol fo, as) of
  ("rt_mvecWrite", [v, i, x]) -> do
    vv <- freshName "v"
    iv <- freshName "i"
    xv <- freshName "x"
    pure $ Just
      ( [ vv ++ " := " ++ v, iv ++ " := " ++ i, xv ++ " := " ++ x
        , "if " ++ vv ++ ".mu == nil && uint(" ++ iv ++ ") < uint(len(" ++ vv ++ ".xs)) {"
        , vv ++ ".xs[" ++ iv ++ "] = " ++ xv, "} else {", "rt_mvecWriteSlow(" ++ vv ++ ", " ++ iv ++ ", " ++ xv ++ ")", "}" ]
      , "struct{}{}" )
  ("rt_mvecRead", [v, i]) | TCon "IO" [el] <- snd (splitFun 2 (foreignInst fo targs)) -> do
    vv <- freshName "v"
    iv <- freshName "i"
    yv <- freshName "y"
    pure $ Just
      ( [ vv ++ " := " ++ v, iv ++ " := " ++ i, "var " ++ yv ++ " " ++ goTy ctx el
        , "if " ++ vv ++ ".mu == nil && uint(" ++ iv ++ ") < uint(len(" ++ vv ++ ".xs)) {"
        , yv ++ " = " ++ vv ++ ".xs[" ++ iv ++ "]", "} else {", yv ++ " = rt_mvecReadSlow(" ++ vv ++ ", " ++ iv ++ ")", "}" ]
      , yv )
  _ -> pure Nothing

-- | Whether a function from Go makes an action.
foreignIO :: Foreign -> Bool
foreignIO f = case snd (splitFun (fArity f) (fType f)) of
  TCon "IO" _ -> True
  _ -> False

-- | The type a call to Go was declared with, the type of what it gives (in
-- an action or not), the call, and the body of a Go function that makes an
-- Either from a Go function that returns an error.
foreignParts :: Ctx -> Foreign -> [Type] -> Bool -> [String] -> (Type, Type, String, Type -> String)
foreignParts ctx f targs adapted as0 = (declared, t, goCall, eitherBody)
  where
    (_, declared) = splitFun (fArity f) (fType f)
    t = case r of TCon "IO" [x] -> x; x -> x
    (params, r) = splitFun (fArity f) (foreignInst f targs)
    isIO = case r of TCon "IO" _ -> True; _ -> False
    -- arguments already made into what Go expects, or values to adapt
    as = if adapted then as0 else zipWith3 (callback ctx (isRuntimeSymbol f)) (fst (splitFun (fArity f) (fType f))) params as0
    sym = snd (splitSymbol (fSymbol f)) ++ (if length targs == length (fVars f) then typeArgs ctx targs else "")
    goCall = case (fSymbol f, as) of
      -- ".Body.Close()": a selector on the first argument, a field or a method
      ('.' : _, recv : rest) -> "(" ++ recv ++ ")" ++ fSymbol f ++ (if null rest then "" else "(" ++ commas rest ++ ")")
      ('.' : _, []) -> error ("codegen: the selector " ++ fSymbol f ++ " needs a value to select from")
      _ | fArity f == 0 && not isIO -> sym
      _ -> sym ++ "(" ++ commas as ++ ")"
    -- a Go function that returns (T, error) is an Either String T; one that
    -- returns only an error is an Either String ()
    eitherBody e =
      let targsOf = case e of TCon _ ts -> ts; _ -> []
          unitRight = case declared of
            TCon "IO" [TCon "Either" [_, TCon "()" []]] -> True
            TCon "Either" [_, TCon "()" []] -> True
            _ -> False
       in unlines
            [ (if unitRight then "hg_err := " else "hg_v, hg_err := ") ++ goCall
            , "if hg_err != nil { return " ++ conValue ctx "Left" targsOf ["hg_err.Error()"] ++ " }"
            , "return " ++ conValue ctx "Right" targsOf [if unitRight then "struct{}{}" else "hg_v"] ]

-- | A Hago function or action already computed, given to a Go function: see
-- 'foreignArg', which makes better code when it sees the function's source.
--
-- The shape of what Go gets is the declared type's (decl), with the types of
-- this call (ty): a parameter declared a -> b takes a function of one
-- argument even where b is a function, and one declared a takes any value
-- as it is.
callback :: Ctx -> Bool -> Type -> Type -> String -> String
callback ctx runtime decl ty a = case decl of
  TFun _ _ | runtime, [_] <- args -> a
  TFun _ _ -> goFunc ctx runtime args res (\ps -> "(" ++ a ++ ")" ++ concat ["(" ++ p ++ ")" | p <- ps])
  TCon "IO" [_] | not runtime -> goFunc ctx runtime [] ty (const a)
  _ -> a
  where
    (args, res) = splitFun (arrows decl) ty

zipWith3M :: Applicative m => (a -> b -> c -> m d) -> [a] -> [b] -> [c] -> m [d]
zipWith3M f as bs cs = sequenceA (zipWith3 f as bs cs)

-- | A Go function of all the arguments at once, whose body applies the Hago
-- function (given the parameter names). For a Go function from outside the
-- runtime, an action it makes is run and its result returned (nothing for
-- ()), and a failure in it ends the program, as in any thread: Go may call
-- it from any goroutine (net/http calls a handler on one per request). The
-- runtime's functions get the action itself.
goFunc :: Ctx -> Bool -> [Type] -> Type -> ([String] -> String) -> String
goFunc ctx runtime args res apply =
  "func(" ++ commas [p ++ " " ++ goTy ctx x | (p, x) <- zip ps args] ++ ")" ++ resTy
    ++ " {\n" ++ (if runtime then "" else "defer rt_failed()\n") ++ body ++ "\n}"
  where
    ps = ["hg_p" ++ show i | i <- [0 .. length args - 1]]
    applied = apply ps
    (resTy, body) = case res of
      TCon "IO" [TCon "()" []] | not runtime -> ("", "rt_run(" ++ applied ++ ")")
      TCon "IO" [x] | not runtime -> (" " ++ goTy ctx x, "return rt_run(" ++ applied ++ ")")
      x -> (" " ++ goTy ctx x, "return " ++ applied)

-- | The Go type of what 'goFunc' makes.
goFuncType :: Ctx -> Bool -> [Type] -> Type -> String
goFuncType ctx runtime args res = "func(" ++ commas (map (goTy ctx) args) ++ ")" ++ case res of
  TCon "IO" [TCon "()" []] | not runtime -> ""
  TCon "IO" [x] | not runtime -> " " ++ goTy ctx x
  x -> " " ++ goTy ctx x

-- | A Go function's type, with its type variables given.
foreignInst :: Foreign -> [Type] -> Type
foreignInst f targs = substTV (M.fromList (zip (fVars f) targs)) (fType f)

-- | The runtime's own functions take Hago's actions as they are; any other Go
-- function gets them made into Go functions that run them.
isRuntimeSymbol :: Foreign -> Bool
isRuntimeSymbol f = "rt_" `isPrefixOf` fSymbol f

-- | An argument of a call to Go. A function is given as a Go function of all
-- its arguments at once; when its source is a lambda or a known function,
-- that function is generated directly, without the curried closures a
-- function value has, which would allocate one per argument on each call.
foreignArg :: Ctx -> Bool -> Type -> Type -> CExpr -> Gen String
foreignArg ctx runtime decl ty e = case decl of
  TFun _ _
    | [_] <- args, runtime -> genExpr ctx e
    | otherwise -> case e of
        CLam ps _ body | length ps == n -> do
          let ctx' = noSelf (bindLocals ctx [(p, 0) | (p, _) <- ps])
          ls <- genStmts ctx' body
          let direct = "func(" ++ commas [mangle p ++ " " ++ goTy ctx t | (p, t) <- ps] ++ ") " ++ goTy ctx res ++ " {\n" ++ unlines ls ++ "}"
          pure (if runtime then direct else goFunc ctx runtime args res (\qs -> direct ++ "(" ++ commas qs ++ ")"))
        CVar x ref t | Just k <- arityOf x, k == n -> do
          let names = ["hg_p" ++ show i | i <- [0 .. n - 1]]
          body <- call ctx x ref t names
          pure (goFunc ctx runtime args res (const body))
        -- a known function given some of its arguments: those are computed
        -- once, before the Go function is made
        CApp (CVar x ref t) given | Just k <- arityOf x, k == length given + n -> do
          vals <- mapM (genExpr ctx) given
          vars <- mapM (const (freshName "a")) given
          let names = ["hg_p" ++ show i | i <- [0 .. n - 1]]
          body <- call ctx x ref t (vars ++ names)
          pure ("func() " ++ goFuncType ctx runtime args res ++ " {\n" ++ unlines [v ++ " := " ++ a | (v, a) <- zip vars vals]
                  ++ "return " ++ goFunc ctx runtime args res (const body) ++ "\n}()")
        _ -> callback ctx runtime decl ty <$> genExpr ctx e
  TCon "IO" [_] | not runtime -> callback ctx runtime decl ty <$> genExpr ctx e
  _ -> genExpr ctx e
  where
    (args, res) = splitFun (arrows decl) ty
    n = length args
    arityOf x = case M.lookup x (cxVars ctx) of
      Just (VKTop a _ _) -> Just a
      Just (VKLocal a) -> Just a
      Just (VKPrim a) -> Just a
      _ -> Nothing

conValue :: Ctx -> Name -> [Type] -> [String] -> String
conValue ctx k targs as = case k of
  "True" -> "true"
  "False" -> "false"
  "()" -> "struct{}{}"
  _ | Just ci <- M.lookup k (progCons (cxProg ctx)), Just Pointer <- M.lookup (ciType ci) (cxUnboxed ctx) ->
        if null (ciFields ci)
          then goTy ctx (TCon (ciType ci) targs) ++ "(nil)"
          else "&" ++ conRef ctx k targs ++ "{" ++ commas as ++ "}"
  _ | Just ci <- M.lookup k (progCons (cxProg ctx)), Just Tagged <- M.lookup (ciType ci) (cxUnboxed ctx) ->
        typeName (ciType ci) ++ typeArgs ctx targs ++ "{" ++ commas (("tag: " ++ show (ciTag ci)) : [taggedField ci i ++ ": " ++ a | (i, a) <- zip [0 :: Int ..] as]) ++ "}"
  _ -> conRef ctx k targs ++ "{" ++ commas as ++ "}"

-- | The field of a tagged struct that holds a constructor's i-th field.
taggedField :: ConInfo -> Int -> String
taggedField ci i = "K" ++ show (ciTag ci) ++ "_" ++ show i

genLam :: Ctx -> [(Name, Type)] -> Type -> CExpr -> Gen String
genLam ctx ps r body = go ps
  where
    ctx' = noSelf (bindLocals ctx [(p, 0) | (p, _) <- ps])
    go [] = error "genLam: no parameters"
    go [(p, t)] = do
      ls <- genStmts ctx' body
      pure ("func(" ++ mangle p ++ " " ++ goTy ctx t ++ ") " ++ goTy ctx r ++ " {\n" ++ unlines ls ++ "}")
    go ((p, t) : rest) = do
      inner <- go rest
      let restTy = foldr (TFun . snd) r rest
      pure ("func(" ++ mangle p ++ " " ++ goTy ctx t ++ ") " ++ goTy ctx restTy ++ " { return " ++ inner ++ " }")

genDo :: Ctx -> Type -> [CStmt] -> Gen String
genDo ctx0 r stmts = do
  ls <- go (noSelf ctx0) stmts
  pure ("func() IOStep[" ++ rt ++ "] {\n" ++ unlines ls ++ "}")
  where
    rt = goTy ctx0 r
    -- the last action is returned to rt_run instead of called: a tail call
    go _ [] = pure []
    go ctx [CSExpr _ e] = case e of
      CApp (CVar n _ _) [x] | n `elem` ["primReturnIO", instMethodName "inst_Applicative_IO" "pure"] ->
        (\x' -> ["return rt_done[" ++ rt ++ "](" ++ x' ++ ")"]) <$> genExpr ctx x
      _ -> (\e' -> ["return rt_next[" ++ rt ++ "](" ++ e' ++ ")"]) <$> genExpr ctx e
    -- the others are run on the spot (see 'genRun')
    go ctx (s : rest) = case s of
      CSExpr _ e -> (++) <$> genRun ctx RDiscard e <*> go ctx rest
      CSBind "_" _ e -> (++) <$> genRun ctx RDiscard e <*> go ctx rest
      CSBind x t e -> (\a b -> a ++ unshare ctx x e rest ++ b) <$> genRun ctx (RBind x t) e <*> go (bindLocals ctx [(x, 0)]) rest
      CSLet bs -> do
        (ctx', ls) <- genBinds ctx bs
        (ls ++) <$> go ctx' rest

-- Running actions directly ------------------------------------------------------

-- An action is a closure that the trampoline (rt_run) calls, and a function
-- that returns one returns a closure made on every call. Where an action is
-- run as soon as it is made (a statement in a do block, the action a
-- function returns when that function's own action is run), it does not
-- need to exist: 'genRun' makes the statements that run it. A function
-- that returns an action also gets a run form, hgrun_f, which runs what f
-- would return and returns its result; a call to f that is run at once
-- calls hgrun_f instead.
--
-- The trampoline is there so that loops written as recursion, and
-- functions that end calling each other, run in constant stack. In a run
-- form, a tail call to itself becomes a loop, as in a pure function, and
-- the run forms of functions that call each other and give the same type
-- are one loop (see 'genRunLoop'), around which a tail call to any of them
-- goes; one to a function that cannot call it back (a later one in
-- dependency order) is a direct call, so a chain of them is as long as the
-- program has functions. A tail call to one that may call it back
-- otherwise (one that gives another type, a function around a local one)
-- goes through the trampoline, and so does every action whose source is
-- not known (a parameter, a suspension). Once on the trampoline, a loop
-- stays on it. main, when nothing refers to it, is run the same way.

-- | What becomes of an action's result: returned (True: from a run form,
-- where tail calls loop; False: from a Go function called on the spot),
-- dropped, or bound to a variable of a type.
data RunK = RReturn Bool | RDiscard | RBind Name Type

runName :: Name -> String
runName n = "hgrun_" ++ mangle n

-- | What an action of this type gives, if it is one.
ioResult :: Ctx -> Type -> Maybe Type
ioResult ctx t = case zonk (progSubst (cxProg ctx)) t of
  TCon "IO" [x] -> Just x
  _ -> Nothing

-- | A top-level function that returns an action has a run form.
hasRunForm :: Program -> TopBind -> Bool
hasRunForm prog b = case tbBody b of
  CLam ps r _ -> tbArity b > 0 && not (tbShared b) && length ps == tbArity b && case zonk (progSubst prog) r of
    TCon "IO" [_] -> True
    _ -> False
  _ -> False

isPrim :: Ctx -> Name -> Bool
isPrim ctx n = case M.lookup n (cxVars ctx) of
  Just (VKPrim _) -> True
  _ -> False

stripReturn :: String -> Maybe String
stripReturn l = if "return " `isPrefixOf` l then Just (drop 7 l) else Nothing

-- | The parameters, result type and body of a run form.
genRunFunction :: Ctx -> Maybe (Name, Int) -> [(Name, Type)] -> Type -> CExpr -> Gen String
genRunFunction ctx self ps x inner = do
  saved <- gets gsLoop
  modify (\s -> s {gsLoop = False})
  let ctx' = (bindLocals ctx [(p, 0) | (p, _) <- ps]) {cxSelf = self, cxSelfParams = map fst ps}
  ls <- genRun ctx' (RReturn True) inner
  looped <- gets gsLoop
  modify (\s -> s {gsLoop = saved})
  let params = commas [(if looped then nextName p else mangle p) ++ " " ++ goTy ctx pt | (p, pt) <- ps]
      body = if looped then ["for {"] ++ roundStart (map fst ps) ++ ls ++ ["}"] else ls
  pure (unlines (["(" ++ params ++ ") " ++ goTy ctx x ++ " {"] ++ body ++ ["}"]))

-- | The run forms of functions that end calling each other, as one Go
-- function: a loop over which of them is running, whose tail calls to one
-- another (and to themselves) assign the arguments and go round again.
-- They have the same type parameters (the enclosing context's) and give
-- the same type, x. Only those that go round in a circle of such calls,
-- two or more, are the loop: a chain of tail calls that ends is as long
-- as the program is, and goes faster as direct calls. The result, unless
-- there is no circle: the loop, as a function's parameters, result and
-- body, and for each of its functions, the form that enters the loop there
-- (the run form, or for pure functions the function itself).
genRunLoop :: Bool -> Ctx -> String -> [(Name, [(Name, Type)], CExpr)] -> Type -> Gen (Maybe (String, [(Name, String)]))
genRunLoop pure' ctx loopName members x = do
  saved <- gets gsJumped
  modify (\s -> s {gsJumped = []})
  let nexts = [[loopNext i p | (p, _) <- ps] | (i, (_, ps, _)) <- zip [0 :: Int ..] members]
      loop = M.fromList [(n, (i, ns)) | (i, (n, _, _), ns) <- zip3 [0 ..] members nexts]
  cases <- forM (zip3 [0 :: Int ..] members nexts) $ \(i, (_, ps, body), ns) -> do
    let ctx' = bindLocals ((noSelf ctx) {cxLoop = (i, loop)}) [(p, 0) | (p, _) <- ps]
    ls <- if pure' then genStmts ctx' body else genRun ctx' (RReturn True) body
    pure (["case " ++ show i ++ ":"] ++ concat [[mangle p ++ " := " ++ nx, "_ = " ++ mangle p] | ((p, _), nx) <- zip ps ns] ++ ls)
  jumps <- gets gsJumped
  modify (\s -> s {gsJumped = saved})
  let circles = S.fromList
        [ i | CyclicSCC is <- stronglyConnComp [(i, i, [j | (f, j) <- jumps, f == i]) | i <- [0 .. length members - 1]]
        , length is > 1, i <- is ]
  let params = commas ("hg_which int" : [nx ++ " " ++ goTy ctx pt | ((_, ps, _), ns) <- zip members nexts, ((_, pt), nx) <- zip ps ns])
      fn = unlines (["(" ++ params ++ ") " ++ goTy ctx x ++ " {", "for {", "switch hg_which {"] ++ concat cases ++ ["}", "}", "}"])
      insts = if null (cxTParams ctx) then "" else "[" ++ commas (map tyVar (cxTParams ctx)) ++ "]"
      entry :: Int -> (Name, [(Name, Type)], CExpr) -> (Name, String)
      entry i (n, ps, _) =
        let args = show i : concat [if j == i then map (mangle . fst) qs else ["*new(" ++ goTy ctx qt ++ ")" | (_, qt) <- qs] | (j, (_, qs, _)) <- zip [0 ..] members]
         in (n, unlines ["(" ++ commas [mangle p ++ " " ++ goTy ctx pt | (p, pt) <- ps] ++ ") " ++ goTy ctx x ++ " {", "return " ++ loopName ++ insts ++ "(" ++ commas args ++ ")", "}"])
  if S.null circles
    then pure Nothing
    else
      if S.size circles < length members
        then genRunLoop pure' ctx loopName [m | (i, m) <- zip [0 :: Int ..] members, S.member i circles] x
        else pure (Just (fn, zipWith entry [0 ..] members))
  where
    loopNext i p = "hg_next" ++ show i ++ "_" ++ mangle p

-- | The functions of a loop have the same type parameters (local ones,
-- none of their own), and a call that goes round it must be at those.
sameLoopInstance :: Ctx -> VRef -> Bool
sameLoopInstance ctx ref = case refTypes ctx ref of
  [] -> True
  ts -> ts == map TVar (cxTParams ctx)

-- | The groups of functions whose run forms can be one loop (see
-- 'genRunLoop'): of a group of mutually recursive ones, those that have a
-- run form, by the type they give; at least two in each.
runLoops :: Eq k => [(a, k)] -> [[a]]
runLoops ms = filter ((> 1) . length) [[n | (n, k') <- ms, k' == k] | k <- nub (map snd ms)]

-- | Statements that run the action and do with its result what k says.
genRun :: Ctx -> RunK -> CExpr -> Gen [String]
genRun ctx k e = case e of
  CDo m _ _ stmts | Just _ <- ioResult ctx (tApp m tUnit) -> sequenced stmts
  CApp (CVar "primReturnIO" _ _) [x] | isPrim ctx "primReturnIO" -> finish <$> genExpr ctx x
  CApp (CVar "primBindIO" _ _) [m, CLam [(x, t)] _ body] | isPrim ctx "primBindIO" ->
    sequenced [CSBind x t m, CSExpr t body]
  CApp (CVar "primBindIO" (Inst [a, _] _) _) [m, f] | isPrim ctx "primBindIO" -> do
    v <- freshName "b"
    sequenced [CSBind v a m, CSExpr a (CApp f [CVar v (Inst [] []) a])]
  CApp (CVar "primThenIO" _ _) [a, b] | isPrim ctx "primThenIO" ->
    sequenced [CSExpr tUnit a, CSExpr tUnit (case b of CDelay _ x -> x; _ -> CForce b)]
  -- the same in a monad that passes a state, as StateT over IO does once
  -- its newtype is gone: the fold makes a function of the state, applied to
  -- the first one
  CApp (CVar "listFoldr" _ t) [kf, z, xs, s0]
    | isTop ctx "listFoldr", fusable (prodOf ctx xs), Just _ <- stateStepsOf ctx kf -> do
        (ls, ctx', st) <- fuseFoldrState ctx t kf xs s0
        (ls ++) <$> genRun ctx' k (CApp z [CVar st (Inst [] []) tUnit])
  -- Iter.mapM_ over an Iter made right there
  CApp (CVar f _ _) [g0, xs0]
    | Just "rt_iterMapM_" <- foreignSym ctx f, let p = iterProdOf ctx xs0, iterKnown p, fusable p -> do
        (g, xs) <- renamed2 g0 xs0
        let c0 = noSelf ctx
        loop <- genLoop c0 (iterProdOf c0 xs) $ \c x -> case g of
          CLam [(v, _)] _ body -> ([mangle v ++ " := " ++ mangle x, "_ = " ++ mangle v] ++) <$> genRun (bindLocals c [(v, 0)]) RDiscard body
          _ -> genRun c RDiscard (CApp g [CVar x (Inst [] []) tUnit])
        rest <- genRun ctx k (CApp (CVar "primReturnIO" (Inst [tUnit] []) (TFun tUnit (tIO tUnit))) [CCon "()" [] tUnit])
        pure (["{"] ++ loop ++ ["}"] ++ rest)
  -- mapM_ and its kind over a list made only for it: a loop
  CApp (CVar "listFoldr" _ _) [kf, z, xs]
    | isTop ctx "listFoldr", fusable (prodOf ctx xs), Just _ <- ioStepsOf ctx kf -> do
        ls <- fuseFoldrIO ctx kf xs
        (ls ++) <$> genRun ctx k z

  CIf c a b _ -> case k of
    RBind x t -> onTheSpot x t
    RDiscard -> do
      c' <- genExpr ctx c
      as <- genRun ctx k a
      bs <- genRun ctx k b
      pure (["if " ++ c' ++ " {"] ++ as ++ ["} else {"] ++ bs ++ ["}"])
    RReturn _ -> do
      c' <- genExpr ctx c
      as <- genRun ctx k a
      bs <- genRun ctx k b
      pure (["if " ++ c' ++ " {"] ++ as ++ ["}"] ++ bs)
  CMatch ss rows t -> case k of
    RBind x xt -> onTheSpot x xt
    RDiscard -> do
      ls <- genMatch (\c -> genRun c (RReturn False)) (noSelf ctx) ss rows
      pure (["func() " ++ goTy ctx (fromMaybe tUnit (ioResult ctx t)) ++ " {"] ++ ls ++ ["}()"])
    RReturn _ -> genMatch (\c -> genRun c k) ctx ss rows
  CLet bs body _ -> case k of
    RBind x t -> onTheSpot x t
    RDiscard -> do
      (ctx', ls) <- genBinds ctx bs
      b <- genRun ctx' k body
      pure (["{"] ++ ls ++ b ++ ["}"])
    RReturn _ -> do
      (ctx', ls) <- genBinds ctx bs
      (ls ++) <$> genRun ctx' k body
  CForce x -> (\x' -> finish ("rt_run(" ++ x' ++ ".force())")) <$> genExpr ctx x
  CApp (CVar f ref _) args
    -- a tail call to one of the loop's functions: round the loop again, as it
    | RReturn True <- k, (from, loop) <- cxLoop ctx, Just (j, ns) <- M.lookup f loop, length args == length ns
    , sameInstance ref -> do
        as <- mapM (genExpr ctx) args
        when (j /= from) (modify (\s -> s {gsJumped = (from, j) : gsJumped s}))
        pure [commas ns ++ " = " ++ commas as, "hg_which = " ++ show j, "continue"]
    -- a tail call to itself: round the loop again
    | RReturn True <- k, Just (self, n) <- cxSelf ctx, f == self, length args == n, M.member f (cxRun ctx) -> do
        as <- mapM (genExpr ctx) args
        modify (\s -> s {gsLoop = True})
        pure [commas (map nextName (cxSelfParams ctx)) ++ " = " ++ commas as, "continue"]
    | Just (rn, n) <- M.lookup f (cxRun ctx), length args == n -> case k of
        RReturn True | S.member f (cxGroup ctx) -> trampolined
        _ -> do
          as <- mapM (genExpr ctx) args
          pure (finish (runCall ctx rn f ref as))
    | Just (VKForeign fo) <- M.lookup f (cxVars ctx), fArity fo == length args, fArity fo > 0, foreignIO fo -> do
        let targs = refTypes ctx ref
            (params, _) = splitFun (fArity fo) (foreignInst fo targs)
        as <- zipWith3M (foreignArg ctx (isRuntimeSymbol fo)) (fst (splitFun (fArity fo) (fType fo))) params args
        (ls, v) <- vectorAccess ctx fo targs as >>= maybe (pure (foreignRun ctx fo targs as)) pure
        pure (ls ++ finishValue v)
    | f `elem` ["putStrLn", "putStr"], isPrim ctx f, [a] <- args -> do
        a' <- genExpr ctx a
        pure (("rt_fmt." ++ (if f == "putStrLn" then "Println(" else "Print(") ++ a' ++ ")") : finishValue "struct{}{}")
  CVar f ref _
    | Just (VKForeign fo) <- M.lookup f (cxVars ctx), fArity fo == 0, foreignIO fo -> do
        let (ls, v) = foreignRun ctx fo (refTypes ctx ref) []
        pure (ls ++ finishValue v)
  _ -> trampolined
  where
    trampolined = (\e' -> finish ("rt_run(" ++ e' ++ ")")) <$> genExpr ctx e
    sameInstance = sameLoopInstance ctx
    finish v = case k of
      RReturn _ -> ["return " ++ v]
      RDiscard -> ["_ = " ++ v]
      RBind x _ -> [mangle x ++ " := " ++ v, "_ = " ++ mangle x]
    finishValue v = case k of
      RDiscard | v == "struct{}{}" -> []
      _ -> finish v
    -- statements run one after the other: in a block of their own, since
    -- they bind names, or in a Go function called on the spot when the
    -- result is bound to a name outside it
    sequenced stmts = case k of
      RBind x t -> onTheSpot x t
      _ -> (\ls -> ["{"] ++ ls ++ ["}"]) <$> runStmts ctx k stmts
    onTheSpot x t
      -- nothing to bind: () is ()
      | TCon "()" [] <- zonk (progSubst (cxProg ctx)) t = do
          ls <- genRun ctx RDiscard e
          pure (ls ++ [mangle x ++ " := struct{}{}", "_ = " ++ mangle x])
      | otherwise = do
          ls <- genRun (noSelf ctx) (RReturn False) e
          pure ([mangle x ++ " := func() " ++ goTy ctx t ++ " {"] ++ ls ++ ["}()", "_ = " ++ mangle x])

-- | The statements of a do block, run in order; the last one's result is
-- the block's.
runStmts :: Ctx -> RunK -> [CStmt] -> Gen [String]
runStmts ctx k = \case
  [] -> pure []
  [CSExpr _ e] -> genRun ctx k e
  CSExpr _ e : rest -> (++) <$> genRun ctx RDiscard e <*> runStmts ctx k rest
  CSBind "_" _ e : rest -> (++) <$> genRun ctx RDiscard e <*> runStmts ctx k rest
  CSBind x t e : rest -> (\a b -> a ++ unshare ctx x e rest ++ b) <$> genRun ctx (RBind x t) e <*> runStmts (bindLocals ctx [(x, 0)]) k rest
  CSLet bs : rest -> do
    (ctx', ls) <- genBinds ctx bs
    (ls ++) <$> runStmts ctx' k rest

-- Structures that stay in one thread ------------------------------------------------

-- A mutable vector or hash table made in IO, in a program that has threads,
-- takes a lock on each operation, since another thread could reach it. When
-- the action that makes it binds it to a variable that only the
-- operations of its module are given, in this action (its statements, the
-- binds and folds that run here, local functions it only calls), no other
-- thread can: it is unshared at once, and takes no lock.

-- | The statement that unshares x, bound to what e made, if what comes after
-- (rest) keeps it in this thread.
unshare :: Ctx -> Name -> CExpr -> [CStmt] -> [String]
unshare ctx x e rest = case madeBy ctx e of
  Just kind | confinedStmts ctx (S.singleton x) rest -> [kind ++ "(" ++ mangle x ++ ")"]
  _ -> []

-- | Whether e makes a new mutable vector or hash table: the unsharing
-- function, if so.
madeBy :: Ctx -> CExpr -> Maybe String
madeBy ctx e = case e of
  -- a bind gives what its last action gives (replicate, copied in, is a
  -- bind of primShared)
  CApp (CVar p _ _) [_, CLam [_] _ b] | p == "primBindIO", isPrim ctx p -> madeBy ctx b
  CApp (CVar p _ _) [_, b] | p == "primThenIO", isPrim ctx p -> madeBy ctx (case b of CDelay _ x -> x; _ -> b)
  CApp (CVar f _ _) _ -> byName f
  CVar f _ _ -> byName f
  _ -> Nothing
  where
    byName f
      | any (made f) ["Data.Vector.Mutable.replicate", "Data.Vector.Mutable.generate", "Data.Vector.Mutable.thaw", "Data.Vector.Mutable.fromList"]
          || foreignSym ctx f `elem` map Just ["rt_mvecReplicate", "rt_mvecGenerate", "rt_mvecThaw"] = Just "rt_mvecUnshare"
      | any (made f) ["Data.HashTable.new", "Data.HashTable.fromList"] || foreignSym ctx f == Just "rt_tableNew" = Just "rt_tableUnshare"
      | otherwise = Nothing
    made f base = f == base || (base ++ "__") `isPrefixOf` f

-- | An operation of the mutable structures' modules, which does nothing
-- with the structure but use it.
structOp :: Ctx -> Name -> Bool
structOp ctx f = any (`isPrefixOf` f) ["Data.Vector.Mutable.", "Data.HashTable."]
  || maybe False (\sym -> any (`isPrefixOf` sym) ["rt_mvec", "rt_table"]) (foreignSym ctx f)

-- | Whether the names in t (the structure, and the local functions that
-- use it) are used only where they stay in this thread.
confined :: Ctx -> S.Set Name -> CExpr -> Bool
confined ctx t e
  | not (mentions e) = True
  | otherwise = case e of
      CApp (CVar f _ _) args
        | structOp ctx f -> all (\a -> isT a || confined ctx t a) args
        | f `elem` ["primBindIO", "primThenIO"], isPrim ctx f -> all (confinedLam ctx t) args
        | f `elem` ["listFoldr", "listFoldl"], isTop ctx f -> all (confinedLam ctx t) args
        | S.member f t -> all (confined ctx t) args
        -- a function that keeps the parameters it is given here in the thread
        | Just flags <- M.lookup f (cxConfined ctx), length flags == length args ->
            and [if isT a then ok else confined ctx t a | (a, ok) <- zip args flags]
      CIf c a b _ -> all (confined ctx t) [c, a, b]
      -- a case may name the structure: the name is it too
      CMatch ss rows _ -> all (\sc -> isT sc || confined ctx t sc) ss && all (aliasRow ss) rows
      CLet bs b _ -> let (t', ok) = letNames ctx t bs in ok && confined ctx t' b
      CDo _ _ _ ss -> confinedStmts ctx t ss
      CForce x -> confined ctx t x
      CDelay _ x -> confined ctx t x
      _ -> False
  where
    mentions x = any (`S.member` t) (coreRefs x)
    isT = \case
      CVar v _ _ -> S.member v t
      _ -> False
    aliasRow ss r@(CRow pats _ _) =
      let names = [x | (sc, q) <- zip ss pats, isT sc, Just x <- [patName q]]
          plain = and [maybe False (const True) (patName q) || isWild q | (sc, q) <- zip ss pats, isT sc]
       in plain && rowIn (S.union t (S.fromList names)) r
    patName = \case
      CPVar x _ -> Just x
      _ -> Nothing
    isWild = \case
      CPWild -> True
      _ -> False
    rowIn t0 (CRow _ bs gs) =
      let (t', ok) = letNames ctx t0 bs
       in ok && all (\(g, b) -> maybe True (confined ctx t') g && confined ctx t' b) gs

-- | The names a group of local bindings adds to t, and whether the group
-- keeps them in the thread: a value that is only another name for one of
-- them is one too (lifting local functions makes such names), a local
-- function that uses them is tainted by them, and any other value must not
-- use them.
letNames :: Ctx -> S.Set Name -> [CBind] -> (S.Set Name, Bool)
letNames ctx t bs = (t', ok)
  where
    t' = grow t
    grow acc =
      let more = S.fromList ([n | CBind n _ 0 (CVar v _ _) <- bs, S.member v acc]
                               ++ [n | CBind n _ ar b <- bs, ar > 0, any (`S.member` acc) (coreRefs b)])
       in if more `S.isSubsetOf` acc then acc else grow (S.union acc more)
    ok = and [ if ar > 0 then confinedLam ctx t' b else alias b || not (any (`S.member` t') (coreRefs b))
             | CBind _ _ ar b <- bs ]
    alias = \case
      CVar v _ _ -> S.member v t'
      _ -> False

-- | The same for a lambda run here: a continuation, a fold's step, a local
-- function.
-- | For each top-level function, which of its parameters, mutable vectors or
-- hash tables, it keeps in the calling thread: the greatest such, since
-- functions call each other (all are first assumed to, then those that do
-- not are taken out until nothing changes).
confinedParams :: Ctx -> Program -> M.Map Name [Bool]
confinedParams ctx prog = go start
  where
    funs = [(tbName b, ps, inner) | b <- progBinds prog, CLam ps _ inner <- [tbBody b], length ps == tbArity b, tbArity b > 0]
    start = M.fromList [(n, map (structural . snd) ps) | (n, ps, _) <- funs]
    structural t = case zonk (progSubst prog) t of
      TCon c _ -> c `elem` ["Data.Vector.Mutable.MVector", "Data.HashTable.HashTable"]
      _ -> False
    go tbl =
      let c = ctx {cxConfined = tbl}
          tbl' = M.fromList [ (n, [flag && confined c (S.singleton p) inner | ((p, _), flag) <- zip ps (tbl M.! n)])
                            | (n, ps, inner) <- funs ]
       in if tbl' == tbl then tbl else go tbl'

confinedLam :: Ctx -> S.Set Name -> CExpr -> Bool
confinedLam ctx t = \case
  CLam _ _ b -> confinedLam ctx t b
  e -> confined ctx t e

confinedStmts :: Ctx -> S.Set Name -> [CStmt] -> Bool
confinedStmts ctx t = \case
  [] -> True
  CSExpr _ e : rest -> confined ctx t e && confinedStmts ctx t rest
  CSBind _ _ e : rest -> confined ctx t e && confinedStmts ctx t rest
  CSLet bs : rest -> let (t', ok) = letNames ctx t bs in ok && confinedStmts ctx t' rest

-- | A call to a run form.
runCall :: Ctx -> String -> Name -> VRef -> [String] -> String
runCall ctx rn x ref as = case M.lookup x (cxVars ctx) of
  Just (VKTop _ tps _) -> rn ++ insts tps ++ "(" ++ commas (dictArgs ctx ref ++ as) ++ ")"
  _ -> rn ++ "(" ++ commas as ++ ")"
  where
    insts tps = case ref of
      Inst ts _ -> typeArgs ctx ts
      SelfGroup -> if null tps then "" else "[" ++ commas (map tyVar (cxTParams ctx)) ++ "]"

-- Loops over lists ----------------------------------------------------------------

-- A list made only to be folded at once does not need to exist: sum (map f
-- (filter p [1 .. n])), length of a comprehension, mapM_ over a range. The
-- Prelude's folds (sum, length, maximum, any, elem, mapM_, forM_ and the
-- rest, once copied in) are listFoldl and listFoldr; when the list they fold
-- is made by the producers below, the fold is generated as Go loops that
-- visit its elements, nested for a comprehension, and no cell is made.
--
-- It computes what the list would have: every element a cell would hold is
-- computed, in the same order (map's even when the fold does not look at
-- it, since a cell's head is strict), and only as far as the fold goes (a
-- take, a takeWhile, or a fold that stops, like any, ends the loops). The
-- list is the argument of the fold, so nothing else can share it.

-- | How a list is made.
data Prod
  = PRange CExpr RangeStep (Maybe CExpr)
    -- ^ a range of Int, from where, by what step, up to where (or the end of
    -- Int): [a ..], [a .. b], [a, b ..], [a, b .. c]
  | PRangeDown CExpr Integer CExpr
    -- ^ the range [a, a + n .. c], from its last element back to a (see 'backwards')
  | PCells CExpr                  -- ^ any other list, whose cells are visited
  | PSeq CExpr                    -- ^ any other Iter, ranged over
  | PMap CExpr Prod
  | PFilter CExpr Prod
  | PTake CExpr Prod
  | PTakeWhile CExpr Prod
  | PDrop CExpr Prod
  | PDropWhile CExpr Prod
  | PRepeat CExpr
  | PIterate CExpr CExpr
  | PAppend Prod Prod
  | PIf CExpr Prod Prod
  | PLet [CBind] Prod
  | PMatch [CExpr] [CRow] (CExpr -> Prod)
    -- ^ a case whose bodies make the list, each body as the producer makes it
  | PNil
  | PCons CExpr Prod
  | PZip (Maybe CExpr) (Type, Type) Prod Prod
    -- ^ zipWith g xs ys, or zip xs ys (Nothing), with the types of the
    -- elements of each
  | PZip3 (Maybe CExpr) (Type, Type, Type) Prod Prod Prod
    -- ^ zipWith3 and zip3: the first list visited by its loops, the other
    -- two a step at a time
  | PFold Name Prod Step Prod
    -- ^ listFoldr (\x rest -> step) end src, as concatMap and comprehensions
    -- make it: for each x of src, the elements of step, then those of end

-- | A range's step, or its second element.
data RangeStep = By CExpr | Then CExpr

-- | What a step of a fold that makes a list gives before its rest.
data Step
  = SNext
  | SYield CExpr Step
  | SEach Prod Step
  | SIf CExpr Step Step
  | SLet [CBind] Step
  | SMatch [CExpr] [CRow] (CExpr -> Step)   -- ^ a case, and the step each body is
  | SStop Prod   -- ^ these elements, and the list ends: the step dropped its rest

-- | The type of an Iter's values.
iterElem :: Type -> Maybe Type
iterElem = \case
  TCon _ [el] -> Just el
  _ -> Nothing

isTop :: Ctx -> Name -> Bool
isTop ctx n = case M.lookup n (cxVars ctx) of
  Just VKTop {} -> True
  _ -> False

prodOf :: Ctx -> CExpr -> Prod
prodOf ctx e = case e of
  CApp (CVar f _ _) as | isTop ctx f -> case (f, as) of
    ("intsTo", [a, b, c]) -> PRange a (By b) (Just c)
    ("intsFrom", [a, b]) -> PRange a (By b) Nothing
    _ | f == enumInt "enumFrom", [a] <- as -> PRange a (By one) Nothing
      | f == enumInt "enumFromThen", [a, b] <- as -> PRange a (Then b) Nothing
      | f == enumInt "enumFromTo", [a, c] <- as -> PRange a (By one) (Just c)
      | f == enumInt "enumFromThenTo", [a, b, c] <- as -> PRange a (Then b) (Just c)
    ("map", [g, xs]) -> PMap g (prodOf ctx xs)
    ("filter", [q, xs]) -> PFilter q (prodOf ctx xs)
    ("take", [n, xs]) -> PTake n (prodOf ctx xs)
    ("takeWhile", [q, xs]) -> PTakeWhile q (prodOf ctx xs)
    ("drop", [n, xs]) -> PDrop n (prodOf ctx xs)
    ("dropWhile", [q, xs]) -> PDropWhile q (prodOf ctx xs)
    ("repeat", [x]) -> PRepeat x
    ("iterate", [g, x]) -> PIterate g x
    ("append", [xs, ys]) -> PAppend (prodOf ctx xs) (prodOf ctx (forced ys))
    ("zip", [xs, ys]) | Just tys <- elemTypes 0 -> PZip Nothing tys (prodOf ctx xs) (second xs ys)
    ("zipWith", [g, xs, ys]) | Just tys <- elemTypes 1 -> PZip (Just g) tys (prodOf ctx xs) (second xs ys)
    ("zip3", [xs, ys, zs]) | Just tys <- elemTypes3 0 -> PZip3 Nothing tys (prodOf ctx xs) (stepped ys) (stepped zs)
    ("zipWith3", [g, xs, ys, zs]) | Just tys <- elemTypes3 1 -> PZip3 (Just g) tys (prodOf ctx xs) (stepped ys) (stepped zs)
    ("listFoldr", [k, z, xs])
      | Just (x, r, body) <- lam2 k, Just st <- stepOf ctx r body -> PFold x (prodOf ctx xs) st (prodOf ctx z)
    _ -> PCells e
  CApp (CVar "primAppend" (Inst [TCon "[]" _] _) _) [xs, ys] | isPrim ctx "primAppend" ->
    PAppend (prodOf ctx xs) (prodOf ctx (forced ys))
  CCon "[]" _ _ -> PNil
  CApp (CCon ":" _ _) [h, t] -> PCons h (prodOf ctx (forced t))
  CIf c a b _ -> PIf c (prodOf ctx a) (prodOf ctx b)
  CLet bs b _ -> PLet bs (prodOf ctx b)
  CMatch ss rows _ -> PMatch ss rows (prodOf ctx)
  _ -> PCells e
  where
    forced t = case t of
      CDelay _ x -> x
      _ -> CForce t
    enumInt = instMethodName "inst_Enum_Int"
    one = CLit (LInt 1)
    -- the types of the elements of the two lists, after n other arguments
    elemTypes n = case e of
      CApp (CVar _ _ t) _ -> case fst (splitFun (n + 2) (zonk (progSubst (cxProg ctx)) t)) of
        ts | [TCon "[]" [a], TCon "[]" [b]] <- drop n ts -> Just (a, b)
        _ -> Nothing
      _ -> Nothing
    -- one of the two lists is visited a step at a time (see 'genPull'):
    -- when neither can be, the second is made, and its cells visited
    second xs ys
      | pullable (prodOf ctx ys) || pullable (prodOf ctx xs) = prodOf ctx ys
      | otherwise = PCells ys
    stepped ys = if pullable (prodOf ctx ys) then prodOf ctx ys else PCells ys
    elemTypes3 n = case e of
      CApp (CVar _ _ t) _ -> case fst (splitFun (n + 3) (zonk (progSubst (cxProg ctx)) t)) of
        ts | [TCon "[]" [a], TCon "[]" [b], TCon "[]" [c]] <- drop n ts -> Just (a, b, c)
        _ -> Nothing
      _ -> Nothing

-- | The Go function a foreign name calls.
foreignSym :: Ctx -> Name -> Maybe String
foreignSym ctx f = case M.lookup f (cxVars ctx) of
  Just (VKForeign fo) -> Just (fSymbol fo)
  _ -> Nothing

-- | How an Iter is made: Data.Iter's functions, known by the Go functions
-- they call, as for lists (see 'prodOf'). An Iter is Go's iter.Seq, a
-- function that gives each value to yield, so the same loops make one.
iterProdOf :: Ctx -> CExpr -> Prod
iterProdOf ctx e = case e of
  CApp (CVar f _ _) as | Just sym <- foreignSym ctx f -> case (sym, as) of
    ("rt_iterRange", [a, b]) -> PRange a (By (CLit (LInt 1))) (Just b)
    ("rt_iterFrom", [a]) -> PRange a (By (CLit (LInt 1))) Nothing
    ("rt_iterSingleton", [x]) -> PCons x PNil
    ("rt_iterMap", [g, xs]) -> PMap g (iterProdOf ctx xs)
    ("rt_iterFilter", [q, xs]) -> PFilter q (iterProdOf ctx xs)
    ("rt_iterTakeWhile", [q, xs]) -> PTakeWhile q (iterProdOf ctx xs)
    ("rt_iterTake", [n, xs]) -> PTake n (iterProdOf ctx xs)
    ("rt_iterDrop", [n, xs]) -> PDrop n (iterProdOf ctx xs)
    ("rt_iterDropWhile", [q, xs]) -> PDropWhile q (iterProdOf ctx xs)
    ("rt_iterRepeat", [x]) -> PRepeat x
    ("rt_iterIterate", [g, x]) -> PIterate g x
    ("rt_iterAppend", [a, b]) -> PAppend (iterProdOf ctx a) (iterProdOf ctx b)
    ("rt_iterFromList", [xs]) -> prodOf ctx xs
    ("rt_iterConcatMap", [CLam [(x, _)] _ body, xs]) -> PFold x (iterProdOf ctx xs) (SEach (iterProdOf ctx body) SNext) PNil
    _ -> PSeq e
  CVar f _ _ | Just "rt_iterEmpty" <- foreignSym ctx f -> PNil
  CIf c a b _ -> PIf c (iterProdOf ctx a) (iterProdOf ctx b)
  CLet bs b _ -> PLet bs (iterProdOf ctx b)
  CMatch ss rows _ -> PMatch ss rows (iterProdOf ctx)
  _ -> PSeq e

-- | Whether an Iter's own Go function is worth making: it binds values in
-- turn (a do), each of which would make an Iter of its own.
iterWorthIt :: Prod -> Bool
iterWorthIt = \case
  PFold {} -> True
  PMap _ q -> iterWorthIt q
  PFilter _ q -> iterWorthIt q
  PTake _ q -> iterWorthIt q
  PTakeWhile _ q -> iterWorthIt q
  PDrop _ q -> iterWorthIt q
  PDropWhile _ q -> iterWorthIt q
  PAppend a b -> iterWorthIt a || iterWorthIt b
  PIf _ a b -> iterWorthIt a || iterWorthIt b
  PLet _ q -> iterWorthIt q
  PMatch _ rows pf -> or [iterWorthIt (pf b) | CRow _ _ gs <- rows, (_, b) <- gs]
  _ -> False

-- | Whether a fold over the Iter is a loop worth making: it is not an Iter
-- whose source is not known.
iterKnown :: Prod -> Bool
iterKnown = \case
  PSeq _ -> False
  PLet _ q -> iterKnown q
  _ -> True

-- | A function of two arguments, as a lambda.
lam2 :: CExpr -> Maybe (Name, Name, CExpr)
lam2 = \case
  CLam [(x, _), (y, _)] _ b -> Just (x, y, b)
  CLam [(x, _)] _ (CLam [(y, _)] _ b) -> Just (x, y, b)
  _ -> Nothing

-- | The rest r is a suspension; a step uses it once, at its end.
isRest :: Name -> CExpr -> Bool
isRest r = \case
  CVar v _ _ -> v == r
  CDelay _ (CForce (CVar v _ _)) -> v == r
  _ -> False

stepOf :: Ctx -> Name -> CExpr -> Maybe Step
stepOf ctx r e = case e of
  _ | free e -> Just (SStop (prodOf ctx e))
  CForce (CVar v _ _) | v == r -> Just SNext
  CApp (CVar "append" _ _) [q, t] | isTop ctx "append", free q -> SEach (prodOf ctx q) <$> lazyStep t
  CApp (CVar "primAppend" (Inst [TCon "[]" _] _) _) [q, t] | isPrim ctx "primAppend", free q -> SEach (prodOf ctx q) <$> lazyStep t
  CApp (CCon ":" _ _) [h, t] | free h -> SYield h <$> lazyStep t
  CIf c a b _ | free c -> SIf c <$> stepOf ctx r a <*> stepOf ctx r b
  CLet bs b _ | all (\(CBind _ _ _ x) -> free x) bs -> SLet bs <$> stepOf ctx r b
  -- a case whose scrutinees, bindings and guards do not use the rest, as a
  -- comprehension's generator with a pattern makes
  CMatch ss rows _
    | all free ss, all rowFree rows
    , Just _ <- mapM (stepOf ctx r) [b | CRow _ _ gs <- rows, (_, b) <- gs] ->
        Just (SMatch ss rows (\b -> fromMaybe (error "stepOf: a body not of the case") (stepOf ctx r b)))
    where
      rowFree (CRow _ binds gs) = all (\(CBind _ _ _ x) -> free x) binds && all (maybe True free . fst) gs
  _ -> Nothing
  where
    free x = r `notElem` coreRefs x
    lazyStep t
      | isRest r t = Just SNext
      | CDelay _ x <- t = stepOf ctx r x
      | otherwise = Nothing

-- | Whether making the loops is not too much code: the fold's body is
-- copied where each element is made.
fusable :: Prod -> Bool
fusable p = sites p <= 8
  where
    sites = \case
      PNil -> 0
      PCons _ q -> 1 + sites q
      PAppend a b -> sites a + sites b
      PIf _ a b -> sites a + sites b
      PLet _ q -> sites q
      PMatch _ rows pf -> sum [sites (pf b) | CRow _ _ gs <- rows, (_, b) <- gs]
      PMap _ q -> sites q
      PFilter _ q -> sites q
      PTake _ q -> sites q
      PTakeWhile _ q -> sites q
      PDrop _ q -> sites q
      PDropWhile _ q -> sites q
      PZip _ _ a b -> sites a + sites b
      PZip3 _ _ a _ _ -> sites a
      PFold _ src st end -> sites src * max 1 (stepSites st) + sites end
      _ -> 1 :: Int
    stepSites = \case
      SNext -> 0
      SYield _ s -> 1 + stepSites s
      SEach q s -> sites q + stepSites s
      SIf _ a b -> stepSites a + stepSites b
      SLet _ s -> stepSites s
      SMatch _ rows sf -> sum [stepSites (sf b) | CRow _ _ gs <- rows, (_, b) <- gs]
      SStop q -> sites q

-- | Names bound by the expression made new, so that the loops, which bind
-- them in nested Go blocks, never hide a name of the code around.
renamed :: CExpr -> Gen CExpr
renamed = renameBinders $ \x -> do
  n <- gets gsNext
  modify (\s -> s {gsNext = n + 1})
  pure (takeWhile (`notElem` "#%") x ++ "%" ++ show n)

renamed2 :: CExpr -> CExpr -> Gen (CExpr, CExpr)
renamed2 a b = do
  r <- renamed (CApp a [b])
  pure $ case r of
    CApp a' [b'] -> (a', b')
    _ -> (a, b)

-- | The statements that visit each element of the list, given to k as a
-- variable bound in the context it gets. Each visit is a block of its own.
genLoop :: Ctx -> Prod -> (Ctx -> Name -> Gen [String]) -> Gen [String]
genLoop ctx p k = case p of
  PNil -> pure []
  PCons h t -> do
    (ls, c, y) <- bindNew ctx h
    b <- k c y
    rest <- genLoop ctx t k
    pure (["{"] ++ ls ++ b ++ ["}"] ++ rest)
  PRange a st l -> do
    i <- freshName "i"
    s' <- freshName "s"
    l' <- freshName "l"
    a' <- genExpr ctx a
    let v = mangle i
    step <- case st of
      By b -> (\b' -> s' ++ " := " ++ b') <$> genExpr ctx b
      Then b -> (\b' -> s' ++ " := " ++ b' ++ " - " ++ v) <$> genExpr ctx b
    limit <- case l of
      Just c -> (\c' -> [l' ++ " := " ++ c']) <$> genExpr ctx c
      Nothing -> pure [l' ++ " := -int(^uint(0)>>1) - 1", "if " ++ s' ++ " >= 0 {", l' ++ " = int(^uint(0) >> 1)", "}"]
    b <- visit (bindLocals ctx [(i, 0)]) i
    let up = s' ++ " >= 0"
        down = s' ++ " < 0"
    pure $
      [v ++ " := " ++ a', step] ++ limit ++
      [ "for ; ; " ++ v ++ " += " ++ s' ++ " {"
      , "if " ++ up ++ " && " ++ v ++ " > " ++ l' ++ " || " ++ down ++ " && " ++ v ++ " < " ++ l' ++ " {", "break", "}" ]
        ++ b ++
      -- the next one would be past the end of Int: the range stops, as intsTo does
      [ "if " ++ up ++ " && " ++ v ++ " > int(^uint(0)>>1)-" ++ s' ++ " || " ++ down ++ " && " ++ v ++ " < -int(^uint(0)>>1)-1-" ++ s' ++ " {", "break", "}"
      , "}" ]
  PRangeDown a n c -> do
    i <- freshName "i"
    a0 <- freshName "a"
    l' <- freshName "l"
    a' <- genExpr ctx a
    c' <- genExpr ctx c
    b <- visit (bindLocals ctx [(i, 0)]) i
    let v = mangle i
        m = show (abs n)
        -- the last element: a and as many steps as fit, counted in uint,
        -- where the distance between any two Ints fits
        (cond, dist, lastE, back) = if n > 0
          then (a0 ++ " <= " ++ l', "uint(" ++ l' ++ ") - uint(" ++ a0 ++ ")", a0 ++ " + int(", v ++ " -= " ++ m)
          else (a0 ++ " >= " ++ l', "uint(" ++ a0 ++ ") - uint(" ++ l' ++ ")", a0 ++ " - int(", v ++ " += " ++ m)
    pure $
      [a0 ++ " := " ++ a', l' ++ " := " ++ c', "if " ++ cond ++ " {"
      , v ++ " := " ++ lastE ++ "(" ++ dist ++ ") / " ++ m ++ " * " ++ m ++ ")"
      , "for ; ; " ++ back ++ " {" ]
        ++ b ++
      ["if " ++ v ++ " == " ++ a0 ++ " {", "break", "}", "}", "}"]
  PCells e -> do
    c <- freshName "c"
    x <- freshName "e"
    e' <- genExpr ctx e
    b <- k (bindLocals ctx [(x, 0)]) x
    pure (["for " ++ c ++ " := " ++ e' ++ "; " ++ c ++ " != nil; " ++ c ++ " = " ++ c ++ ".F1.force() {", mangle x ++ " := " ++ c ++ ".F0", "_ = " ++ mangle x] ++ b ++ ["}"])
  PSeq e -> do
    x <- freshName "e"
    e' <- genExpr ctx e
    b <- k (bindLocals ctx [(x, 0)]) x
    pure (["for " ++ mangle x ++ " := range " ++ e' ++ " {", "_ = " ++ mangle x] ++ b ++ ["}"])
  PMap g q -> genLoop ctx q $ \c x -> do
    (ls, c', y) <- applyNew c g [x]
    (ls ++) <$> k c' y
  PFilter f q -> genLoop ctx q $ \c x -> do
    (ls, c', y) <- applyNew c f [x]
    b <- k c' x
    pure (ls ++ ["if " ++ mangle y ++ " {"] ++ b ++ ["}"])
  PTake n q -> do
    cnt <- freshName "n"
    lab <- freshName "L"
    n' <- genExpr ctx n
    inner <- genLoop ctx q $ \c x -> do
      b <- k c x
      pure (b ++ [cnt ++ "--", "if " ++ cnt ++ " <= 0 {", "break " ++ lab, "}"])
    pure ([cnt ++ " := " ++ n', "if " ++ cnt ++ " > 0 {", lab ++ ":", "for {"] ++ inner ++ ["break", "}", "}"])
  PTakeWhile f q -> do
    lab <- freshName "L"
    inner <- genLoop ctx q $ \c x -> do
      (ls, c', y) <- applyNew c f [x]
      b <- k c' x
      pure (ls ++ ["if !" ++ mangle y ++ " {", "break " ++ lab, "}"] ++ b)
    pure ([lab ++ ":", "for {"] ++ inner ++ ["break", "}"])
  PDrop n q -> do
    cnt <- freshName "n"
    n' <- genExpr ctx n
    inner <- genLoop ctx q $ \c x -> do
      b <- k c x
      pure (["if " ++ cnt ++ " > 0 {", cnt ++ "--", "} else {"] ++ b ++ ["}"])
    pure (["{", cnt ++ " := " ++ n'] ++ inner ++ ["}"])
  -- dropWhile: the test is computed only while dropping
  PDropWhile f q -> do
    dropping <- freshName "dropping"
    inner <- genLoop ctx q $ \c x -> do
      (ls, _, y) <- applyNew c f [x]
      b <- k c x
      pure (["if " ++ dropping ++ " {"] ++ ls ++ ["if !" ++ mangle y ++ " {", dropping ++ " = false", "}", "}", "if !" ++ dropping ++ " {"] ++ b ++ ["}"])
    pure (["{", dropping ++ " := true"] ++ inner ++ ["}"])
  PRepeat e -> do
    (ls, c, y) <- bindNew ctx e
    b <- visit c y
    pure (["{"] ++ ls ++ ["for {"] ++ b ++ ["}", "}"])
  PIterate g x -> do
    (ls, c, v) <- bindNew ctx x
    b <- visit c v
    (ls', _, y) <- applyNew c g [v]
    pure (["{"] ++ ls ++ ["for {"] ++ b ++ ["{"] ++ ls' ++ [mangle v ++ " = " ++ mangle y, "}", "}", "}"])
  PAppend a b -> (++) <$> genLoop ctx a k <*> genLoop ctx b k
  PIf c a b -> do
    c' <- genExpr ctx c
    as <- genLoop ctx a k
    bs <- genLoop ctx b k
    pure (["if " ++ c' ++ " {"] ++ as ++ ["} else {"] ++ bs ++ ["}"])
  PLet bs q -> do
    (ctx', ls) <- genBinds ctx bs
    b <- genLoop ctx' q k
    pure (["{"] ++ ls ++ b ++ ["}"])
  -- each row's loops, then out of the case; no row matching is a failure
  PMatch ss rows pf -> do
    lab <- freshName "M"
    ls <- genMatch (\c b -> (++ ["break " ++ lab]) <$> genLoop c (pf b) k) ctx ss rows
    pure ([lab ++ ":", "for {"] ++ ls ++ ["}"])
  -- zip: one list visited by its loops, the other a step at a time; the
  -- first list's cell is reached before the second's, as zip does
  PZip g (ta, tb) a b -> do
    lab <- freshName "L"
    let end = "break " ++ lab
        pair c x y = case g of
          Just f -> applyNew c f [x, y]
          Nothing -> bindNew c (CApp (CCon "(,)" [ta, tb] (TFun ta (TFun tb (TCon "(,)" [ta, tb])))) [CVar x (Inst [] []) ta, CVar y (Inst [] []) tb])
    body <- if pullable b
      then do
        (initB, nextB) <- genPull ctx b
        inner <- genLoop ctx a $ \c x -> do
          (ls, c', y) <- nextB c end
          (ls', c'', z) <- pair c' x y
          (\kb -> ls ++ ls' ++ kb) <$> k c'' z
        pure (initB ++ inner)
      else do
        -- the first list a step ahead, so that its next cell is reached
        -- before the second's, and an empty one stops before the second's
        (initA, nextA) <- genPull ctx a
        cur <- freshName "x"
        (first, c0, x0) <- nextA ctx end
        inner <- genLoop c0 b $ \c y -> do
          (ls', c', z) <- pair (bindLocals c [(cur, 0)]) cur y
          kb <- k c' z
          (ls, _, x1) <- nextA c end
          pure (ls' ++ kb ++ ls ++ [mangle cur ++ " = " ++ mangle x1])
        pure (initA ++ first ++ [mangle cur ++ " := " ++ mangle x0, "_ = " ++ mangle cur] ++ inner)
    pure ([lab ++ ":", "for {"] ++ body ++ ["break " ++ lab, "}"])
  -- zip3: the first list's cell, then the second's, then the third's
  PZip3 g (ta, tb, tc) a b cq -> do
    lab <- freshName "L"
    let end = "break " ++ lab
    (initB, nextB) <- genPull ctx b
    (initC, nextC) <- genPull ctx cq
    inner <- genLoop ctx a $ \c x -> do
      (ls1, c1, y) <- nextB c end
      (ls2, c2, z) <- nextC c1 end
      (ls3, c3, w) <- case g of
        Just f -> applyNew c2 f [x, y, z]
        Nothing -> bindNew c2 (CApp (CCon "(,,)" [ta, tb, tc] (TFun ta (TFun tb (TFun tc (TCon "(,,)" [ta, tb, tc])))))
                                  [CVar x (Inst [] []) ta, CVar y (Inst [] []) tb, CVar z (Inst [] []) tc])
      (\kb -> ls1 ++ ls2 ++ ls3 ++ kb) <$> k c3 w
    pure ([lab ++ ":", "for {"] ++ initB ++ initC ++ inner ++ ["break " ++ lab, "}"])
  PFold x src st end
    | stops st -> do
        -- a step that drops its rest ends the whole list, the end too
        lab <- freshName "L"
        each <- genLoop ctx src $ \c e ->
          ([mangle x ++ " := " ++ mangle e, "_ = " ++ mangle x] ++) <$> genStep (bindLocals c [(x, 0)]) (Just lab) st k
        after <- genLoop ctx end k
        pure ([lab ++ ":", "for {"] ++ each ++ after ++ ["break " ++ lab, "}"])
    | otherwise -> do
        each <- genLoop ctx src $ \c e ->
          ([mangle x ++ " := " ++ mangle e, "_ = " ++ mangle x] ++) <$> genStep (bindLocals c [(x, 0)]) Nothing st k
        after <- genLoop ctx end k
        pure (each ++ after)
  where
    visit c x = (\b -> ["{"] ++ b ++ ["}"]) <$> k c x

-- | Lists that can be visited a step at a time, from outside a loop.
pullable :: Prod -> Bool
pullable = \case
  PRange {} -> True
  PCells _ -> True
  PRepeat _ -> True
  PIterate _ _ -> True
  PMap _ q -> pullable q
  _ -> False

-- | The statements that start visiting a list a step at a time, and a
-- function that makes those of each step: a variable holding the next
-- element, or the end statement where there is none. A list's next cell,
-- and iterate's next element, are reached only when the step asks for
-- them, as the list would.
genPull :: Ctx -> Prod -> Gen ([String], Ctx -> String -> Gen ([String], Ctx, Name))
genPull ctx p = case p of
  PRange a st l -> do
    cur <- freshName "cur"
    s' <- freshName "s"
    l' <- freshName "l"
    ok <- freshName "ok"
    a' <- genExpr ctx a
    step <- case st of
      By b -> (\b' -> s' ++ " := " ++ b') <$> genExpr ctx b
      Then b -> (\b' -> s' ++ " := " ++ b' ++ " - " ++ cur) <$> genExpr ctx b
    limit <- case l of
      Just c -> (\c' -> [l' ++ " := " ++ c']) <$> genExpr ctx c
      Nothing -> pure [l' ++ " := -int(^uint(0)>>1) - 1", "if " ++ s' ++ " >= 0 {", l' ++ " = int(^uint(0) >> 1)", "}"]
    let next c end = do
          y <- freshName "e"
          pure ( [ "if !" ++ ok ++ " || " ++ s' ++ " >= 0 && " ++ cur ++ " > " ++ l' ++ " || " ++ s' ++ " < 0 && " ++ cur ++ " < " ++ l' ++ " {", end, "}"
                 , mangle y ++ " := " ++ cur, "_ = " ++ mangle y
                 , "if " ++ s' ++ " >= 0 && " ++ cur ++ " > int(^uint(0)>>1)-" ++ s' ++ " || " ++ s' ++ " < 0 && " ++ cur ++ " < -int(^uint(0)>>1)-1-" ++ s' ++ " {"
                 , ok ++ " = false", "} else {", cur ++ " += " ++ s', "}" ]
               , bindLocals c [(y, 0)], y )
    pure ([cur ++ " := " ++ a', step] ++ limit ++ [ok ++ " := true", "_, _, _, _ = " ++ cur ++ ", " ++ s' ++ ", " ++ l' ++ ", " ++ ok], next)
  PCells e -> do
    cur <- freshName "cur"
    started <- freshName "started"
    e' <- genExpr ctx e
    let next c end = do
          y <- freshName "e"
          pure ( [ "if " ++ started ++ " {", cur ++ " = " ++ cur ++ ".F1.force()", "}", started ++ " = true"
                 , "if " ++ cur ++ " == nil {", end, "}", mangle y ++ " := " ++ cur ++ ".F0", "_ = " ++ mangle y ]
               , bindLocals c [(y, 0)], y )
    pure ([cur ++ " := " ++ e', started ++ " := false", "_, _ = " ++ cur ++ ", " ++ started], next)
  PRepeat e -> do
    (ls, _, v) <- bindNew ctx e
    pure (ls, \c _ -> pure ([], bindLocals c [(v, 0)], v))
  PIterate g x -> do
    (ls, _, v) <- bindNew ctx x
    started <- freshName "started"
    let next c0 _ = do
          let c = bindLocals c0 [(v, 0)]
          (ls', _, y) <- applyNew c g [v]
          pure (["if " ++ started ++ " {"] ++ ls' ++ [mangle v ++ " = " ++ mangle y, "}", started ++ " = true"], c, v)
    pure (ls ++ [started ++ " := false", "_ = " ++ started], next)
  PMap g q -> do
    (ls, nextQ) <- genPull ctx q
    let next c end = do
          (ls1, c1, x) <- nextQ c end
          (ls2, c2, y) <- applyNew c1 g [x]
          pure (ls1 ++ ls2, c2, y)
    pure (ls, next)
  _ -> error "genPull: not a list visited a step at a time"

-- | Whether a step can end the list.
stops :: Step -> Bool
stops = \case
  SStop _ -> True
  SYield _ s -> stops s
  SEach _ s -> stops s
  SIf _ a b -> stops a || stops b
  SLet _ s -> stops s
  SMatch _ rows sf -> or [stops (sf b) | CRow _ _ gs <- rows, (_, b) <- gs]
  SNext -> False

-- | A step's elements; lab is the label that ends the list, for a step
-- that drops its rest.
genStep :: Ctx -> Maybe String -> Step -> (Ctx -> Name -> Gen [String]) -> Gen [String]
genStep ctx lab st k = case st of
  SNext -> pure []
  SYield h s -> do
    (ls, c, y) <- bindNew ctx h
    b <- k c y
    rest <- genStep ctx lab s k
    pure (["{"] ++ ls ++ b ++ ["}"] ++ rest)
  SEach p s -> (++) <$> genLoop ctx p k <*> genStep ctx lab s k
  SIf c a b -> do
    c' <- genExpr ctx c
    as <- genStep ctx lab a k
    bs <- genStep ctx lab b k
    pure (["if " ++ c' ++ " {"] ++ as ++ ["} else {"] ++ bs ++ ["}"])
  SLet bs s -> do
    (ctx', ls) <- genBinds ctx bs
    b <- genStep ctx' lab s k
    pure (["{"] ++ ls ++ b ++ ["}"])
  SMatch ss rows sf -> do
    m <- freshName "M"
    ls <- genMatch (\c b -> (++ ["break " ++ m]) <$> genStep c lab (sf b) k) ctx ss rows
    pure ([m ++ ":", "for {"] ++ ls ++ ["}"])
  SStop p -> (++ maybe [] (\l -> ["break " ++ l]) lab) <$> genLoop ctx p k

-- | A new variable holding the value of e.
bindNew :: Ctx -> CExpr -> Gen ([String], Ctx, Name)
bindNew ctx e = do
  y <- freshName "e"
  e' <- genExpr ctx e
  pure ([mangle y ++ " := " ++ e', "_ = " ++ mangle y], bindLocals ctx [(y, 0)], y)

-- | A new variable holding g applied to variables: a lambda's parameters
-- are bound to them (its names are new, see 'renamed'), anything else is
-- called.
applyNew :: Ctx -> CExpr -> [Name] -> Gen ([String], Ctx, Name)
applyNew ctx g xs = case lamN (length xs) g of
  Just (ps, body) -> do
    let binds = concat [[mangle p ++ " := " ++ mangle x, "_ = " ++ mangle p] | (p, x) <- zip ps xs]
    (ls, c, y) <- bindNew (bindLocals ctx [(p, 0) | p <- ps]) body
    pure (binds ++ ls, c, y)
  Nothing -> bindNew ctx (CApp g [CVar x (Inst [] []) tUnit | x <- xs])
  where
    lamN 0 b = Just ([], b)
    lamN n (CLam ps _ b)
      | length ps <= n = (\(qs, b') -> (map fst ps ++ qs, b')) <$> lamN (n - length ps) b
    lamN _ _ = Nothing

-- | listFoldl g z xs: the accumulator, changed by each element.
fuseFoldl :: Ctx -> Type -> CExpr -> CExpr -> CExpr -> Gen String
fuseFoldl = fuseFoldlWith prodOf

fuseFoldlWith :: (Ctx -> CExpr -> Prod) -> Ctx -> Type -> CExpr -> CExpr -> CExpr -> Gen String
fuseFoldlWith prodFor ctx0 t g0 z xs0 = do
  (g1, xs) <- renamed2 g0 xs0
  let ctx = noSelf ctx0
      b = goTy ctx (snd (splitFun 3 t))
  acc <- freshName "acc"
  o <- freshName "o"
  z' <- genExpr ctx z
  -- a map built in place, with an owner of the loop's own (see Data.Map)
  let owned = ownedStep ctx g1
      g = if owned then giveOwner ctx o g1 else g1
      ctxA = bindLocals ctx [(acc, 0), (o, 0)]
  loop <- genLoop ctxA (prodFor ctx xs) $ \c x -> do
    (ls, _, y) <- applyNew c g [acc, x]
    pure (ls ++ [mangle acc ++ " = " ++ mangle y])
  pure $ "func() " ++ b ++ " {\nvar " ++ mangle acc ++ " " ++ b ++ " = " ++ z' ++ "\n"
    ++ (if owned then mangle o ++ " := rt_newOwner()\n" else "")
    ++ unlines loop
    ++ (if owned then "rt_endOwner(" ++ mangle o ++ ")\n" else "")
    ++ "return " ++ mangle acc ++ "\n}()"

-- | The step of a fold that changes its accumulator, a map, in place: an
-- operation of Data.Map that takes an owner, given none (insertWith,
-- insert and delete are those, given noOwner), whose map is the
-- accumulator, used nowhere else. The accumulator's earlier values are
-- then seen by no one, so the nodes the loop made can be changed. It may
-- be under a let or a case of a pair, as fromList's step is.
ownedStep :: Ctx -> CExpr -> Bool
ownedStep ctx g = case lam2 g of
  Just (acc, _, body) -> length [() | CVar v _ _ <- everything body, v == acc] == 1 && go acc body
  Nothing -> False
  where
    go acc = \case
      CApp (CVar f _ _) (CVar o _ _ : rest)
        | isTop ctx f, Just "rt_noOwner" <- foreignSym ctx o, not (null rest), CVar a _ _ <- last rest -> a == acc
      CLet bs b _ -> all (\(CBind _ _ _ x) -> acc `notElem` coreRefs x) bs && go acc b
      CMatch [sc] [CRow [p] [] [(Nothing, b)]] _ -> acc `notElem` coreRefs sc && irrefutable p && go acc b
      _ -> False
    irrefutable = \case
      CPVar _ _ -> True
      CPWild -> True
      CPCon c _ qs | Just _ <- tupleArity c -> all irrefutable qs
      _ -> False

-- | The step given the owner o in place of none.
giveOwner :: Ctx -> Name -> CExpr -> CExpr
giveOwner ctx o g = case g of
  CLam ps r b | length ps == 2 -> CLam ps r (go b)
  CLam ps r (CLam qs r' b) -> CLam ps r (CLam qs r' (go b))
  _ -> g
  where
    go = \case
      CApp f@(CVar _ _ _) (CVar n ref t : rest) | Just "rt_noOwner" <- foreignSym ctx n -> CApp f (CVar o ref t : rest)
      CLet bs b t -> CLet bs (go b) t
      CMatch ss [CRow ps bs [(Nothing, b)]] t -> CMatch ss [CRow ps bs [(Nothing, go b)]] t
      e -> e

-- | The step of a listFoldr whose rest is either the value (the fold goes
-- on) or not used (the fold stops with that value): any, all, elem, find,
-- and, or. The Prelude's && and || stop when they can.
exitsOf :: Ctx -> CExpr -> Maybe (Name, Name, CExpr)
exitsOf ctx k = case k of
  CVar op ref t | op `elem` ["&&", "||"], isTop ctx op ->
    Just ("hg_x", "hg_r", CApp (CVar op ref t) [CVar "hg_x" (Inst [] []) tBool, CVar "hg_r" (Inst [] []) tBool])
  _ | Just (x, r, body) <- lam2 k, exits r body -> Just (x, r, body)
  _ -> Nothing
  where
    exits r e = case e of
      _ | r `notElem` coreRefs e -> True
      CForce (CVar v _ _) -> v == r
      CApp (CVar op _ _) [a, b] | op `elem` ["&&", "||"], isTop ctx op -> isRest r b && r `notElem` coreRefs a
      CIf c a b _ -> r `notElem` coreRefs c && exits r a && exits r b
      CLet bs b _ -> all (\(CBind _ _ _ x) -> r `notElem` coreRefs x) bs && exits r b
      _ -> False

-- | Whether a step puts at most one element before its rest, as a
-- comprehension's does (see 'fuseFoldrLazy').
producer :: Step -> Bool
producer = \case
  SNext -> True
  SYield _ SNext -> True
  SIf _ a b -> producer a && producer b
  SLet _ s -> producer s
  SMatch _ rows sf -> and [producer (sf b) | CRow _ _ gs <- rows, (_, b) <- gs]
  _ -> False

-- | A foldr that makes a list that is kept, a comprehension's: a loop
-- over the cells that skips the elements the step drops, and for one it
-- keeps, a cell whose tail goes on with the loop from the next cell, when
-- it is forced. listFoldr would call the step's curried closure on every
-- element and suspend the rest of the fold for each, kept or not. The end
-- z is computed first, as listFoldr's argument is.
fuseFoldrLazy :: Ctx -> Type -> CExpr -> CExpr -> CExpr -> Gen String
fuseFoldrLazy ctx0 t k0 z xs0 = do
  (k, xs) <- renamed2 k0 xs0
  let ctx = noSelf ctx0
      (pts, res) = splitFun 3 (zonk (progSubst (cxProg ctx)) t)
  case (lam2 k, pts, res) of
    (Just (x, r, body), [_, _, srcT], TCon "[]" [_]) | Just st <- stepOf ctx r body -> do
      go <- freshName "go"
      c <- freshName "c"
      zv <- freshName "z"
      z' <- genExpr ctx z
      xs' <- genExpr ctx xs
      let ctx' = bindLocals ctx [(x, 0)]
          resT = goTy ctx res
          step c' = \case
            SNext -> pure []
            SYield h _ -> do
              h' <- genExpr c' h
              tl <- freshName "t"
              pure [ tl ++ " := " ++ c ++ ".F1"
                   , "return &Cons[" ++ goTy ctx (elemOf res) ++ "]{" ++ h' ++ ", rt_lazy(func() " ++ resT ++ " { return " ++ go ++ "(" ++ tl ++ ".force()) })}" ]
            SIf cond a b -> do
              cond' <- genExpr c' cond
              as <- step c' a
              bs <- step c' b
              pure (["if " ++ cond' ++ " {"] ++ as ++ ["} else {"] ++ bs ++ ["}"])
            SLet bs s -> do
              (c'', ls) <- genBinds c' bs
              b <- step c'' s
              pure (["{"] ++ ls ++ b ++ ["}"])
            SMatch ss rows sf -> do
              m <- freshName "M"
              ls <- genMatch (\c'' b -> (++ ["break " ++ m]) <$> step c'' (sf b)) c' ss rows
              pure ([m ++ ":", "for {"] ++ ls ++ ["}"])
            _ -> error "fuseFoldrLazy: not a step that makes one element"
      ls <- step ctx' st
      pure $ intercalate "\n" $
        [ "func() " ++ resT ++ " {"
        , zv ++ " := " ++ z'
        , "var " ++ go ++ " func(" ++ goTy ctx srcT ++ ") " ++ resT
        , go ++ " = func(" ++ c ++ " " ++ goTy ctx srcT ++ ") " ++ resT ++ " {"
        , "for ; " ++ c ++ " != nil; " ++ c ++ " = " ++ c ++ ".F1.force() {"
        , mangle x ++ " := " ++ c ++ ".F0", "_ = " ++ mangle x ]
        ++ ls ++
        [ "}", "return " ++ zv, "}", "return " ++ go ++ "(" ++ xs' ++ ")", "}()" ]
    _ -> error "fuseFoldrLazy: not a fold that makes a list"
  where
    elemOf = \case
      TCon "[]" [e] -> e
      _ -> error "fuseFoldrLazy: not a list"

fuseFoldr :: Ctx -> Type -> CExpr -> CExpr -> CExpr -> Gen String
fuseFoldr ctx0 t k0 z xs0 = do
  (k, xs) <- renamed2 k0 xs0
  let ctx = noSelf ctx0
  case exitsOf ctx k of
    Nothing -> error "fuseFoldr: not a fold that stops"
    Just (x, r, body) -> do
      loop <- genLoop ctx (prodOf ctx xs) $ \c e ->
        ([mangle x ++ " := " ++ mangle e, "_ = " ++ mangle x] ++) <$> exit r (bindLocals c [(x, 0)]) body
      end <- genStmts ctx z
      pure ("func() " ++ goTy ctx (snd (splitFun 3 t)) ++ " {\n" ++ unlines (loop ++ end) ++ "}()")
  where
    exit r c e = case e of
      _ | r `notElem` coreRefs e -> genStmts c e
      CForce _ -> pure []
      CApp (CVar op _ _) [a, _] -> do
        a' <- genExpr c a
        pure $ if op == "||"
          then ["if " ++ a' ++ " {", "return true", "}"]
          else ["if !(" ++ a' ++ ") {", "return false", "}"]
      CIf cond a b _ -> do
        cond' <- genExpr c cond
        as <- exit r c a
        bs <- exit r c b
        pure (["if " ++ cond' ++ " {"] ++ as ++ ["} else {"] ++ bs ++ ["}"])
      CLet bs b _ -> do
        (c', ls) <- genBinds c bs
        b' <- exit r c' b
        pure (["{"] ++ ls ++ b' ++ ["}"])
      _ -> error "fuseFoldr: not a step that stops"

-- | The step of a listFoldr that forces its rest once, whatever happens:
-- x + rest, max x rest, f x + rest, x `div` rest. It is recursion, not a
-- loop, but the elements can be kept and the step taken from the last one
-- back, without the Go stack and the suspension per element that the
-- Prelude's listFoldr takes. In the recursion, what the step computes
-- before it forces its rest is computed from the first element on (with
-- the elements, as the list's cells are made), and what it computes after,
-- from the last one back. So the first part is computed on the way
-- forward and kept with each element, unless it is total (it is then
-- computed on the way back, which nothing can tell), and the second on the
-- way back: everything happens in the recursion's order. The rest is
-- forced first where nothing comes before it but what is computed at once
-- (the function and earlier arguments of a call, the bindings before a
-- let's body, the condition of an if, the scrutinee of a case), not in a
-- branch, a lambda or a suspension; it may be used again after that,
-- anywhere, forced, since it is then the same value. The result: the
-- element's name, the rest's,
-- what is computed forward (names, types and expressions, in order), and
-- the step with those names for them.
strictStepOf :: Ctx -> CExpr -> Maybe (Name, Name, [(Name, Type, CExpr)], CExpr)
strictStepOf ctx k = case lam2 k of
  Just (x, r, body) | uses r body == forces r body, Just (_, hs, body') <- split x r (0 :: Int) body -> Just (x, r, hs, body')
  _ -> Nothing
  where
    uses r body = length [() | CVar v _ _ <- everything body, v == r]
    forces r body = length [() | CForce (CVar v _ _) <- everything body, v == r]
    mentions r e = r `elem` coreRefs e
    split x r n e = case e of
      CForce (CVar v _ _) | v == r -> Just (n, [], e)
      CApp f as
        | headOk f, (pts, _) <- splitFun (length as) (zonk (progSubst (cxProg ctx)) (headType f)), length pts == length as
        , (pre, a : post) <- break (mentions r) as -> do
            let (n', hs, pre') = hoist x n (zip pts pre)
            (n'', hs', a') <- split x r n' a
            Just (n'', hs ++ hs', CApp f (pre' ++ [a'] ++ post))
      CLet bs b t | all (\(CBind _ _ ar _) -> ar == 0) bs -> case break (\(CBind _ _ _ v) -> mentions r v) bs of
        (pre, []) -> do
          (n', hs, b') <- split x r n b
          Just (n', [(m, ty, v) | CBind m ty _ v <- pre] ++ hs, b')
        (pre, CBind m ty ar v : after) -> do
          (n', hs, v') <- split x r n v
          Just (n', [(m', ty', w) | CBind m' ty' _ w <- pre] ++ hs, CLet (CBind m ty ar v' : after) b t)
      CIf c a b t | mentions r c -> (\(n', hs, c') -> (n', hs, CIf c' a b t)) <$> split x r n c
      CMatch [sc] rows t | mentions r sc -> (\(n', hs, sc') -> (n', hs, CMatch [sc'] rows t)) <$> split x r n sc
      _ -> Nothing
    headOk = \case
      CVar {} -> True
      CCon {} -> True
      _ -> False
    headType = \case
      CVar _ _ t -> t
      CCon _ _ t -> t
      _ -> tUnit
    -- an argument computed before the rest: kept where it is if it is
    -- total, else computed forward, in a variable of its own
    hoist _ n [] = (n, [], [])
    hoist x n ((pt, a) : more)
      | totalExpr ctx a = let (n', hs, as) = hoist x n more in (n', hs, a : as)
      | otherwise =
          let h = x ++ "#h" ++ show n
              (n', hs, as) = hoist x (n + 1) more
           in (n', (h, pt, a) : hs, CVar h (Inst [] []) pt : as)

-- | An expression that cannot fail and has nothing to show: computing it
-- now or later, or not at all, is the same.
totalExpr :: Ctx -> CExpr -> Bool
totalExpr ctx = total
  where
    total = \case
      CVar {} -> True
      CLit _ -> True
      CNum {} -> True
      CFrac {} -> True
      CCon {} -> True
      CDelay {} -> True
      CLam {} -> True
      CApp (CCon {}) as -> all total as
      CApp (CVar p _ _) as | isPrim ctx p, p `elem` totalPrims -> all total as
      CApp (CVar op _ _) as | op `elem` ["&&", "||"], isTop ctx op -> all total as
      CIf c a b _ -> total c && total a && total b
      CLet bs b _ -> all (\(CBind _ _ _ x) -> total x) bs && total b
      CForce (CVar {}) -> True
      _ -> False
    totalPrims =
      [ "primAdd", "primSub", "primMul", "primNeg", "primEq", "primNeq", "primLt", "primLe", "primGt", "primGe"
      , "primIntToDouble", "primFDiv" ]

-- | Such a listFoldr: z, then the elements, each with what its step
-- computes forward, onto a stack, then the step from the last element
-- back, with the rest the value so far. The stack is in blocks, which are
-- never copied (a slice that doubles would leave the old ones to the
-- collector) and are let go on the way back. When nothing is computed
-- forward and the elements are a range whose step is known, they are
-- visited from the last back instead, and nothing is kept.
fuseFoldrBack :: Ctx -> Type -> CExpr -> CExpr -> CExpr -> Gen String
fuseFoldrBack ctx0 t k0 z xs0 = do
  (k, xs) <- renamed2 k0 xs0
  let ctx = noSelf ctx0
      (argTys, resTy) = splitFun 3 (zonk (progSubst (cxProg ctx)) t)
      elTy = case argTys of
        [_, _, TCon "[]" [a]] -> a
        _ -> tUnit
      b = goTy ctx resTy
  case strictStepOf ctx k of
    Nothing -> error "fuseFoldrBack: not a strict step"
    Just (x, r, hs, body) -> do
      acc <- freshName "acc"
      rv <- freshName "rest"
      z' <- genExpr ctx z
      let restIsVar = everywhere (\case
            CForce (CVar v _ _) | v == r -> CVar rv (Inst [] []) resTy
            other -> other)
          start = ["func() " ++ b ++ " {", "var " ++ mangle acc ++ " " ++ b ++ " = " ++ z']
          finish = ["return " ++ mangle acc, "}()"]
          -- the step, the element and what was computed forward bound; the
          -- rest in a variable of each round's, which closures may keep
          back c = do
            step <- genExpr (bindLocals c [(acc, 0), (rv, 0)]) (restIsVar body)
            pure [mangle rv ++ " := " ++ mangle acc, "_ = " ++ mangle rv, mangle acc ++ " = " ++ step]
      case backwards ctx (prodOf ctx xs) of
        Just p | null hs -> do
          loop <- genLoop ctx p $ \c e -> ([mangle x ++ " := " ++ mangle e, "_ = " ++ mangle x] ++) <$> back (bindLocals c [(x, 0)])
          pure (intercalate "\n" (start ++ loop ++ finish))
        _ -> do
          chunks <- freshName "chunks"
          top <- freshName "top"
          ci <- freshName "ci"
          ch <- freshName "ch"
          i <- freshName "i"
          el <- freshName "el"
          -- kept: what the way back uses, of the element and what was computed
          let used = coreRefs body
              fields = [(f, ft) | (f, ft) <- (x, elTy) : [(h, ht) | (h, ht, _) <- hs], f `elem` used]
              single = length fields == 1
              ty = if single then concat [goTy ctx ft | (_, ft) <- fields] else "struct{ " ++ intercalate "; " ["f" ++ show j ++ " " ++ goTy ctx ft | (j, (_, ft)) <- zip [0 :: Int ..] fields] ++ " }"
          loop <- genLoop ctx (prodOf ctx xs) $ \c e -> do
            (_, ls) <- foldM (\(cc, acc') (h, _, he) -> do
                he' <- genExpr cc he
                pure (bindLocals cc [(h, 0)], acc' ++ [mangle h ++ " := " ++ he', "_ = " ++ mangle h]))
              (bindLocals c [(x, 0)], [mangle x ++ " := " ++ mangle e, "_ = " ++ mangle x]) hs
            let v = if single then commas (map (mangle . fst) fields) else ty ++ "{" ++ commas (map (mangle . fst) fields) ++ "}"
            pure (ls ++
              [ "if len(" ++ top ++ ") == cap(" ++ top ++ ") {"
              , "if " ++ top ++ " != nil {", chunks ++ " = append(" ++ chunks ++ ", " ++ top ++ ")", "}"
              , top ++ " = make([]" ++ ty ++ ", 0, min(max(2*cap(" ++ top ++ "), 32), 16384))", "}"
              , top ++ " = append(" ++ top ++ ", " ++ v ++ ")" ])
          stepLs <- back (bindLocals ctx [(f, 0) | (f, _) <- fields])
          let unpack = if single
                then concat [[mangle f ++ " := " ++ ch ++ "[" ++ i ++ "]", "_ = " ++ mangle f] | (f, _) <- fields]
                else concat [[mangle f ++ " := " ++ el ++ ".f" ++ show j, "_ = " ++ mangle f] | (j, (f, _)) <- zip [0 :: Int ..] fields]
              getEl = if single then [] else [el ++ " := " ++ ch ++ "[" ++ i ++ "]"]
          pure $ intercalate "\n"
            ( start
                ++ ["var " ++ chunks ++ " [][]" ++ ty, "var " ++ top ++ " []" ++ ty]
                ++ loop
                ++ [ chunks ++ " = append(" ++ chunks ++ ", " ++ top ++ ")"
                   , "for " ++ ci ++ " := len(" ++ chunks ++ ") - 1; " ++ ci ++ " >= 0; " ++ ci ++ "-- {"
                   , ch ++ " := " ++ chunks ++ "[" ++ ci ++ "]", chunks ++ "[" ++ ci ++ "] = nil"
                   , "for " ++ i ++ " := len(" ++ ch ++ ") - 1; " ++ i ++ " >= 0; " ++ i ++ "-- {" ]
                ++ getEl ++ unpack ++ stepLs
                ++ ["}", "}"]
                ++ finish )

-- | The same elements, from the last back, when that can be done without
-- keeping them: a range whose end and step are known (the step a literal),
-- through maps and filters whose functions are total, since then the order
-- in which they are applied cannot be seen.
backwards :: Ctx -> Prod -> Maybe Prod
backwards ctx = \case
  PRange a (By st) (Just c) | Just n <- literal st, n /= 0, abs n < 2 ^ (62 :: Int) -> Just (PRangeDown a n c)
  PMap g q | totalFn g -> PMap g <$> backwards ctx q
  PFilter g q | totalFn g -> PFilter g <$> backwards ctx q
  _ -> Nothing
  where
    literal = \case
      CLit (LInt n) -> Just n
      CNum n _ _ -> Just n
      _ -> Nothing
    totalFn = \case
      CLam _ _ body -> totalExpr ctx body
      _ -> False

-- | The step of a listFoldr of actions that runs some and then its rest:
-- mapM_, forM_, traverse_, sequence_.
ioStepsOf :: Ctx -> CExpr -> Maybe (Name, Name, CExpr)
ioStepsOf ctx k = case lam2 k of
  Just (x, r, body) | steps r body -> Just (x, r, body)
  _ -> Nothing
  where
    steps r e = case e of
      CForce (CVar v _ _) -> v == r
      CApp (CVar "primBindIO" _ _) [m, CLam [_] _ b] | isPrim ctx "primBindIO" -> r `notElem` coreRefs m && steps r b
      CApp (CVar "primThenIO" _ _) [a, b] | isPrim ctx "primThenIO" ->
        r `notElem` coreRefs a && (isRest r b || case b of CDelay _ b' -> steps r b'; _ -> False)
      CIf c a b _ -> r `notElem` coreRefs c && steps r a && steps r b
      CLet bs b _ -> all (\(CBind _ _ _ x) -> r `notElem` coreRefs x) bs && steps r b
      CDo _ _ _ ss | Just _ <- ioResult ctx (tApp (doMonad e) tUnit), not (null ss) ->
        case last ss of
          CSExpr _ l -> steps r l && all (\st -> r `notElem` stmtRefs st) (init ss)
          _ -> False
      _ -> False
    doMonad (CDo m _ _ _) = m
    doMonad _ = tUnit
    stmtRefs = \case
      CSBind _ _ x -> coreRefs x
      CSExpr _ x -> coreRefs x
      CSLet bs -> concat [coreRefs x | CBind _ _ _ x <- bs]

-- | The loops of a listFoldr of actions, run: each element's actions, in
-- order. What comes after (the fold's last action) is the caller's.
fuseFoldrIO :: Ctx -> CExpr -> CExpr -> Gen [String]
fuseFoldrIO ctx0 k0 xs0 = do
  (k, xs) <- renamed2 k0 xs0
  let ctx = noSelf ctx0
  case ioStepsOf ctx k of
    Nothing -> error "fuseFoldrIO: not a fold of actions"
    Just (x, r, body) -> do
      loop <- genLoop ctx (prodOf ctx xs) $ \c e ->
        ([mangle x ++ " := " ++ mangle e, "_ = " ++ mangle x] ++) <$> run r (bindLocals c [(x, 0)]) body
      pure (["{"] ++ loop ++ ["}"])
  where
    run r c e = case e of
      CForce _ -> pure []
      CApp (CVar "primBindIO" _ _) [m, CLam [(v, vt)] _ b] -> (++) <$> genRun c (RBind v vt) m <*> run r (bindLocals c [(v, 0)]) b
      CApp (CVar "primThenIO" _ _) [a, b] -> do
        as <- genRun c RDiscard a
        bs <- if isRest r b then pure [] else case b of
          CDelay _ b' -> run r c b'
          _ -> pure []
        pure (as ++ bs)
      CIf cond a b _ -> do
        cond' <- genExpr c cond
        as <- run r c a
        bs <- run r c b
        pure (["if " ++ cond' ++ " {"] ++ as ++ ["} else {"] ++ bs ++ ["}"])
      CLet bs b _ -> do
        (c', ls) <- genBinds c bs
        b' <- run r c' b
        pure (["{"] ++ ls ++ b' ++ ["}"])
      CDo _ _ _ ss -> stmts c ss
      _ -> error "fuseFoldrIO: not a step of actions"
      where
        stmts c' = \case
          [] -> pure []
          [CSExpr _ l] -> run r c' l
          CSExpr _ a : rest -> (++) <$> genRun c' RDiscard a <*> stmts c' rest
          CSBind "_" _ a : rest -> (++) <$> genRun c' RDiscard a <*> stmts c' rest
          CSBind v vt a : rest -> (++) <$> genRun c' (RBind v vt) a <*> stmts (bindLocals c' [(v, 0)]) rest
          CSLet bs : rest -> do
            (c'', ls) <- genBinds c' bs
            (ls ++) <$> stmts c'' rest

-- | The step of a listFoldr of functions of a state that give an action:
-- \x rest s -> actions, then rest applied to the next state. StateT's mapM_
-- and forM_ over IO are this, once its newtype is gone and its >>= copied in.
stateStepsOf :: Ctx -> CExpr -> Maybe (Name, Name, Name, CExpr)
stateStepsOf ctx k = case lam3 k of
  Just (x, r, st, body) | steps r body -> Just (x, r, st, body)
  _ -> Nothing
  where
    lam3 = \case
      CLam [(x, _), (r, _), (st, _)] _ b -> Just (x, r, st, b)
      CLam [(x, _), (r, _)] _ (CLam [(st, _)] _ b) -> Just (x, r, st, b)
      CLam [(x, _)] _ (CLam [(r, _), (st, _)] _ b) -> Just (x, r, st, b)
      CLam [(x, _)] _ (CLam [(r, _)] _ (CLam [(st, _)] _ b)) -> Just (x, r, st, b)
      _ -> Nothing
    free r x = r `notElem` coreRefs x
    steps r e = case e of
      CApp (CForce (CVar v _ _)) [a] -> v == r && free r a
      CApp (CVar "primBindIO" _ _) [m, CLam [_] _ b] | isPrim ctx "primBindIO" -> free r m && steps r b
      CApp (CVar "primThenIO" _ _) [a, CDelay _ b] | isPrim ctx "primThenIO" -> free r a && steps r b
      CIf c a b _ -> free r c && steps r a && steps r b
      CLet bs b _ -> all (\(CBind _ _ _ x) -> free r x) bs && steps r b
      CMatch [sc] [CRow ps [] [(Nothing, b)]] _ -> free r sc && all irrefutable ps && steps r b
      _ -> False
    irrefutable = \case
      CPVar _ _ -> True
      CPWild -> True
      CPCon c _ qs | Just _ <- tupleArity c -> all irrefutable qs
      CPCon "()" _ _ -> True
      _ -> False

-- | The loops of such a fold: the state in a variable, each element's
-- actions run with it and leaving the next one in it. What comes after
-- (the fold's last function, applied to the state) is the caller's, given
-- the variable.
fuseFoldrState :: Ctx -> Type -> CExpr -> CExpr -> CExpr -> Gen ([String], Ctx, Name)
fuseFoldrState ctx0 t k0 xs0 s0 = do
  (k, xs) <- renamed2 k0 xs0
  let ctx = noSelf ctx0
      stTy = case snd (splitFun 3 (zonk (progSubst (cxProg ctx)) t)) of
        TFun a _ -> a
        other -> other
  st <- freshName "st"
  s0' <- genExpr ctx s0
  case stateStepsOf ctx k of
    Nothing -> error "fuseFoldrState: not a fold of a state"
    Just (x, r, sv, body) -> do
      let ctxS = bindLocals ctx [(st, 0)]
      loop <- genLoop ctxS (prodOf ctx xs) $ \c e ->
        ([mangle x ++ " := " ++ mangle e, "_ = " ++ mangle x, mangle sv ++ " := " ++ mangle st, "_ = " ++ mangle sv] ++)
          <$> step r st (bindLocals c [(x, 0), (sv, 0)]) body
      pure (["var " ++ mangle st ++ " " ++ goTy ctx stTy ++ " = " ++ s0', "{"] ++ loop ++ ["}"], bindLocals ctx0 [(st, 0)], st)
  where
    step r st c e = case e of
      CApp (CForce _) [a] -> (\a' -> [mangle st ++ " = " ++ a']) <$> genExpr c a
      CApp (CVar "primBindIO" _ _) [m, CLam [(v, vt)] _ b] -> (++) <$> genRun c (RBind v vt) m <*> step r st (bindLocals c [(v, 0)]) b
      CApp (CVar "primThenIO" _ _) [a, CDelay _ b] -> (++) <$> genRun c RDiscard a <*> step r st c b
      CIf cond a b _ -> do
        cond' <- genExpr c cond
        as <- step r st c a
        bs <- step r st c b
        pure (["if " ++ cond' ++ " {"] ++ as ++ ["} else {"] ++ bs ++ ["}"])
      CLet bs b _ -> do
        (c', ls) <- genBinds c bs
        b' <- step r st c' b
        pure (["{"] ++ ls ++ b' ++ ["}"])
      CMatch [sc] [CRow [pat] [] [(Nothing, b)]] _ -> do
        (ls, c', v) <- bindNew c sc
        b' <- genPats c' [(mangle v, pat)] (\c'' -> step r st c'' b)
        pure (["{"] ++ ls ++ b' ++ ["}"])
      _ -> error "fuseFoldrState: not a step of a state"

-- Literals ---------------------------------------------------------------------------

genLit :: Lit -> String
genLit = \case
  LInt n -> show n
  LDouble d -> show d
  LChar c
    | c == '\'' -> "'\\''"
    | c == '\\' -> "'\\\\'"
    | c >= ' ' && c <= '~' -> ['\'', c, '\'']
    | otherwise -> "rune(" ++ show (ord c) ++ ")"
  LStr s -> "\"" ++ concatMap esc s ++ "\""
  where
    esc '"' = "\\\""
    esc '\\' = "\\\\"
    esc '\n' = "\\n"
    esc '\t' = "\\t"
    esc c
      | c >= ' ' && c <= '~' = [c]
      | ord c < 0x10000 = "\\u" ++ pad 4 (showHex (ord c) "")
      | otherwise = "\\U" ++ pad 8 (showHex (ord c) "")
    pad n s = replicate (n - length s) '0' ++ s

-- | Every outermost type inside a value.
typesIn :: forall a. Data a => a -> [Type]
typesIn = go
  where
    go :: forall b. Data b => b -> [Type]
    go x = case eqT @b @Type of
      Just Refl -> [x]
      Nothing -> concat (gmapQ go x)
